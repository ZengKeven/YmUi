import { expect, test } from '@playwright/test'

const fixture = '/tests/fixture/message.html'
const stack = '.ym-message__stack'

test('inline slots override their fallback and the keyboard close button emits each event once', async ({ page }) => {
  await page.goto(fixture)
  const warning = page.locator('#slotted').getByRole('alert')
  await expect(warning.getByText('!', { exact: true })).toBeVisible()
  await expect(warning.locator('strong')).toHaveText('库存不足')
  await expect(warning).not.toContainText('后备')
  const close = warning.getByRole('button')
  await expect(close).toContainText('确认')
  await expect(close).toHaveAccessibleName('确认')
  await close.press('Enter')
  await expect(warning).toBeHidden()
  const events = await page.locator('#events').innerText()
  expect(events.split(',').sort()).toEqual(['click', 'close-click'])
  const plain = page.locator('#slotted').getByRole('status')
  await expect(plain).toHaveText('无图标')
  await expect(plain.locator('svg')).toHaveCount(0)
  await expect(plain.getByRole('button')).toHaveCount(0)
})

test('the default timer waits for hover and keyboard focus to leave, then closes once', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-01-01T12:00:00Z') })
  await page.goto(fixture)
  await page.clock.pauseAt(new Date('2026-01-01T12:01:00Z'))
  const start = page.getByRole('button', { name: '开始计时' })
  const panel = page.locator('#timed .ym-message')
  await start.click()
  await page.clock.runFor(1800)
  await panel.hover()
  await page.clock.runFor(3200)
  await expect(panel).toBeVisible()
  await panel.getByRole('button').focus()
  await start.hover()
  await page.clock.runFor(3200)
  await expect(panel).toBeVisible()
  await start.focus()
  await page.clock.runFor(2700)
  await expect(panel).toBeVisible()
  await page.clock.runFor(400)
  await expect(panel).toBeHidden()
  const events = await page.locator('#events').innerText()
  expect(events.split(',').sort()).toEqual(['duration-end', 'timeout'])
  await expect(page.getByText('无图标', { exact: true })).toBeVisible()
})

test('imperative shortcuts stack in call order, with independently dismissible handles and placements', async ({ page }) => {
  await page.goto(fixture)
  const top = page.locator(`${stack}[data-placement="top"]`)
  const bottom = page.locator(`${stack}[data-placement="bottom-right"]`)
  await page.getByRole('button', { name: '批量提示' }).click()
  const cards = top.locator('.ym-message')
  await expect(cards).toHaveText(['读取中', '已保存', '余额不足', '写入失败', '是否继续', '处理中'])
  await expect(top.getByRole('alert')).toHaveCount(2)
  await expect(top.getByRole('status').filter({ hasText: '已保存' })).toBeVisible()
  const first = (await cards.first().boundingBox())!
  const second = (await cards.nth(1).boundingBox())!
  expect(first.y + first.height).toBeLessThanOrEqual(second.y)
  expect(first.x + first.width / 2).toBeCloseTo(page.viewportSize()!.width / 2, 0)
  await expect(bottom).toHaveText('底部提示')
  expect((await bottom.locator('.ym-message').boundingBox())!.y).toBeGreaterThan(second.y)
  const close = page.getByRole('button', { name: '关闭首条' })
  await close.click()
  await close.click()
  await expect(cards).toHaveCount(5)
  await expect(page.locator('#api-events')).toHaveText('api')
  await page.getByRole('button', { name: '全部关闭' }).click()
  await expect(page.locator(stack)).toHaveCount(0)
  await close.click()
  await expect(page.locator('#api-events')).toHaveText('api')
  const shortcut = page.getByRole('button', { name: '快捷提示' })
  await shortcut.press('Enter')
  await expect(top.getByRole('status')).toHaveText('ad')
  await expect(shortcut).toBeFocused()
  await expect(top.locator('.ym-message')).toHaveCSS('border-radius', '7px')
})

test('body-mounted messages follow their source provider and allow a local size override', async ({ page }) => {
  await page.goto(fixture)
  await page.getByRole('button', { name: '打开指定来源的提示' }).click()
  const inline = page.locator('#source .ym-message')
  const inherited = page.locator(`${stack} .ym-message`).filter({ hasText: '外部挂载' })
  const local = page.locator(`${stack} .ym-message`).filter({ hasText: '显式尺寸' })
  await expect(inherited).toBeVisible()
  expect(await inherited.evaluate(el => !document.querySelector('#app')!.contains(el))).toBe(true)
  for (const panel of [inline, inherited]) {
    await expect(panel).toHaveCSS('border-radius', '7px')
    await expect(panel).toHaveCSS('background-color', 'rgb(237, 242, 248)')
    await expect(panel).toHaveCSS('color', 'rgb(35, 69, 103)')
  }
  await page.getByLabel('浅色背景').fill('#dde6ce')
  await expect(inherited).toHaveCSS('background-color', 'rgb(221, 230, 206)')
  await page.getByLabel('深色模式').check()
  await expect(inherited).toHaveCSS('background-color', 'rgb(40, 57, 74)')
  await expect(inherited).toHaveCSS('color', 'rgb(241, 229, 219)')
  await page.getByLabel('直角面板').check()
  await expect(inherited).toHaveCSS('border-radius', '0px')
  for (const [size, font] of [['extra-small', '11px'], ['small', '12px'], ['medium', '14px'], ['large', '16px']]) {
    await page.getByRole('combobox', { name: '消息尺寸' }).selectOption(size)
    await expect(inline).toHaveCSS('font-size', font)
    await expect(inherited).toHaveCSS('font-size', font)
    await expect(local).toHaveCSS('font-size', '12px')
  }
})

test('a shortcut timeout and a close button each release the last global entry once', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-01-01T12:00:00Z') })
  await page.goto(fixture)
  await page.clock.pauseAt(new Date('2026-01-01T12:01:00Z'))
  const launch = page.getByRole('button', { name: '限时反馈' })
  const events = page.locator('#api-events')
  const close = page.locator(stack).getByRole('button', { name: '知道了' })
  await launch.click()
  await expect(close).toBeVisible()
  await page.clock.runFor(900)
  await expect(page.locator(stack)).toHaveCount(0)
  expect((await events.innerText()).split(',').sort()).toEqual(['duration-end', 'timeout'])
  await launch.click()
  await close.press('Enter')
  await expect(page.locator(stack)).toHaveCount(0)
  await page.getByRole('button', { name: '关闭首条' }).click()
  await page.clock.runFor(900)
  expect((await events.innerText()).split(',').sort()).toEqual(['click', 'close-click', 'duration-end', 'timeout'])
})
