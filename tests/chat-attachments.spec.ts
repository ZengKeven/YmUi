test('an attachment-only draft honors sender restrictions and can select the same file again', async ({ page }) => {
  const sender = page.locator('#sender')
  const choose = sender.getByRole('button', { name: '选择附件' })
  const send = sender.getByRole('button', { name: '发送消息' })
  const field = sender.getByRole('textbox')
  const input = sender.locator('input[type=file]')
  await expect(page.locator('#text-only').getByRole('button', { name: '选择附件' })).toHaveCount(0)
  await expect(send).toBeDisabled()
  const chooser = page.waitForEvent('filechooser')
  await choose.click()
  await (await chooser).setFiles([photo, note])
  const image = sender.getByRole('img', { name: photo.name })
  const src = await image.evaluate((img: HTMLImageElement) => img.src)
  expect(src).toMatch(/^blob:/)
  await sender.getByRole('button', { name: '移除 签收.png' }).click()
  await expect(image).toHaveCount(0)
  await expect.poll(() => canReadUrl(page, src)).toBe(false)
  await sender.getByRole('button', { name: '移除 清单.txt' }).click()
  await expect(send).toBeDisabled()
  await input.setInputFiles(note)
  await expect(send).toBeEnabled()
  await sender.getByLabel('暂停发送').check()
  await expect(send).toBeDisabled()
  await field.press('Enter')
  await expect(sender.locator('#sent')).toBeEmpty()
  await sender.getByLabel('暂停发送').uncheck()
  await sender.getByLabel('禁用发送框').check()
  await expect(choose).toBeDisabled()
  await expect(send).toBeDisabled()
  await expect(sender.getByRole('button', { name: '移除 清单.txt' })).toHaveCount(0)
  await sender.getByLabel('禁用发送框').uncheck()
  await field.press('Enter')
  await expect(sender.locator('#sent')).toHaveText('["keydown","",[["清单.txt",true]]]')
  await expect(page.locator('#history').getByText(note.name, { exact: true })).toBeVisible()
  await expect(page.locator('#history .copy')).toBeEmpty()
})

test('a sent image outlives its draft and releases its preview when history is removed', async ({ page }) => {
  const sender = page.locator('#sender')
  await sender.locator('input[type=file]').setInputFiles([photo, note])
  const draftImage = sender.getByRole('img', { name: photo.name })
  const draftUrl = await draftImage.evaluate((img: HTMLImageElement) => img.src)
  await sender.getByRole('textbox').fill('到货凭证')
  await sender.getByRole('button', { name: '发送消息' }).click()
  await expect(sender.locator('#sent')).toHaveText('["click","到货凭证",[["签收.png",true],["清单.txt",true]]]')
  await expect(draftImage).toHaveCount(0)
  const message = page.locator('#history').getByRole('article')
  await expect(message.getByRole('listitem')).toHaveCount(2)
  await expect(message.locator('.copy')).toHaveText('到货凭证')
  await expect(message.getByRole('button', { name: /^移除 / })).toHaveCount(0)
  await expect.poll(() => canReadUrl(page, draftUrl)).toBe(false)
  await message.getByRole('button', { name: '预览 签收.png' }).click()
  const preview = page.getByRole('dialog').getByRole('img', { name: photo.name })
  await expect.poll(() => preview.evaluate((img: HTMLImageElement) => img.naturalWidth)).toBe(1)
  const historyUrl = await preview.evaluate((img: HTMLImageElement) => img.src)
  expect(await canReadUrl(page, historyUrl)).toBe(true)
  // 模拟预览期间业务清除历史，移除拥有该本地地址的消息。
  await page.locator('#clear-history').evaluate((button: HTMLButtonElement) => button.click())
  await expect(message).toHaveCount(0)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect.poll(() => canReadUrl(page, historyUrl)).toBe(false)
})

test('attachment cards and the image preview inherit live nested provider settings', async ({ page }) => {
  const card = page.locator('#inherited').getByRole('listitem')
  const local = page.locator('#local').getByRole('listitem')
  await expect(card).toHaveCSS('font-size', '16px')
  await expect(local).toHaveCSS('font-size', '12px')
  await expect(card).toHaveCSS('border-radius', '9px')
  await expect(card).toHaveCSS('border-top-color', 'rgb(82, 104, 123)')
  await page.getByLabel('边框颜色').fill('#aa6677')
  await expect(card).toHaveCSS('border-top-color', 'rgb(170, 102, 119)')
  await page.getByLabel('紧凑尺寸').check()
  await expect(card).toHaveCSS('font-size', '11px')
  await expect(local).toHaveCSS('font-size', '12px')
  await card.getByRole('button', { name: '预览 日历.png' }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toHaveCSS('background-color', 'rgb(240, 244, 248)')
  await expect(dialog).toHaveCSS('border-radius', '9px')
  for (const label of ['深色模式', '直角卡片']) {
    await page.getByLabel(label).evaluate((input: HTMLInputElement) => {
      input.checked = true
      input.dispatchEvent(new Event('change', { bubbles: true }))
    })
  }
  await expect(dialog).toHaveCSS('background-color', 'rgb(33, 50, 64)')
  await expect(dialog).toHaveCSS('border-radius', '0px')
  await dialog.getByRole('button', { name: '关闭预览' }).click()
  await expect(card).toHaveCSS('border-radius', '0px')
  await expect(card).toHaveCSS('border-top-color', 'rgb(170, 188, 204)')
})
