test('mixed attachments retain their order and request removal of the chosen duplicate', async ({ page }) => {
  const section = page.locator('#basic')
  const list = section.getByRole('list', { name: '附件列表' })
  const rows = list.getByRole('listitem')
  await expect(rows).toHaveCount(4)
  await expect(rows.nth(0)).toContainText('说明.txt')
  await expect(rows.nth(0)).toContainText('20 B')
  await expect(rows.nth(1)).toContainText('日历.png')
  await expect(rows.nth(1)).toContainText('2 KB')
  await expect(rows.nth(2)).toContainText('修订稿')
  await expect(rows.nth(2)).not.toContainText('70 B')
  await expect(rows.nth(3)).toContainText('待补原图.png')
  await expect(list.getByRole('button', { name: /^预览 / })).toHaveCount(1)
  await rows.nth(2).getByRole('button', { name: '移除 说明.txt' }).press('Enter')
  await expect(section.locator('#removed')).toHaveText('["second",2,"click"]')
  await expect(section.locator('#next')).toHaveText('first,photo,missing')
  await expect(rows).toHaveCount(4)
  await section.getByRole('button', { name: '接受移除' }).click()
  await expect(rows).toHaveCount(3)
  await expect(list.getByText('修订稿')).toHaveCount(0)
  await section.getByLabel('可移除').uncheck()
  await expect(list.getByRole('button', { name: /^移除 / })).toHaveCount(0)
})

test('a loaded image opens from the keyboard, returns focus, and respects imageViewer', async ({ page }) => {
  const section = page.locator('#basic')
  const open = section.getByRole('button', { name: '预览 日历.png' })
  await open.press('Enter')
  const dialog = page.getByRole('dialog', { name: '图片预览' })
  const image = dialog.getByRole('img', { name: '日历.png' })
  await expect.poll(() => image.evaluate((img: HTMLImageElement) => img.naturalWidth)).toBeGreaterThan(0)
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(open).toBeFocused()
  await section.getByLabel('允许预览').uncheck()
  await expect(open).toHaveCount(0)
  await expect(section.getByRole('img', { name: '日历.png' })).toBeVisible()
})

