import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.goto('/tests/fixture/chat-sender.html')
})

test('click and Enter send the current draft once, Shift+Enter inserts a newline', async ({ page }) => {
  const composer = page.locator('#composer')
  const field = composer.getByRole('textbox')
  const send = composer.getByRole('button', { name: '发送消息' })
  const sends = composer.locator('#sends')
  await expect(field).toHaveValue('')
  await expect(field).toHaveAttribute('placeholder', '输入消息')
  await expect(send).toBeDisabled()
  await field.fill('订单')
  await expect(composer.locator('#edits')).toHaveText('["input|订单"]')
  await send.click()
  await expect(composer.locator('#focus-events')).toHaveText('["focus|","blur|订单"]')
  await expect(sends).toHaveText('["click|订单"]')
  await expect(field).toHaveValue('订单')
  await field.press('End')
  await field.press('Shift+Enter')
  await expect(field).toHaveValue('订单\n')
  await expect(sends).toHaveText('["click|订单"]')
  await field.press('Enter')
  await expect(sends).toHaveText(JSON.stringify(['click|订单', 'keydown|订单\n']))
  await page.getByRole('button', { name: '载入草稿' }).click()
  await expect(field).toHaveValue('外部草稿')
  await expect(composer.locator('#draft')).toHaveText('外部草稿')
})

test('composition confirmation commits one change and only the next intentional Enter sends', async ({ page }) => {
  const field = page.locator('#composer').getByRole('textbox')
  const sends = page.locator('#sends')
  await field.fill('查')
  await field.evaluate((input: HTMLTextAreaElement) => {
    input.dispatchEvent(new CompositionEvent('compositionstart', { bubbles: true }))
    input.value = '查ding'
    input.dispatchEvent(new InputEvent('input', { bubbles: true, isComposing: true }))
    input.dispatchEvent(new KeyboardEvent('keydown', { bubbles: true, key: 'Enter', isComposing: true }))
    input.value = '查订'
    input.dispatchEvent(new CompositionEvent('compositionend', { bubbles: true, data: '订' }))
    input.dispatchEvent(new KeyboardEvent('keydown', { bubbles: true, key: 'Enter' }))
    input.dispatchEvent(new InputEvent('input', { bubbles: true, data: '订' }))
  })
  await expect(sends).toHaveText('[]')
  await expect(page.locator('#draft')).toHaveText('查订')
  await expect(page.locator('#edits')).toHaveText('["input|查","compositionend|查订"]')
  await field.press('Enter')
  await expect(sends).toHaveText('["keydown|查订"]')
})

test('loading, sendBtnDisabled and disabled guard keyboard and button actions consistently', async ({ page }) => {
  const composer = page.locator('#composer')
  const field = composer.getByRole('textbox')
  const send = composer.getByRole('button', { name: '发送消息' })
  const stop = composer.getByRole('button', { name: '停止生成' })
  await field.fill('查订单')
  await page.getByLabel('禁止发送').check()
  await expect(send).toBeDisabled()
  await field.press('Enter')
  await page.getByLabel('禁止发送').uncheck()
  await page.getByLabel('正在生成').check()
  await expect(send).toHaveCount(0)
  await field.press('Enter')
  await stop.click()
  await expect(composer.locator('#stops')).toHaveText('["click|查订单"]')
  await page.getByLabel('正在生成').uncheck()
  await page.getByLabel('显示停止按钮').check()
  await expect(stop).toBeEnabled()
  await field.press('Enter')
  await page.getByLabel('禁用发送框').check()
  await expect(field).toBeDisabled()
  await expect(stop).toBeDisabled()
  await page.getByLabel('显示停止按钮').uncheck()
  await expect(send).toBeDisabled()
  await expect(composer.locator('#sends')).toHaveText('[]')
})

test('an uncontrolled draft grows and shrinks within textareaProps bounds, and value can reject edits', async ({ page }) => {
  const composer = page.locator('#uncontrolled')
  const field = composer.getByRole('textbox')
  const height = () => field.evaluate(input => input.clientHeight)
  await expect(field).toHaveValue('初始草稿')
  const initial = await height()
  await field.fill('第一行\n第二行\n第三行')
  await expect.poll(height).toBeGreaterThan(initial)
  const maximum = await height()
  await field.fill('草稿\n'.repeat(10))
  await expect.poll(height).toBe(maximum)
  await field.fill('提问')
  await expect.poll(height).toBe(initial)
  await composer.getByRole('button', { name: '发送消息' }).click()
  await expect(page.locator('#sends')).toHaveText('["click|提问"]')
  const fixed = page.locator('#controlled')
  await fixed.getByRole('textbox').fill('编辑内容')
  await expect(fixed.locator('output')).toHaveText('编辑内容')
  await expect(fixed.getByRole('textbox')).toHaveValue('固定草稿')
})

test('the named value model syncs both ways and a native form reset restores the next sent draft', async ({ page }) => {
  const named = page.locator('#named-draft')
  const bound = named.getByRole('textbox')
  await expect(bound).toHaveValue('备选问题')
  await bound.fill('报价多少？')
  await expect(named.locator('output')).toHaveText('报价多少？')
  await named.getByRole('button', { name: '替换备选问题' }).click()
  await expect(bound).toHaveValue('下一条问题')

  const field = page.getByRole('textbox', { name: '待发送提问', exact: true })
  await expect(field).toHaveAttribute('id', 'question-draft')
  await field.fill('改写的草稿')
  await field.press('Enter')
  await expect(page.locator('#sends')).toHaveText('["keydown|改写的草稿"]')
  await page.getByRole('button', { name: '重置提问' }).click()
  await expect(field).toHaveValue('初始草稿')
  await field.press('Enter')
  await expect(page.locator('#sends')).toHaveText('["keydown|改写的草稿","keydown|初始草稿"]')
})

test('named slots render and custom actions honor the sender state', async ({ page }) => {
  const composer = page.locator('#slots')
  for (const label of ['草稿箱', '采购助手', '给采购组', '内部对话']) {
    await expect(composer.getByText(label, { exact: true })).toBeVisible()
  }
  await expect(composer.getByRole('button', { name: '发送消息' })).toHaveCount(0)
  const submit = composer.getByRole('button', { name: '提交提要' })
  await submit.click()
  await expect(page.locator('#sends')).toHaveText('["click|提要"]')
  await page.getByLabel('禁用发送框').check()
  await expect(submit).toHaveAttribute('aria-disabled', 'true')
  await submit.dispatchEvent('click')
  await expect(page.locator('#sends')).toHaveText('["click|提要"]')
  await page.getByLabel('禁用发送框').uncheck()
  await page.getByLabel('正在生成').check()
  await composer.getByRole('button', { name: '中断提要' }).click()
  await expect(page.locator('#stops')).toHaveText('["click|提要"]')
})

test('nested providers update the visible surface, radius and font, while the local size takes precedence', async ({ page }) => {
  const composer = page.locator('#inherited .ym-chat-sender')
  const local = page.locator('#local .ym-chat-sender')
  await expect(composer.getByRole('textbox')).toHaveCSS('font-size', '16px')
  await expect(local.getByRole('textbox')).toHaveCSS('font-size', '12px')
  await expect(composer).toHaveCSS('border-radius', '11px')
  await expect(composer).toHaveCSS('background-color', 'rgb(239, 239, 224)')
  await page.getByLabel('表面颜色').fill('#eeffee')
  await expect(composer).toHaveCSS('background-color', 'rgb(238, 255, 238)')
  await page.getByLabel('深色主题').check()
  await expect(local).toHaveCSS('background-color', 'rgb(39, 53, 73)')
  await page.getByLabel('紧凑尺寸').check()
  await expect(composer.getByRole('textbox')).toHaveCSS('font-size', '11px')
  await expect(local.getByRole('textbox')).toHaveCSS('font-size', '12px')
  await expect(composer).toHaveCSS('border-radius', '0px')
})
