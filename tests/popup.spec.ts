import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.goto('/tests/fixture/')
})

test('click and slot actions open and dismiss the popup once per interaction', async ({ page }) => {
  const anchor = page.getByRole('button', { name: '查看单据说明' })
  const outside = page.getByRole('button', { name: '浮层外按钮' })
  const panel = page.locator('.popup-click-panel:popover-open')
  await expect(anchor).toHaveAttribute('aria-expanded', 'false')
  await anchor.click()
  await expect(anchor).toHaveAttribute('aria-expanded', 'true')
  await expect(panel).toHaveAttribute('id', (await anchor.getAttribute('aria-controls'))!)
  await expect(panel).toHaveText('收起说明')
  await panel.getByRole('button', { name: '收起说明' }).click()
  await expect(panel).toBeHidden()
  await anchor.click()
  await anchor.click()
  await expect(panel).toBeHidden()
  await anchor.click()
  await outside.click()
  await expect(panel).toBeHidden()
  await expect(outside).toBeFocused()
  await page.getByLabel('禁用单据说明').check()
  await anchor.click({ force: true })
  await expect(panel).toBeHidden()
  await expect(page.locator('#popup-updates')).toHaveText('true,false,true,false,true,false')
  await expect(page.locator('#popup-changes')).toHaveText('true,false,true,false,true,false')
})

test('controlled visibility follows its owner and manual triggers respect the initial value', async ({ page }) => {
  const controlled = page.locator('.popup-controlled-panel:popover-open')
  const request = page.getByRole('button', { name: '请求显示受控说明' })
  await request.click()
  await expect(page.locator('#popup-updates')).toHaveText('true')
  await expect(controlled).toBeHidden()
  const toggle = page.getByRole('button', { name: '切换受控浮层' })
  await toggle.click()
  await expect(controlled).toHaveText('受控说明')
  await request.click()
  await expect(page.locator('#popup-updates')).toHaveText('true,false')
  await expect(controlled).toBeVisible()
  await toggle.click()
  await expect(controlled).toBeHidden()

  const manual = page.locator('.popup-manual-panel:popover-open')
  await page.getByRole('button', { name: '挂载手动浮层' }).click()
  await expect(manual).toHaveText('初始展开的说明')
  await page.getByRole('button', { name: '手动浮层锚点' }).click()
  await expect(manual).toBeVisible()
})

test('hover permits moving into the panel and keyboard dismissal returns to the anchor', async ({ page }) => {
  const anchor = page.getByRole('button', { name: '悬停查看备注' })
  const detail = page.getByRole('button', { name: '查看备注详情' })
  await anchor.hover()
  await expect(detail).toBeVisible()
  await detail.hover()
  await expect(detail).toBeVisible()
  await page.getByRole('button', { name: '浮层外按钮' }).hover()
  await expect(detail).toBeHidden()
  await anchor.focus()
  await expect(detail).toBeVisible()
  await page.keyboard.press('Tab')
  await expect(detail).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(detail).toBeHidden()
  await expect(anchor).toBeFocused()
})

test('the popup escapes clipping, flips at the viewport edge and follows a scrolling anchor', async ({ page }) => {
  await page.getByRole('button', { name: '打开定位用例' }).click()
  const anchor = page.getByRole('button', { name: '视口边缘触发器' })
  const panel = page.locator('.popup-position-panel:popover-open')
  await anchor.click()
  await expect(panel).toBeVisible()
  const first = (await panel.boundingBox())!
  const trigger = (await anchor.boundingBox())!
  expect(first.y + first.height).toBeLessThanOrEqual(trigger.y + 1)
  expect(first.y).toBeGreaterThanOrEqual(0)
  expect(await panel.evaluate(el => {
    const { left, top, width, height } = el.getBoundingClientRect()
    return el.contains(document.elementFromPoint(left + width / 2, top + height / 2))
  })).toBe(true)
  await page.locator('#popup-scroll-container').evaluate(el => { el.scrollLeft += 40 })
  await expect.poll(async () => Math.round(first.x - (await panel.boundingBox())!.x)).toBe(40)
})

test('open panels react to nested size, color, theme mode and radius settings', async ({ page }) => {
  await page.getByRole('button', { name: '显示全局配置浮层' }).click()
  const panel = page.locator('.popup-global-panel:popover-open')
  await expect(panel).toHaveCSS('font-size', '16px')
  await expect(panel).toHaveCSS('border-radius', '11px')
  await expect(panel).toHaveCSS('background-color', 'rgb(240, 242, 244)')
  await expect(panel).toHaveCSS('color', 'rgb(73, 49, 82)')
  await page.getByLabel('浮层浅色背景').fill('#d6e3f1')
  await expect(panel).toHaveCSS('background-color', 'rgb(214, 227, 241)')
  await page.getByLabel('浮层深色模式').check()
  await expect(panel).toHaveCSS('background-color', 'rgb(32, 37, 48)')
  await expect(panel).toHaveCSS('color', 'rgb(225, 226, 233)')
  await page.getByLabel('浮层紧凑配置').check()
  await expect(panel).toHaveCSS('font-size', '12px')
  await expect(panel).toHaveCSS('border-radius', '0px')
  await page.getByRole('button', { name: '显示局部尺寸浮层' }).click()
  const local = page.locator('.popup-local-panel:popover-open')
  await expect(local).toHaveCSS('font-size', '11px')
  await expect(local).toHaveCSS('background-color', 'rgb(32, 37, 48)')
})
