import { expect, test } from '@playwright/test'

test('a native submit fires once and stays focusable while loading', async ({ page }) => {
  await page.goto('/tests/fixture/')
  const submit = page.locator('#submit')
  const events = page.locator('#events')
  await expect(submit).toHaveAttribute('data-source', 'fixture')
  await expect(submit).toHaveClass(/from-parent/)
  await submit.click()
  await expect(events).toHaveText('1/1/1')
  await page.getByLabel('busy', { exact: true }).check()
  await expect(submit).toHaveAttribute('aria-busy', 'true')
  await expect(submit).not.toHaveAttribute('disabled')
  await submit.focus()
  await expect(submit).toBeFocused()
  await page.keyboard.press('Enter')
  await submit.dispatchEvent('click')
  await expect(events).toHaveText('1/1/1')
  await page.getByLabel('disabled', { exact: true }).check()
  await expect(submit).toBeDisabled()
  await page.getByLabel('name', { exact: true }).fill('changed')
  await page.locator('#reset').click()
  await expect(page.getByLabel('name', { exact: true })).toHaveValue('initial')
})

test('a disabled link blocks navigation and bubbling, and an explicit tag wins over href', async ({ page }) => {
  await page.goto('/tests/fixture/')
  const link = page.locator('#link')
  await expect(page.locator('a#link')).toHaveAttribute('href', '#destination')
  await page.getByLabel('disabled', { exact: true }).check()
  await expect(link).toHaveAttribute('tabindex', '-1')
  await link.dispatchEvent('click')
  const allowMiddleClick = await link.evaluate(el =>
    el.dispatchEvent(new MouseEvent('auxclick', { button: 1, bubbles: true, cancelable: true })),
  )
  expect(allowMiddleClick).toBe(false)
  await expect(page).not.toHaveURL(/#destination$/)
  await expect(page.locator('#events')).toHaveText('0/0/0')
  await page.getByLabel('disabled', { exact: true }).uncheck()
  await link.click()
  await expect(page).toHaveURL(/#destination$/)
  await page.getByLabel('custom tag').check()
  await expect(page.locator('div#link')).toHaveRole('button')
  await link.press('Enter')
  await link.press('Space')
  await expect(page.locator('#events')).toHaveText('3/0/3')
})

test('the default slot falls back to the content string, including with icons and loading', async ({ page }) => {
  await page.goto('/tests/fixture/')
  const plain = page.locator('#prop-label')
  await expect(plain).toHaveAccessibleName('保存')
  await expect(plain).toHaveAttribute('type', 'button')
  await expect(plain).toHaveAttribute('data-shape', 'rectangle')
  await expect(plain).toHaveAttribute('data-variant', 'base')
  await expect(plain).toHaveAttribute('data-theme', 'primary')
  await expect(page.locator('#slot-label')).toHaveAccessibleName('保存')
  const button = page.locator('#slots')
  const label = button.locator('.ym-button__text')
  await expect(label).toHaveText('default slot')
  await page.getByLabel('default slot').uncheck()
  await expect(label).toHaveText('保存')
  await page.getByLabel('button content').fill('已保存')
  await expect(label).toHaveText('已保存')
  await page.getByLabel('default slot').check()
  await expect(label).toHaveText('default slot')
  await page.getByLabel('busy', { exact: true }).check()
  await expect(button.locator('.ym-button__icon')).toHaveCount(0)
  await expect(button.getByRole('status')).toHaveText('waiting')
  await expect(button.locator('.ym-loading__spinner')).toHaveCSS('width', '19px')
  await expect(button.locator('.ym-button__suffix')).toHaveText('suffix')
  await page.getByLabel('busy', { exact: true }).uncheck()
  await expect(button.locator('.ym-button__icon')).toHaveText('icon')
})

test('partial nested palettes inherit other colors, and nested modes select their own palette', async ({ page }) => {
  await page.goto('/tests/fixture/')
  await expect(page.locator('#submit')).toHaveCSS('background-color', 'rgb(0, 110, 255)')
  await expect(page.locator('#inherited-brand')).toHaveCSS('background-color', 'rgb(136, 187, 238)')
  await expect(page.locator('#local-success')).toHaveCSS('background-color', 'rgb(117, 206, 157)')
  await expect(page.locator('#local-light')).toHaveCSS('background-color', 'rgb(34, 85, 136)')
  await expect(page.locator('#button-palette')).toHaveCSS('color', 'rgb(221, 238, 255)')
  await expect(page.locator('#local-success')).toHaveCSS('color', 'rgb(17, 34, 51)')
  await expect(page.locator('#local-light')).toHaveCSS('color', 'rgb(255, 255, 255)')
  await page.getByLabel('busy', { exact: true }).check()
  const spinner = page.locator('#inherited-brand .ym-loading__spinner path')
  await expect(spinner).toHaveCSS('fill', 'rgb(17, 34, 51)')
  await page.locator('#switch-mode').click()
  await expect(spinner).toHaveCSS('fill', 'rgb(255, 255, 255)')
  await expect(page.locator('#inherited-brand')).toHaveCSS('background-color', 'rgb(34, 85, 136)')
  await expect(page.locator('#local-success')).toHaveCSS('background-color', 'rgb(10, 191, 91)')
})
