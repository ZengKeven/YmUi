import { expect, test, type Locator, type Page } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.clock.setFixedTime(new Date('2026-10-01T12:00:00'))
  await page.goto('/tests/fixture/date-picker.html')
})

function rangeFields(page: Page, name: string) {
  const group = page.getByRole('group', { name, exact: true })
  return {
    start: group.getByRole('combobox', { name: '开始日期' }),
    end: group.getByRole('combobox', { name: '结束日期' }),
  }
}

function monthGrid(panel: Locator, year: number, month: number) {
  return panel.getByRole('grid', { name: `${year}年${month}月`, exact: true })
}

test('relative presets resolve only on activation and update both endpoints across midnight', async ({ page }) => {
  await page.clock.setFixedTime(new Date(2026, 11, 31, 23, 58))
  const fields = rangeFields(page, '配送范围')
  const panel = page.getByRole('dialog', { name: '选择日期范围' })
  const recent = panel.getByRole('button', { name: '近 3 天' })
  await fields.start.click()
  await expect(recent).toBeVisible()
  await expect(page.locator('#preset-calls')).toHaveText('0')
  await page.clock.setFixedTime(new Date(2027, 0, 1, 0, 2))
  await recent.press('Enter')
  await expect(panel).toBeHidden()
  await expect(fields.start).toBeFocused()
  await expect(fields.start).toHaveValue('2026-12-30')
  await expect(fields.end).toHaveValue('2027-01-01')
  const events = '[["2026-12-30","2027-01-01"]]'
  await expect(page.locator('#range-updates')).toHaveText(events)
  await expect(page.locator('#range-changes')).toHaveText(events)
  expect(await page.locator('#order').evaluate(el => new FormData(el as HTMLFormElement).get('window'))).toBe('2026-12-30 至 2027-01-01')
  await fields.end.click()
  await recent.click()
  await expect(panel).toBeHidden()
  await expect(page.locator('#range-changes')).toHaveText(events)
  await expect(page.locator('#preset-calls')).toHaveText('2')
})

