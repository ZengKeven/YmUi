test('choosing a date from the annotated calendar updates the model and form, and an external reset restores the placeholder', async ({ page }) => {
  const field = page.getByRole('combobox', { name: '收货日期' })
  const panel = page.getByRole('dialog', { name: '选择日期' })
  await expect(field).toHaveValue('2026-10-01')
  await expect(field).toHaveAttribute('readonly', '')
  await field.click()
  await expect(field).toHaveAttribute('aria-expanded', 'true')
  await expect(page.locator('.ym-calendar[data-theme="card"]')).toBeVisible()
  await expect(panel.getByRole('columnheader')).toHaveText(['日', '一', '二', '三', '四', '五', '六'])
  await expect(panel.getByRole('button', { name: '2026-10-01' })).toContainText('国庆节')
  await expect(panel.getByRole('button', { name: '2026-10-10' }).locator('.ym-calendar__badge')).toHaveText('班')
  await expect(panel.getByRole('button', { name: '2026-10-02' }).locator('.ym-calendar__lunar')).toBeVisible()
  await expect(panel.getByRole('button', { name: '2026-10-04' })).toBeDisabled()
  const stocktake = panel.getByRole('button', { name: '2026-10-03' })
  await expect(stocktake).toContainText('盘点日')
  await stocktake.click()
  await expect(panel).toBeHidden()
  await expect(field).toBeFocused()
  await expect(field).toHaveValue('2026-10-03')
  await expect(page.locator('#model')).toHaveText('2026-10-03')
  expect(await page.locator('form#order').evaluate(form => new FormData(form as HTMLFormElement).get('delivery'))).toBe('2026-10-03')
  await field.click()
  await stocktake.click()
  await expect(panel).toBeHidden()
  await expect(page.locator('#changes')).toHaveText('["2026-10-03"]')
  await expect(page.getByRole('button', { name: '清空日期' })).toHaveCount(0)
  await field.press('Backspace')
  await field.press('Delete')
  await expect(field).toHaveValue('2026-10-03')
  await page.getByRole('button', { name: '重置收货日期' }).click()
  await expect(field).toHaveValue('')
  await expect(field).toHaveAttribute('placeholder', '请选择日期')
  await expect(page.locator('#model')).toHaveText('空')
  await expect(page.locator('#updates')).toHaveText('["2026-10-03"]')
  await expect(page.locator('#changes')).toHaveText('["2026-10-03"]')
  await expect(panel).toBeHidden()
  await page.getByRole('button', { name: '变更收货日期' }).click()
  await expect(field).toHaveValue('2027-01-02')
  await field.click()
  await expect(panel.getByRole('button', { name: '2027-01-02' })).toHaveAttribute('aria-pressed', 'true')
})

test('keyboard selection starts at the current value or today, and dismissed browsing preserves the value', async ({ page }) => {
  const field = page.getByRole('combobox', { name: '空日期' })
  const panel = page.getByRole('dialog', { name: '选择日期' })
  await expect(field).toHaveAttribute('placeholder', '请选择日期')
  await field.press('ArrowDown')
  const today = panel.getByRole('button', { name: '2026-10-01' })
  await expect(today).toBeFocused()
  await expect(panel.locator('.ym-calendar__lunar, .ym-calendar__badge')).toHaveCount(0)
  await today.press('ArrowRight')
  await page.keyboard.press('Enter')
  await expect(field).toHaveValue('2026-10-02')
  await expect(field).toBeFocused()
  await field.press('Enter')
  await expect(panel.getByRole('button', { name: '2026-10-02' })).toBeFocused()
  await page.keyboard.press('PageDown')
  await expect(panel.getByRole('button', { name: '2026-11-02' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(panel).toBeHidden()
  await expect(field).toBeFocused()
  await expect(field).toHaveValue('2026-10-02')
  await field.press('Space')
  await expect(panel).toBeVisible()
  await page.keyboard.press('Tab')
  await expect(panel).toBeHidden()
  await field.click()
  await page.getByRole('button', { name: '外部操作' }).click()
  await expect(panel).toBeHidden()
  await expect(page.getByRole('combobox', { name: '禁用日期' })).toBeDisabled()
})

test('nested month menus keep the picker open and the owner controls committed values', async ({ page }) => {
  const field = page.getByRole('combobox', { name: '入库日期' })
  const panel = page.getByRole('dialog', { name: '选择日期' })
  await field.click()
  const toolbar = panel.locator('.ym-calendar__toolbar')
  const month = toolbar.getByRole('combobox', { name: '月份' })
  const year = toolbar.getByRole('combobox', { name: '年份' })
  await expect(month).toHaveValue('10 月')
  await expect(year).toHaveValue('2026')
  await month.press('Tab')
  await expect(year).toBeFocused()
  for (const name of ['上个月', '今天', '下个月']) {
    await page.keyboard.press('Tab')
    await expect(toolbar.getByRole('button', { name })).toBeFocused()
  }
  await toolbar.getByRole('button', { name: '上个月' }).click()
  await expect(month).toHaveValue('9 月')
  await toolbar.getByRole('button', { name: '今天' }).click()
  await expect(month).toHaveValue('10 月')
  await month.click()
  await page.getByRole('option', { name: '11 月', exact: true }).click()
  await expect(field).toHaveValue('2026-10-01')
  await panel.getByRole('button', { name: '2026-11-12' }).click()
  await expect(field).toHaveValue('2026-11-12')
  await page.locator('#order').evaluate(form => (form as HTMLFormElement).reset())
  await expect(field).toHaveValue('2026-10-01')
  const locked = page.getByRole('combobox', { name: '固定日期' })
  await locked.click()
  await panel.getByRole('button', { name: '2026-10-02' }).click()
  await expect(panel).toBeHidden()
  await expect(locked).toHaveValue('2026-10-01')
})

test('the trigger and externally attached calendar follow live nested configuration and local size', async ({ page }) => {
  const field = page.getByRole('combobox', { name: '继承配置' })
  const local = page.getByRole('combobox', { name: '局部尺寸' })
  const panel = page.locator('#date-overlays .ym-popup__panel').first()
  const next = panel.getByRole('button', { name: '下个月' })
  const selected = panel.getByRole('button', { name: '2026-10-01' })
  const localHeight = (await local.boundingBox())!.height
  expect((await field.boundingBox())!.height).toBeGreaterThan(localHeight)
  await field.click()
  await expect(next).toHaveCSS('height', '40px')
  await expect(panel).toHaveCSS('border-radius', '12px')
  await expect(panel).toHaveCSS('background-color', 'rgb(245, 240, 224)')
  await expect(selected).toHaveCSS('background-color', 'rgb(39, 93, 67)')
  // 更新 Provider 的配置时保持焦点在已打开的选择器内。
  await page.getByLabel('浅色背景').evaluate((input: HTMLInputElement) => {
    input.value = '#f2d9ba'
    input.dispatchEvent(new Event('input', { bubbles: true }))
  })
  await expect(panel).toHaveCSS('background-color', 'rgb(242, 217, 186)')
  await page.getByLabel('深色模式').evaluate(el => (el as HTMLInputElement).click())
  await expect(panel).toHaveCSS('background-color', 'rgb(41, 51, 73)')
  await expect(selected).toHaveCSS('background-color', 'rgb(156, 215, 182)')
  await page.getByLabel('紧凑尺寸和直角').evaluate(el => (el as HTMLInputElement).click())
  await expect(next).toHaveCSS('height', '24px')
  await expect(panel).toHaveCSS('border-radius', '0px')
  expect((await local.boundingBox())!.height).toBe(localHeight)
  await local.click()
  await expect(page.getByRole('dialog').getByRole('button', { name: '下个月' })).toHaveCSS('height', '20px')
})

test('range mode previews backwards across months and commits two ordered dates exactly once', async ({ page }) => {
  const field = page.getByRole('combobox', { name: '配送范围' })
  const panel = page.getByRole('dialog', { name: '选择日期范围' })
  const day = (value: string) => panel.getByRole('button', { name: value, exact: true })
  await expect(field).toHaveAttribute('placeholder', '请选择日期范围')
  await field.click()
  await expect(day('2026-10-01')).toContainText('国庆节')
  await panel.getByRole('button', { name: '下个月' }).click()
  await day('2026-11-03').click()
  await expect(panel).toBeVisible()
  await expect(page.locator('#range-model')).toHaveText('null')
  await expect(page.locator('#range-updates')).toHaveText('[]')
  await expect(page.locator('#range-changes')).toHaveText('[]')
  await panel.getByRole('button', { name: '上个月' }).click()
  await expect(day('2026-11-01')).toBeDisabled()
  await day('2026-11-01').dispatchEvent('click')
  await expect(panel).toBeVisible()
  await day('2026-10-30').hover()
  await expect(day('2026-10-31')).toHaveAttribute('data-range', 'inside')
  await day('2026-10-30').click()
  await expect(panel).toBeHidden()
  await expect(field).toBeFocused()
  await expect(field).toHaveValue('2026-10-30 至 2026-11-03')
  await expect(page.locator('#range-model')).toHaveText('["2026-10-30","2026-11-03"]')
  await expect(page.locator('#range-updates')).toHaveText('[["2026-10-30","2026-11-03"]]')
  await expect(page.locator('#range-changes')).toHaveText('[["2026-10-30","2026-11-03"]]')
  await field.click()
  await expect(day('2026-10-30')).toHaveAttribute('data-range', 'start')
  await expect(day('2026-11-03')).toHaveAttribute('data-range', 'end')
  const middle = panel.getByRole('gridcell').filter({ has: page.getByRole('button', { name: '2026-10-31' }) })
  await expect(middle).toHaveAttribute('aria-selected', 'true')
  await day('2026-10-30').click()
  await day('2026-11-03').click()
  await expect(panel).toBeHidden()
  await expect(page.locator('#range-updates')).toHaveText('[["2026-10-30","2026-11-03"]]')
  await expect(page.locator('#range-changes')).toHaveText('[["2026-10-30","2026-11-03"]]')
})

test('keyboard range selection can be cancelled or choose one day, with native reset and controlled ownership', async ({ page }) => {
  const field = page.getByRole('combobox', { name: '默认范围' })
  const panel = page.getByRole('dialog', { name: '选择日期范围' })
  const first = panel.getByRole('button', { name: '2026-10-01' })
  const original = '2026-10-01 至 2026-10-03'
  await field.press('ArrowDown')
  await expect(first).toBeFocused()
  await first.press('Enter')
  await page.keyboard.press('ArrowRight')
  await page.keyboard.press('ArrowRight')
  await expect(panel.getByRole('button', { name: '2026-10-02' })).toHaveAttribute('data-range', 'inside')
  await page.keyboard.press('Escape')
  await expect(panel).toBeHidden()
  await expect(field).toHaveValue(original)
  await field.press('Enter')
  await first.press('Space')
  await expect(panel).toBeVisible()
  await page.keyboard.press('Enter')
  await expect(field).toHaveValue('2026-10-01 至 2026-10-01')
  await field.click()
  await expect(first).toHaveAttribute('data-range', 'single')
  await page.locator('#order').evaluate(form => (form as HTMLFormElement).reset())
  await expect(panel).toBeHidden()
  await expect(field).toHaveValue(original)
  const locked = page.getByRole('combobox', { name: '固定范围' })
  await locked.click()
  await panel.getByRole('button', { name: '2026-10-07' }).click()
  await panel.getByRole('button', { name: '2026-10-12' }).click()
  await expect(panel).toBeHidden()
  await expect(locked).toHaveValue(original)
})

test('external values, disabling and switching modes discard an unfinished range', async ({ page }) => {
  const field = page.getByRole('combobox', { name: '配送范围' })
  const panel = page.getByRole('dialog', { name: '选择日期范围' })
  await field.click()
  await panel.getByRole('button', { name: '2026-10-02' }).click()
  // Change parent props without an outside pointer/focus event dismissing the draft first.
  await page.getByRole('button', { name: '外部设置范围' }).evaluate(el => (el as HTMLButtonElement).click())
  await expect(field).toHaveValue('2027-01-05 至 2027-01-09')
  if (!await panel.isVisible()) await field.click()
  await panel.getByRole('button', { name: '2027-01-08' }).click()
  await expect(panel).toBeVisible()
  await expect(page.locator('#range-changes')).toHaveText('[]')
  const disabled = page.getByLabel('禁用范围', { exact: true })
  await disabled.evaluate(el => (el as HTMLInputElement).click())
  await expect(panel).toBeHidden()
  await expect(field).toBeDisabled()
  await disabled.uncheck()
  await field.click()
  await panel.getByRole('button', { name: '2027-01-06' }).click()
  await expect(panel).toBeVisible()
  await page.getByRole('button', { name: '外部操作' }).click()
  await expect(field).toHaveValue('2027-01-05 至 2027-01-09')
  await page.getByRole('button', { name: '外部重置范围' }).click()
  await expect(field).toHaveValue('')
  const switchable = page.getByRole('combobox', { name: '切换模式的日期' })
  await switchable.click()
  await panel.getByRole('button', { name: '2026-10-05' }).click()
  await page.getByRole('button', { name: '切换选择模式' }).evaluate(el => (el as HTMLButtonElement).click())
  const single = page.getByRole('dialog', { name: '选择日期', exact: true })
  if (!await single.isVisible()) await switchable.click()
  await single.getByRole('button', { name: '2026-10-06' }).click()
  await expect(single).toBeHidden()
  await expect(switchable).toHaveValue('2026-10-06')
})

