import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.clock.setFixedTime(new Date('2026-10-01T12:00:00'))
  await page.goto('/tests/fixture/date-picker.html')
})

test('choosing a date from the annotated calendar updates the model and form, and clearing emits null', async ({ page }) => {
  const field = page.getByRole('combobox', { name: '收货日期' })
  const panel = page.getByRole('dialog', { name: '选择日期' })
  await expect(field).toHaveValue('2026-10-01')
  await expect(field).toHaveAttribute('readonly', '')
  await field.click()
  await expect(field).toHaveAttribute('aria-expanded', 'true')
  await expect(page.locator('.ym-calendar[data-theme="card"]')).toBeVisible()
  await expect(panel.getByRole('columnheader').first()).toHaveText('周日')
  await expect(panel.getByRole('button', { name: '2026-10-01' })).toContainText('国庆节')
  await expect(panel.getByRole('button', { name: '2026-10-10' }).locator('.ym-calendar__badge')).toHaveText('班')
  await expect(panel.getByRole('button', { name: '2026-10-02' }).locator('.ym-calendar__lunar')).toBeVisible()
  await expect(panel.getByRole('button', { name: '2026-10-04' })).toBeDisabled()
  const stocktake = panel.getByRole('button', { name: '2026-10-03' })
  await expect(stocktake).toContainText('盘点日')
  await stocktake.click()
  await expect(panel).toBeHidden()
  await expect(field).toBeFocused()
  await expect(field).toHaveValue('2026-10-03')
  await expect(page.locator('#model')).toHaveText('2026-10-03')
  expect(await page.locator('form#order').evaluate(form => new FormData(form as HTMLFormElement).get('delivery'))).toBe('2026-10-03')
  await field.click()
  await stocktake.click()
  await expect(panel).toBeHidden()
  await expect(page.locator('#changes')).toHaveText('["2026-10-03"]')
  await page.getByRole('button', { name: '清空日期' }).click()
  await expect(field).toHaveValue('')
  await expect(page.locator('#model')).toHaveText('空')
  await expect(page.locator('#updates')).toHaveText('["2026-10-03",null]')
  await expect(page.locator('#changes')).toHaveText('["2026-10-03",null]')
  await expect(page.locator('#clears')).toHaveText('1')
  await expect(panel).toBeHidden()
  await page.getByRole('button', { name: '变更收货日期' }).click()
  await expect(field).toHaveValue('2027-01-02')
  await field.click()
  await expect(panel.getByRole('button', { name: '2027-01-02' })).toHaveAttribute('aria-pressed', 'true')
})

test('keyboard selection starts at the current value or today, and dismissed browsing preserves the value', async ({ page }) => {
  const field = page.getByRole('combobox', { name: '空日期' })
  const panel = page.getByRole('dialog', { name: '选择日期' })
  await expect(field).toHaveAttribute('placeholder', '请选择日期')
  await field.press('ArrowDown')
  const today = panel.getByRole('button', { name: '2026-10-01' })
  await expect(today).toBeFocused()
  await expect(panel.locator('.ym-calendar__lunar, .ym-calendar__badge')).toHaveCount(0)
  await today.press('ArrowRight')
  await page.keyboard.press('Enter')
  await expect(field).toHaveValue('2026-10-02')
  await expect(field).toBeFocused()
  await field.press('Enter')
  await expect(panel.getByRole('button', { name: '2026-10-02' })).toBeFocused()
  await page.keyboard.press('PageDown')
  await expect(panel.getByRole('button', { name: '2026-11-02' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(panel).toBeHidden()
  await expect(field).toBeFocused()
  await expect(field).toHaveValue('2026-10-02')
  await field.press('Space')
  await expect(panel).toBeVisible()
  await page.keyboard.press('Tab')
  await expect(panel).toBeHidden()
  await field.click()
  await page.getByRole('button', { name: '外部操作' }).click()
  await expect(panel).toBeHidden()
  await expect(page.getByRole('combobox', { name: '禁用日期' })).toBeDisabled()
})

test('nested month menus keep the picker open and the owner controls committed values', async ({ page }) => {
  const field = page.getByRole('combobox', { name: '入库日期' })
  const panel = page.getByRole('dialog', { name: '选择日期' })
  await field.click()
  await panel.getByRole('combobox', { name: '月份' }).click()
  await page.getByRole('option', { name: '11月', exact: true }).click()
  await expect(field).toHaveValue('2026-10-01')
  await panel.getByRole('button', { name: '2026-11-12' }).click()
  await expect(field).toHaveValue('2026-11-12')
  await page.locator('#order').evaluate(form => (form as HTMLFormElement).reset())
  await expect(field).toHaveValue('2026-10-01')
  const locked = page.getByRole('combobox', { name: '固定日期' })
  await locked.click()
  await panel.getByRole('button', { name: '2026-10-02' }).click()
  await expect(panel).toBeHidden()
  await expect(locked).toHaveValue('2026-10-01')
})

test('the trigger and externally attached calendar follow live nested configuration and local size', async ({ page }) => {
  const field = page.getByRole('combobox', { name: '继承配置' })
  const local = page.getByRole('combobox', { name: '局部尺寸' })
  const panel = page.locator('#date-overlays .ym-popup__panel').first()
  const next = panel.getByRole('button', { name: '下个月' })
  const selected = panel.getByRole('button', { name: '2026-10-01' })
  const localHeight = (await local.boundingBox())!.height
  expect((await field.boundingBox())!.height).toBeGreaterThan(localHeight)
  await field.click()
  await expect(next).toHaveCSS('height', '40px')
  await expect(panel).toHaveCSS('border-radius', '12px')
  await expect(panel).toHaveCSS('background-color', 'rgb(245, 240, 224)')
  await expect(selected).toHaveCSS('background-color', 'rgb(39, 93, 67)')
  // 更新 Provider 的配置时保持焦点在已打开的选择器内。
  await page.getByLabel('浅色背景').evaluate((input: HTMLInputElement) => {
    input.value = '#f2d9ba'
    input.dispatchEvent(new Event('input', { bubbles: true }))
  })
  await expect(panel).toHaveCSS('background-color', 'rgb(242, 217, 186)')
  await page.getByLabel('深色模式').evaluate(el => (el as HTMLInputElement).click())
  await expect(panel).toHaveCSS('background-color', 'rgb(41, 51, 73)')
  await expect(selected).toHaveCSS('background-color', 'rgb(156, 215, 182)')
  await page.getByLabel('紧凑尺寸和直角').evaluate(el => (el as HTMLInputElement).click())
  await expect(next).toHaveCSS('height', '24px')
  await expect(panel).toHaveCSS('border-radius', '0px')
  expect((await local.boundingBox())!.height).toBe(localHeight)
  await local.click()
  await expect(page.getByRole('dialog').getByRole('button', { name: '下个月' })).toHaveCSS('height', '20px')
})
