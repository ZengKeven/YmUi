import { expect, test, type Locator } from '@playwright/test'

const fixture = '/tests/fixture/swiper.html'
const activeSlide = (swiper: Locator) => swiper.locator('.ym-swiper__item:not([aria-hidden="true"])')
const previous = (swiper: Locator) => swiper.getByRole('button', { name: '上一项', exact: true })
const next = (swiper: Locator) => swiper.getByRole('button', { name: '下一项', exact: true })
const indicator = (swiper: Locator, n: number) => swiper.getByRole('button', { name: `转到第 ${n} 项`, exact: true })

test('arrows wrap, indicators select slides and keyboard input remains usable inside a slide', async ({ page }) => {
  await page.goto(fixture)
  const region = page.locator('#basic')
  await expect(region).toHaveRole('region')
  await expect(activeSlide(region)).toContainText('订单')
  const orderNote = region.getByRole('textbox', { name: '订单备注' })
  await orderNote.fill('保留草稿')
  await orderNote.press('ArrowLeft')
  await expect(page.locator('#changes')).toHaveText('[]')
  await previous(region).click()
  await expect(activeSlide(region)).toContainText('结算')
  await next(region).click()
  await expect(orderNote).toHaveValue('保留草稿')
  await indicator(region, 2).click()
  await expect(indicator(region, 2)).toHaveAttribute('aria-current', 'true')
  await expect(activeSlide(region)).toContainText('收货')
  await expect(page.locator('#updates')).toHaveText('[2,0,1]')
  await expect(page.locator('#changes')).toHaveText('["2:click","0:click","1:click"]')
  const inactive = region.locator('.ym-swiper__item[aria-hidden="true"]')
  await expect(inactive).toHaveCount(2)
  for (const slide of await inactive.all()) expect(await slide.evaluate(el => (el as HTMLElement).inert)).toBe(true)
  await page.getByRole('combobox', { name: '触发' }).selectOption('hover')
  await indicator(region, 1).hover()
  await expect(activeSlide(region)).toContainText('订单')
  await expect(page.locator('#changes')).toContainText('0:hover')
})

