test('forward wrap slides the first panel in from the right and a new selection interrupts the transition', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto(fixture)
  const region = page.locator('#basic')
  const viewport = region.locator('.ym-swiper__viewport')
  const slides = viewport.locator('.ym-swiper__item')
  await indicator(region, 3).click()
  await page.getByRole('spinbutton', { name: '动画时长' }).fill('2000')
  await next(region).click()
  await expect(activeSlide(region)).toContainText('订单')
  await viewport.evaluate(async el => {
    const animations = el.getAnimations({ subtree: true })
    await Promise.all(animations.map(animation => {
      animation.pause()
      return animation.ready
    }))
    for (const animation of animations) animation.currentTime = 1000
  })
  const view = (await viewport.boundingBox())!
  const incoming = (await slides.first().boundingBox())!
  const outgoing = (await slides.last().boundingBox())!
  expect((incoming.x - view.x) / view.width).toBeCloseTo(.5, 1)
  expect((outgoing.x - view.x) / view.width).toBeCloseTo(-.5, 1)

  await indicator(region, 2).click()
  await expect(activeSlide(region)).toContainText('收货')
  await expect(slides.last()).toBeHidden()
  await viewport.evaluate(async el => {
    await Promise.all(el.getAnimations({ subtree: true }).map(animation => {
      animation.finish()
      return animation.finished
    }))
  })
  await expect(slides.first()).toBeHidden()
  await expect(slides.last()).toBeHidden()
  expect((await activeSlide(region).boundingBox())!.x).toBeCloseTo(view.x, 1)
  await expect(indicator(region, 2)).toHaveAttribute('aria-current', 'true')
})

test('autoplay waits a full interval, pauses for hover and focus, and ends on the last slide', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.clock.install({ time: new Date('2026-01-01T12:00:00Z') })
  await page.goto(fixture)
  const timed = page.locator('#timed')
  await expect(activeSlide(timed)).toHaveText('一')
  await page.clock.pauseAt(new Date('2026-01-01T12:01:00Z'))
  await page.getByRole('checkbox', { name: '自动播放' }).check()
  await timed.hover()
  await page.clock.runFor(1500)
  await expect(activeSlide(timed)).toHaveText('一')
  await page.mouse.move(0, 0)
  await page.clock.runFor(1000)
  await expect(activeSlide(timed)).toHaveText('二')
  await next(timed).focus()
  await page.clock.runFor(2000)
  await expect(activeSlide(timed)).toHaveText('二')
  await page.getByRole('checkbox', { name: '自动播放' }).focus()
  await page.clock.runFor(1000)
  await expect(activeSlide(timed)).toHaveText('三')
  await page.clock.runFor(2500)
  await expect(page.locator('#automatic-changes')).toHaveText('["1:autoplay","2:autoplay"]')
})

test('touch gestures select along the active axis and leave short or cross-axis gestures alone', async ({ page }) => {
  await page.goto(fixture)
  const region = page.locator('#basic')
  const swipe = (dx: number, dy: number) => activeSlide(region).evaluate((slide, delta) => {
    const point = (x: number, y: number) => new Touch({ identifier: 1, target: slide, clientX: x, clientY: y })
    const from = point(120, 90)
    const to = point(120 + delta.dx, 90 + delta.dy)
    slide.dispatchEvent(new TouchEvent('touchstart', { bubbles: true, touches: [from], changedTouches: [from] }))
    slide.dispatchEvent(new TouchEvent('touchend', { bubbles: true, touches: [], changedTouches: [to] }))
  }, { dx, dy })
  await swipe(-16, 0)
  await swipe(-60, -90)
  await expect(page.locator('#changes')).toHaveText('[]')
  await swipe(-75, 6)
  await expect(activeSlide(region)).toContainText('收货')
  await page.getByRole('combobox', { name: '方向' }).selectOption('vertical')
  await swipe(80, 2)
  await expect(activeSlide(region)).toContainText('收货')
  await swipe(4, -75)
  await expect(activeSlide(region)).toContainText('结算')
  await expect(page.locator('#changes')).toHaveText('["1:touch","2:touch"]')
})

test('nested provider sizes, palette, mode and zero radius update the rendered controls', async ({ page }) => {
  await page.goto(fixture)
  const region = page.locator('#basic')
  const localArrow = previous(page.locator('#local'))
  const size = page.getByRole('combobox', { name: '全局尺寸' })
  const localWidth = (await localArrow.boundingBox())!.width
  let lastWidth = 0
  for (const value of ['extra-small', 'small', 'medium', 'large']) {
    await size.selectOption(value)
    const width = (await previous(region).boundingBox())!.width
    expect(width).toBeGreaterThan(lastWidth)
    expect((await localArrow.boundingBox())!.width).toBe(localWidth)
    lastWidth = width
  }
  const viewport = region.locator('.ym-swiper__viewport')
  await expect(viewport).toHaveCSS('border-top-left-radius', '5px')
  await page.getByRole('checkbox', { name: '直角' }).check()
  await expect(viewport).toHaveCSS('border-top-left-radius', '0px')
  const selected = indicator(region, 1)
  const activeColor = () => selected.evaluate(el => getComputedStyle(el, '::after').backgroundColor)
  await expect.poll(activeColor).toBe('rgb(18, 71, 137)')
  await page.getByLabel('浅色主色').fill('#784298')
  await expect.poll(activeColor).toBe('rgb(120, 66, 152)')
  await page.getByRole('checkbox', { name: '深色模式' }).check()
  await expect.poll(activeColor).toBe('rgb(171, 204, 237)')
})
