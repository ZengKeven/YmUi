import { expect, test, type Locator } from '@playwright/test'

const node = (tree: Locator, label: string) => tree.getByRole('treeitem', { name: label, exact: true })

test.beforeEach(async ({ page }) => {
  await page.goto('/tests/fixture/tree.html')
})

test('activating a category reports its key and node once; expanding a branch only reveals children', async ({ page }) => {
  const tree = page.locator('#basic').getByRole('tree')
  const fruit = node(tree, '水果')
  await expect(tree.getByRole('checkbox')).toHaveCount(0)
  await expect(tree.getByRole('treeitem', { selected: true })).toHaveCount(0)
  await fruit.click()
  await expect(fruit).toHaveAttribute('aria-selected', 'true')
  await expect(fruit).toHaveAttribute('aria-expanded', 'false')
  await fruit.getByRole('button', { name: '展开 水果' }).click()
  const apple = node(tree, 'Apple 苹果')
  await expect(apple).toHaveAttribute('aria-level', '3')
  await expect(page.locator('#updates')).toHaveText('["fruit"]')
  await apple.click()
  await apple.click()
  await node(tree, '梨').click()
  await expect(tree.getByRole('treeitem', { selected: true })).toHaveCount(1)
  await expect(node(tree, '梨')).toHaveAttribute('aria-selected', 'true')
  await expect(page.locator('#updates')).toHaveText('["fruit",0,"0"]')
  await expect(page.locator('#changes')).toHaveText('[["fruit","水果"],[0,"Apple 苹果"],["0","梨"]]')
})

test('local label filtering keeps ancestor paths, the previous expansion and the active category', async ({ page }) => {
  const region = page.locator('#basic')
  const tree = region.getByRole('tree')
  const filter = region.getByPlaceholder('过滤节点')
  await node(tree, '饮品').click()
  await filter.fill('  aPpLe  ')
  await expect(tree.getByRole('treeitem')).toHaveCount(3)
  await expect(node(tree, '食品')).toHaveAttribute('aria-expanded', 'true')
  await expect(node(tree, '水果')).toHaveAttribute('aria-expanded', 'true')
  await expect(node(tree, 'Apple 苹果')).toBeVisible()
  await expect(tree.getByRole('treeitem', { selected: true })).toHaveCount(0)
  await filter.fill('biscuits')
  await expect(tree.getByRole('treeitem')).toHaveCount(0)
  await expect(region.getByText('无匹配节点')).toBeVisible()
  await filter.fill('')
  await expect(node(tree, '食品')).toHaveAttribute('aria-expanded', 'true')
  await expect(node(tree, '水果')).toHaveAttribute('aria-expanded', 'false')
  await expect(node(tree, '饮品')).toHaveAttribute('aria-selected', 'true')
  await expect(page.locator('#updates')).toHaveText('["drinks"]')
  await filter.fill('水果')
  await page.getByLabel('显示分类过滤').uncheck()
  await expect(filter).toBeHidden()
  await expect(node(tree, '饮品')).toBeVisible()
})

test('arrow keys navigate expanded rows; Enter and Space activate the focused category', async ({ page }) => {
  const tree = page.locator('#basic').getByRole('tree')
  const food = node(tree, '食品')
  const fruit = node(tree, '水果')
  const apple = node(tree, 'Apple 苹果')
  await food.focus()
  await page.keyboard.press('ArrowRight')
  await expect(fruit).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await expect(fruit).toHaveAttribute('aria-expanded', 'true')
  await page.keyboard.press('ArrowDown')
  await expect(apple).toBeFocused()
  await expect(apple).toHaveAttribute('tabindex', '0')
  await expect(page.locator('#updates')).toHaveText('[]')
  await page.keyboard.press('Enter')
  await expect(apple).toHaveAttribute('aria-selected', 'true')
  await page.keyboard.press('ArrowLeft')
  await expect(fruit).toBeFocused()
  await page.keyboard.press('ArrowLeft')
  await expect(fruit).toHaveAttribute('aria-expanded', 'false')
  await page.keyboard.press('End')
  await expect(node(tree, '饮品')).toBeFocused()
  await page.keyboard.press('Space')
  await expect(node(tree, '饮品')).toHaveAttribute('aria-selected', 'true')
  await page.keyboard.press('ArrowUp')
  await expect(node(tree, '饼干')).toBeFocused()
  await page.keyboard.press('Home')
  await expect(food).toBeFocused()
  await expect(page.locator('#updates')).toHaveText('[0,"drinks"]')
})

test('the owner can refuse activation, clear the value or replace the data', async ({ page }) => {
  const region = page.locator('#controlled')
  const tree = region.getByRole('tree')
  const apple = node(tree, 'Apple 苹果')
  await expect(region.getByPlaceholder('搜索分类名称')).toBeVisible()
  await expect(apple).toHaveAttribute('aria-selected', 'true')
  await node(tree, '饮品').click()
  await expect(apple).toHaveAttribute('aria-selected', 'true')
  await expect(region.locator('#controlled-changes')).toHaveText('["drinks"]')
  await page.getByLabel('应用选择').check()
  await node(tree, '梨').click()
  await expect(node(tree, '梨')).toHaveAttribute('aria-selected', 'true')
  await page.getByRole('button', { name: '移除分类' }).click()
  await expect(region.getByText('暂无数据')).toBeVisible()
  await page.getByRole('button', { name: '恢复分类' }).click()
  await expect(node(tree, '梨')).toHaveAttribute('aria-selected', 'true')
  await page.getByRole('button', { name: '清除高亮' }).click()
  await expect(tree.getByRole('treeitem', { selected: true })).toHaveCount(0)
  await expect(region.locator('#controlled-changes')).toHaveText('["drinks","0"]')
})

test('rows and filter follow nested size, theme, mode and radius; a local size takes precedence', async ({ page }) => {
  const tree = page.locator('#inherited .ym-tree')
  const active = node(tree, '饮品')
  const label = active.getByText('饮品', { exact: true })
  const local = node(page.locator('#local'), '饮品')
  await expect(tree).toHaveCSS('background-color', 'rgb(245, 239, 227)')
  await expect(label).toHaveCSS('color', 'rgb(38, 115, 75)')
  await page.getByLabel('分类主色').fill('#72489c')
  await expect(label).toHaveCSS('color', 'rgb(114, 72, 156)')
  await page.getByLabel('深色模式').check()
  await expect(tree).toHaveCSS('background-color', 'rgb(25, 39, 56)')
  await expect(label).toHaveCSS('color', 'rgb(173, 201, 234)')
  await expect(active).toHaveCSS('border-radius', '7px')
  await page.getByLabel('直角节点').check()
  await expect(active).toHaveCSS('border-radius', '0px')
  for (const [size, height, font] of [
    ['extra-small', '20px', '11px'], ['small', '24px', '12px'],
    ['medium', '32px', '14px'], ['large', '40px', '16px'],
  ]) {
    await page.getByRole('combobox', { name: '尺寸' }).selectOption(size)
    await expect(active).toHaveCSS('height', height)
    await expect(label).toHaveCSS('font-size', font)
    await expect(tree.locator('.ym-input')).toHaveCSS('height', height)
    await expect(local).toHaveCSS('height', '24px')
  }
})
