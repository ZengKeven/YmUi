test('form controls inherit disabled and readonly; nested size, palettes and radius update at runtime', async ({ page }) => {
  const order = page.locator('#order')
  const email = order.getByRole('textbox', { name: '通知邮箱' })
  const warehouse = order.getByRole('combobox', { name: '仓库' })
  const override = order.getByRole('textbox', { name: '独立备注' })
  await page.getByLabel('禁用控件').check()
  await expect(email).toBeDisabled()
  await expect(order.getByRole('button', { name: '保存订单' })).toBeDisabled()
  await expect(warehouse).toBeDisabled()
  await expect(override).toBeEditable()
  await page.getByLabel('禁用控件').uncheck()
  await page.getByLabel('只读控件').check()
  await expect(email).not.toBeEditable()
  await expect(email).toBeEnabled()
  await expect(warehouse).toBeEnabled()
  await expect(warehouse).not.toBeEditable()
  await expect(override).toBeEditable()
  await page.getByLabel('只读控件').uncheck()
  await expect(email).toBeEditable()

  await page.getByRole('button', { name: '检查邮箱', exact: true }).click()
  const message = order.getByText('请填写邮箱')
  await expect(message).toHaveCSS('color', 'rgb(146, 36, 72)')
  await page.getByLabel('浅色错误色').fill('#843214')
  await expect(message).toHaveCSS('color', 'rgb(132, 50, 20)')
  await page.getByLabel('深色', { exact: true }).check()
  await expect(message).toHaveCSS('color', 'rgb(243, 170, 187)')
  const inherited = order.locator('.ym-input').first()
  const compact = page.locator('#compact .ym-input')
  await expect(inherited).toHaveCSS('border-radius', '3px')
  await page.getByLabel('直角').check()
  await expect(inherited).toHaveCSS('border-radius', '0px')
  let previous = 0
  const compactHeight = (await compact.boundingBox())!.height
  for (const size of ['extra-small', 'small', 'medium', 'large']) {
    await page.getByLabel('全局尺寸').selectOption(size)
    const height = (await inherited.boundingBox())!.height
    expect(height).toBeGreaterThan(previous)
    expect((await compact.boundingBox())!.height).toBe(compactHeight)
    if (size === 'small') expect(height).toBe(compactHeight)
    previous = height
  }
})

test('readonly values remain in native FormData while disabled fields are omitted', async ({ page }) => {
  await page.getByRole('button', { name: '展示提交字段' }).click()
  const form = page.locator('#entry-fields')
  const entries = () => form.evaluate(node => [...new FormData(node as HTMLFormElement).entries()])
  const expected = [
    ['warehouse', 'sh'], ['warehouse', 'hz'], ['tree', 'hz'], ['date', '2026-11-25'],
    ['dates', '2026-11-25 至 2026-11-28'], ['time', '08:00'], ['times', '08:00 至 17:00'],
    ['checks', '甲'], ['delivery', '快递'], ['color', '#112233'], ['explicit', 'sh'],
  ]
  await expect.poll(entries).toEqual(expected)
  const combo = form.getByRole('combobox', { name: '提交仓库' })
  await combo.click()
  await expect(combo).toHaveAttribute('aria-expanded', 'true')
  await page.getByLabel('只读控件').check()
  await expect(combo).toHaveAttribute('aria-expanded', 'false')
  await combo.press('ArrowDown')
  await expect(combo).toHaveAttribute('aria-expanded', 'false')
  await expect(combo).toBeEnabled()
  await expect(combo).not.toBeEditable()
  await form.getByRole('checkbox', { name: '乙' }).click()
  await form.getByRole('radio', { name: '自提' }).click()
  await form.getByRole('radio', { name: '快递' }).press('ArrowRight')
  await expect(form.getByRole('checkbox', { name: '乙' })).not.toBeChecked()
  await expect(form.getByRole('radio', { name: '快递' })).toBeChecked()
  await expect.poll(entries).toEqual(expected)
  await page.getByLabel('禁用控件').check()
  await expect.poll(entries).toEqual([['explicit', 'sh']])
})
