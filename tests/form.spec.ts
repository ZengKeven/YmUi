test('an edit or reset during an asynchronous submit invalidates the previous submission', async ({ page }) => {
  const order = page.locator('#order')
  const account = order.getByRole('textbox', { name: '账号' })
  for (const [index, action] of ['edit', 'reset'].entries()) {
    await account.fill('待查询')
    await page.getByRole('button', { name: '等待提交' }).click()
    await expect(page.locator('#requests')).toHaveText(String((index + 1) * 2))
    if (action === 'edit') await account.fill('已变更')
    else await order.getByRole('button', { name: '清空表单' }).click()
    await page.getByRole('button', { name: '返回旧结果' }).click()
    await expect(page.locator('#finished-submits')).toHaveText(String(index + 1))
    await expect(page.locator('#events')).not.toContainText('提交/')
    await expect(order.getByText('编码冲突 login')).toHaveCount(0)
  }
})

test('reset clears fallback values and active drafts when fields started undefined', async ({ page }) => {
  const panel = page.locator('#empty-values')
  const number = panel.getByRole('textbox', { name: '数量' })
  const choice = panel.getByRole('combobox', { name: '类型' })
  const toggle = panel.getByRole('switch', { name: '启用' })
  const rating = panel.getByRole('slider', { name: '评分' })
  for (const action of ['全部清空', '全部还原']) {
    await number.fill('7')
    await number.press('Tab')
    await choice.click()
    await page.getByRole('option', { name: '成品' }).click()
    await toggle.click()
    await rating.press('ArrowRight')
    await expect(panel.locator('output')).toHaveText('{"num":7,"choice":3,"enabled":true,"score":1}')
    await panel.getByRole('button', { name: '只清数量' }).click()
    await expect(number).toHaveValue('')
    await expect(choice).toHaveValue('成品')
    await expect(toggle).toBeChecked()
    await expect(rating).toHaveAttribute('aria-valuenow', '1')
    await number.fill('-')
    await expect(number).toHaveValue('-')
    // 保持输入框聚焦，让 reset 自己清除尚未提交的草稿。
    await panel.getByRole('button', { name: action }).dispatchEvent('click')
    await expect(number).toHaveValue('')
    await expect(choice).toHaveValue('')
    await expect(toggle).not.toBeChecked()
    await expect(rating).toHaveAttribute('aria-valuenow', '0')
    await expect(panel.locator('output')).toHaveText('{}')
  }
  await panel.getByLabel('等待开关确认').check()
  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-busy', 'true')
  await panel.getByRole('button', { name: '全部还原' }).click()
  await expect(toggle).not.toHaveAttribute('aria-busy', 'true')
  await panel.getByRole('button', { name: '确认开关' }).click()
  await expect(toggle).not.toBeChecked()
  await expect(panel.locator('output')).toHaveText('{}')
})

