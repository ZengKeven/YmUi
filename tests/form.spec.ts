  await order.getByRole('combobox', { name: '仓库' }).click()
  await page.getByRole('option', { name: '上海仓' }).click()
  await expect(order.getByText('请填写邮箱')).toHaveCount(0)
  await expect(order.locator('[data-feedback="profile.email"]')).toHaveText('success')
