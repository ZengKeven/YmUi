test('single selection preserves value types, emits once and follows its owner', async ({ page }) => {
  const field = page.getByRole('combobox', { name: '单选仓库' })
  await expect(field).toHaveValue('Alpha 总仓')
  await field.click()
  await expect(page.getByRole('listbox').locator('input[type="checkbox"]')).toHaveCount(0)
  const selected = page.getByRole('option', { name: 'Alpha 总仓', selected: true })
  await expect(selected).toHaveCSS('color', 'rgb(0, 110, 255)')
  await expect(selected.locator('svg')).toHaveCount(0)
  const disabled = page.getByRole('option', { name: '停用仓库' })
  await expect(disabled).toBeDisabled()
  await disabled.click({ force: true })
  await expect(page.locator('#select-updates')).toHaveText('[]')
  await page.getByRole('option', { name: 'Bravo 分仓' }).click()
  await expect(field).toHaveValue('Bravo 分仓')
  await expect(field).toHaveAttribute('aria-expanded', 'false')
  await expect(page.locator('#select-updates')).toHaveText('["0"]')
  await expect(page.locator('#select-changes')).toHaveText('["0"]')
  await page.getByRole('button', { name: '切换默认仓库' }).click()
  await expect(field).toHaveValue('Charlie 分仓')

  const locked = page.getByRole('combobox', { name: '锁定仓库' })
  await locked.click()
  await page.getByRole('option', { name: 'Charlie 分仓' }).click()
  await expect(locked).toHaveValue('Alpha 总仓')
  const disabledField = page.getByRole('combobox', { name: '禁用仓库' })
  await expect(disabledField).toBeDisabled()
  const disabledTag = page.locator('.ym-select__control').filter({ has: disabledField }).locator('.ym-tag')
  await expect(disabledTag.getByRole('button', { name: '移除 Charlie 分仓' })).toBeDisabled()
})

test('custom multiple options enforce the cap while allowing deselection and chip removal', async ({ page }) => {
  const field = page.getByRole('combobox', { name: '多选仓库' })
  await field.click()
  const tags = page.locator('.ym-select__control').filter({ has: field }).locator('.ym-tag')
  const list = page.getByRole('listbox')
  const alpha = list.getByRole('option', { name: /Alpha 总仓/ })
  const bravo = list.getByRole('option', { name: /Bravo 分仓/ })
  const charlie = list.getByRole('option', { name: /Charlie 分仓/ })
  const alphaCheck = alpha.locator('input[type="checkbox"]')
  const charlieCheck = charlie.locator('input[type="checkbox"]')
  await expect(list).toHaveAttribute('aria-multiselectable', 'true')
  await expect(alpha.locator('small')).toHaveText('WH01')
  await expect(alphaCheck).not.toHaveAttribute('name', 'notification-settings')
  await expect(charlieCheck).not.toBeChecked()
  await expect(list.getByRole('option', { name: /停用仓库/ }).locator('input')).toBeDisabled()
  const box = (await alphaCheck.boundingBox())!
  expect(box.x + box.width).toBeLessThanOrEqual((await alpha.locator('strong').boundingBox())!.x)
  await alphaCheck.click()
  await expect(alphaCheck).toBeChecked()
  await expect(field).toBeFocused()
  await expect(page.locator('#select-updates')).toHaveText('[[0]]')
  await expect(page.locator('#select-changes')).toHaveText('[[0]]')
  await bravo.locator('strong').click()
  await expect(bravo.locator('input')).toBeChecked()
  await expect(tags).toHaveText(['Alpha 总仓', 'Bravo 分仓'])
  await expect(alpha).toHaveAttribute('aria-selected', 'true')
  await expect(charlie).toBeDisabled()
  await expect(charlieCheck).toBeDisabled()
  await charlie.click({ force: true })
  await expect(page.locator('#select-many')).toHaveText('[0,"0"]')
  await alphaCheck.click()
  await expect(alphaCheck).not.toBeChecked()
  await expect(charlie).toBeEnabled()
  await expect(charlieCheck).toBeEnabled()
  await field.press('Escape')
  await field.press('ArrowUp')
  await field.press('Enter')
  await expect(charlieCheck).toBeChecked()
  await expect(page.locator('#select-many')).toHaveText('["0",3]')
  await tags.getByRole('button', { name: '移除 Charlie 分仓' }).click()
  await expect(field).toBeFocused()
  await expect(field).toHaveAttribute('aria-expanded', 'true')
  await expect(charlie).toHaveAttribute('aria-selected', 'false')
  await expect(charlieCheck).not.toBeChecked()
  await field.press('Escape')
  await tags.getByRole('button', { name: '移除 Bravo 分仓' }).click()
  await expect(field).toHaveAttribute('aria-expanded', 'false')
  await expect(tags).toHaveCount(0)
  await expect(page.locator('#select-many')).toHaveText('[]')
})

test('local name and custom filters support keyboard selection', async ({ page }) => {
  const local = page.getByRole('combobox', { name: '按名称筛选' })
  const matches = page.getByRole('listbox').getByRole('option')
  await local.click()
  await local.fill('bRaVo')
  await expect(matches).toHaveCount(1)
  await expect(matches).toHaveText(/Bravo 分仓/)
  await expect(page.locator('#select-searches')).toHaveText('["bRaVo"]')
  await local.press('ArrowDown')
  await local.press('Enter')
  await expect(local).toHaveValue('Bravo 分仓')
  await expect(local).toHaveAttribute('aria-expanded', 'false')
  await local.pressSequentially('Alpha')
  await expect(local).toHaveValue('Alpha')
  await expect(matches).toHaveText('Alpha 总仓')
  await local.press('Escape')
  const custom = page.getByRole('combobox', { name: '按编码筛选' })
  await custom.click()
  await custom.fill('wh04')
  await expect(matches).toHaveCount(1)
  await matches.filter({ hasText: 'Charlie 分仓' }).click()
  await expect(custom).toHaveValue('Charlie 分仓')
})

test('remote selection ignores stale responses across queries and sessions and recovers from errors', async ({ page }) => {
  const requests = new Map<string, Route>()
  await page.route('**/select-remote?*', route => {
    requests.set(new URL(route.request().url()).searchParams.get('query')!, route)
  })
  async function reply(query: string, label?: string, status = 200) {
    await expect.poll(() => requests.has(query)).toBe(true)
    const request = requests.get(query)!
    requests.delete(query)
    await request.fulfill({ status, json: label ? [{ value: query, label }] : [] })
    if (status === 200) await expect(page.locator('#select-remote-completed')).toHaveText(query)
  }
  const field = page.getByRole('combobox', { name: '远程仓库' })
  const list = page.getByRole('listbox')
  await field.click()
  await reply('')
  await field.fill('old')
  await expect.poll(() => requests.has('old')).toBe(true)
  await field.fill('new')
  await reply('new', '当前服务器结果')
  await expect(list.getByRole('option', { name: '当前服务器结果' })).toBeVisible()
  await reply('old', '过期结果')
  await expect(list.getByRole('option')).toHaveCount(1)
  await list.getByRole('option', { name: '当前服务器结果' }).click()
  await expect(field).toHaveValue('当前服务器结果')

  await field.click()
  await reply('')
  await field.fill('discard')
  await expect.poll(() => requests.has('discard')).toBe(true)
  await field.press('Escape')
  await expect(field).toHaveValue('当前服务器结果')
  await field.click()
  await reply('', '重新打开的结果')
  await reply('discard', '已关闭的查询')
  await expect(list.getByRole('option')).toHaveText(/重新打开的结果/)
  await field.fill('failed')
  await reply('failed', undefined, 503)
  await expect(list.getByRole('option')).toHaveCount(0)
  await field.fill('recover')
  await reply('recover', '恢复后的结果')
  await list.getByRole('option', { name: '恢复后的结果' }).click()
  await expect(field).toHaveValue('恢复后的结果')
})

