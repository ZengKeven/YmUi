test('the current option opens in view and forms submit selected keys throughout a search', async ({ page }) => {
  const field = page.getByRole('combobox', { name: '货位', exact: true })
  const values = () => page.locator('form#select-form').evaluate(form => new FormData(form).getAll('location'))
  await field.click()
  const panel = page.locator('.ym-select__panel:popover-open')
  const current = panel.getByRole('option', { name: '货位 34', exact: true })
  await expect.poll(() => current.evaluate(el => {
    const rect = el.getBoundingClientRect()
    const bounds = el.closest('.ym-select__panel')!.getBoundingClientRect()
    return rect.top >= bounds.top && rect.bottom <= bounds.bottom
  })).toBe(true)
  await field.fill('货位 8')
  expect(await values()).toEqual(['34'])
  await panel.getByRole('option', { name: '货位 8', exact: true }).click()
  expect(await values()).toEqual(['34', '8'])
  await page.getByRole('button', { name: '重置货位' }).click()
  await expect.poll(values).toEqual(['34'])
})
