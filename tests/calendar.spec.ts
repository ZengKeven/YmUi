import { expect, test, type Locator } from '@playwright/test'

test.use({ timezoneId: 'America/Los_Angeles' })
test.beforeEach(async ({ page }) => {
  await page.clock.setFixedTime(new Date('2024-02-16T02:00:00Z'))
  await page.goto('/tests/fixture/calendar.html')
})

function day(calendar: Locator, date: string) {
  return calendar.getByRole('button', { name: date, exact: true })
}

test('the default calendar shows the current month and distinguishes today from a selection', async ({ page }) => {
  const empty = page.locator('#empty')
  const dates = empty.getByRole('button', { name: /^\d{4}-\d{2}-\d{2}$/ })
  await expect(dates).toHaveCount(42)
  await expect(day(empty, '2024-02-15')).toHaveAttribute('aria-current', 'date')
  await expect(empty.getByRole('button', { pressed: true })).toHaveCount(0)
  await empty.getByRole('button', { name: '下个月' }).click()
  await expect(day(empty, '2024-03-15')).toBeVisible()
  await empty.getByRole('button', { name: '今天', exact: true }).click()
  await expect(day(empty, '2024-02-15')).toBeVisible()
  await expect(empty.getByRole('button', { pressed: true })).toHaveCount(0)
})

test('card mode selects a leap day, renders its slot, and emits once for each chosen date', async ({ page }) => {
  const calendar = page.locator('#controlled')
  await expect(calendar.locator('.ym-calendar')).toHaveAttribute('data-theme', 'card')
  await expect(day(calendar, '2024-02-15')).toContainText('今天')
  const leapDay = day(calendar, '2024-02-29')
  await expect(leapDay).toContainText('盘点')
  await leapDay.click()
  await expect(leapDay).toHaveText(/已选/)
  await expect(leapDay).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('#value')).toHaveText('2024-02-29')
  await expect(page.locator('#updates')).toHaveText('2024-02-29')
  await expect(page.locator('#changes')).toHaveText('2024-02-29')
  await expect(page.locator('#months')).toBeEmpty()

  await day(calendar, '2024-03-01').click()
  await expect(day(calendar, '2024-03-20')).toBeVisible()
  await expect(day(calendar, '2024-03-01')).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('#updates')).toHaveText('2024-02-29,2024-03-01')
  await expect(page.locator('#changes')).toHaveText('2024-02-29,2024-03-01')
  await expect(page.locator('#months')).toHaveText('2024-03')
})

test('lunar dates follow the local day, including month starts and leap months', async ({ page }) => {
  const card = page.locator('#controlled')
  const toggle = page.getByLabel('显示农历')
  await expect(card.locator('.ym-calendar__lunar')).toHaveCount(0)
  await toggle.check()
  await expect(card.locator('.ym-calendar__lunar')).toHaveCount(42)
  await expect(day(card, '2024-02-10').locator('.ym-calendar__lunar')).toHaveText('正月')
  await expect(day(card, '2024-02-10')).toHaveAccessibleDescription('正月')
  await expect(day(card, '2024-02-11').locator('.ym-calendar__lunar')).toHaveText('初二')
  const adjacent = day(card, '2024-03-01')
  await expect(adjacent.locator('.ym-calendar__lunar')).toHaveText('廿一')
  await expect(day(card, '2024-02-29')).toContainText('盘点')
  await expect(day(card, '2024-02-28')).toHaveAttribute('aria-pressed', 'true')

  const leapMonthStart = day(page.locator('#local'), '2025-07-25')
  const label = leapMonthStart.locator('.ym-calendar__lunar')
  await expect(label).toHaveText('闰六月')
  const numberBox = await leapMonthStart.locator('.ym-calendar__number').boundingBox()
  const lunarBox = await label.boundingBox()
  const buttonBox = await leapMonthStart.boundingBox()
  expect(lunarBox!.y).toBeGreaterThanOrEqual(numberBox!.y + numberBox!.height - 1)
  expect(lunarBox!.y + lunarBox!.height).toBeLessThanOrEqual(buttonBox!.y + buttonBox!.height)
  await adjacent.click()
  await expect(day(card, '2024-03-10').locator('.ym-calendar__lunar')).toHaveText('二月')
  await toggle.uncheck()
  await expect(card.locator('.ym-calendar__lunar')).toHaveCount(0)
  await expect(adjacent).toHaveAttribute('aria-pressed', 'true')
})

test('navigation and external model changes keep the displayed month separate from the selected date', async ({ page }) => {
  const calendar = page.locator('#controlled')
  await calendar.getByRole('button', { name: '上个月' }).click()
  await expect(day(calendar, '2024-01-15')).toBeVisible()
  await expect(page.locator('#months')).toHaveText('2024-01')
  await expect(page.locator('#value')).toHaveText('2024-02-28')
  await expect(page.locator('#updates')).toBeEmpty()
  await page.getByRole('button', { name: '设置次年日期' }).click()
  await expect(day(calendar, '2025-01-02')).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: '清空日期' }).click()
  await expect(calendar.getByRole('button', { pressed: true })).toHaveCount(0)
  await expect(page.locator('#changes')).toBeEmpty()

  const uncontrolled = page.locator('#uncontrolled')
  await expect(day(uncontrolled, '2023-12-31')).toHaveAttribute('aria-pressed', 'true')
  await uncontrolled.getByRole('button', { name: '下个月' }).click()
  await day(uncontrolled, '2024-01-03').click()
  await expect(day(uncontrolled, '2024-01-03')).toHaveAttribute('aria-pressed', 'true')
  const locked = page.locator('#locked')
  await day(locked, '2024-01-15').click()
  await expect(day(locked, '2024-01-12')).toHaveAttribute('aria-pressed', 'true')
})

test('a card inside YmPopup browses months and dismisses on selection, including choosing the same date again', async ({ page }) => {
  const trigger = page.getByRole('button', { name: '选择日期', exact: true })
  const calendar = page.locator('.calendar-picker-panel .ym-calendar')
  await trigger.click()
  await calendar.getByRole('combobox', { name: '年份' }).click()
  await page.getByRole('option', { name: '2025年', exact: true }).click()
  await calendar.getByRole('combobox', { name: '月份' }).click()
  await page.getByRole('option', { name: '11月', exact: true }).click()
  await expect(trigger).toHaveAttribute('aria-expanded', 'true')
  await expect(trigger).toHaveText('请选择日期')
  // Local clocks repeat an hour on November 2 in the fixture time zone.
  await expect(day(calendar, '2025-11-02')).toHaveCount(1)
  const monday = day(calendar, '2025-11-03')
  await monday.click()
  await expect(trigger).toHaveText('2025-11-03')
  await expect(calendar).toBeHidden()
  await expect(page.locator('#picker-selections')).toHaveText('2025-11-03')
  await trigger.click()
  await expect(monday).toHaveAttribute('aria-pressed', 'true')
  await monday.click()
  await expect(calendar).toBeHidden()
  await expect(page.locator('#picker-selections')).toHaveText('2025-11-03,2025-11-03')
  await expect(page.locator('#picker-changes')).toHaveText('2025-11-03')
})

test('the week start reorders the grid and disabled dates prevent choosing weekends', async ({ page }) => {
  const calendar = page.locator('#controlled')
  const firstDay = calendar.getByRole('button', { name: /^\d{4}-\d{2}-\d{2}$/ }).first()
  await expect(firstDay).toHaveAccessibleName('2024-01-29')
  await page.getByLabel('周日起始').check()
  await expect(firstDay).toHaveAccessibleName('2024-01-28')
  const saturday = day(calendar, '2024-02-17')
  await expect(saturday).toBeDisabled()
  await day(calendar, '2024-02-16').press('ArrowRight')
  await expect(saturday).toBeFocused()
  await saturday.press('Enter')
  await saturday.dispatchEvent('click')
  await expect(page.locator('#value')).toHaveText('2024-02-28')
  await page.getByLabel('禁用日历').check()
  await expect(day(calendar, '2024-02-29')).toBeDisabled()
  await expect(calendar.getByRole('button', { name: '下个月' })).toBeDisabled()
  await expect(page.locator('#updates')).toBeEmpty()
})

test('keyboard navigation crosses months, respects the first weekday and selects only on activation', async ({ page }) => {
  const calendar = page.locator('#uncontrolled')
  await day(calendar, '2023-12-31').press('ArrowRight')
  await expect(day(calendar, '2024-01-01')).toBeFocused()
  await day(calendar, '2024-01-01').press('End')
  await expect(day(calendar, '2024-01-07')).toBeFocused()
  await day(calendar, '2024-01-07').press('Home')
  await expect(day(calendar, '2024-01-01')).toBeFocused()
  await day(calendar, '2024-01-01').press('ArrowDown')
  await expect(day(calendar, '2024-01-08')).toBeFocused()
  await day(calendar, '2024-01-08').press('PageDown')
  await expect(day(calendar, '2024-02-08')).toBeFocused()
  await day(calendar, '2024-02-08').press('PageUp')
  const jan8 = day(calendar, '2024-01-08')
  await expect(jan8).toBeFocused()
  await expect(jan8).toHaveAttribute('aria-pressed', 'false')
  await jan8.press('Enter')
  await expect(jan8).toHaveAttribute('aria-pressed', 'true')
})

test('a card inherits live size, mode, palette and radius with a local size override', async ({ page }) => {
  const calendar = page.locator('#inherited .ym-calendar')
  const next = calendar.getByRole('button', { name: '下个月' })
  const localNext = page.locator('#local').getByRole('button', { name: '下个月' })
  const selected = day(calendar, '2024-02-28')
  await expect(calendar).toHaveCSS('background-color', 'rgb(255, 250, 243)')
  await expect(calendar).toHaveCSS('border-radius', '12px')
  await expect(selected).toHaveCSS('background-color', 'rgb(18, 106, 99)')
  await expect(next).toHaveCSS('height', '40px')
  await expect(localNext).toHaveCSS('height', '20px')
  await page.getByLabel('浅色强调色').fill('#be3456')
  await expect(selected).toHaveCSS('background-color', 'rgb(190, 52, 86)')
  await page.getByLabel('深色模式').check()
  await expect(calendar).toHaveCSS('background-color', 'rgb(38, 52, 75)')
  await expect(selected).toHaveCSS('background-color', 'rgb(138, 205, 180)')
  await page.getByLabel('小号和直角').check()
  await expect(calendar).toHaveCSS('border-radius', '0px')
  await expect(next).toHaveCSS('height', '24px')
  await expect(localNext).toHaveCSS('height', '20px')
})
