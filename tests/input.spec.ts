import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.goto('/tests/fixture/')
})

test('text editing syncs the model, forwards input attributes and supports native form behavior', async ({ page }) => {
  const alias = page.getByLabel('账户别名', { exact: true })
  await expect(alias).toHaveValue('')
  await expect(alias).toHaveJSProperty('type', 'text')
  await expect(alias).toHaveAttribute('placeholder', '输入别名')
  await expect(alias).toHaveAttribute('autocomplete', 'nickname')
  await expect(alias).toHaveJSProperty('maxLength', 12)
  await expect(alias).toHaveJSProperty('required', true)
  await expect(page.locator('.ym-input.alias-field')).toHaveCSS('width', '240px')
  await page.getByRole('button', { name: '聚焦账户别名' }).click()
  await expect(alias).toBeFocused()
  await alias.press('A')
  await page.getByRole('button', { name: '移开别名焦点' }).click()
  await expect(alias).not.toBeFocused()
  await expect(page.locator('#input-events')).toHaveText('focus keydown input blur')
  await expect(page.locator('#input-model')).toHaveText('A')
  await expect(page.locator('#input-updates')).toHaveText('["A"]')
  await expect(page.locator('#input-changes')).toHaveText('["A"]')
  await page.getByRole('button', { name: '设置账户别名' }).click()
  await expect(alias).toHaveValue('外部修改')
  await page.getByLabel('访问口令').fill('changed')
  await page.getByRole('button', { name: '重置输入表单' }).click()
  await expect(alias).toHaveValue('外部修改')
  await expect(page.getByLabel('访问口令')).toHaveValue('initial')
  await page.getByRole('button', { name: '切换别名只读' }).click()
  await expect(alias).not.toBeEditable()
  const formData = () => page.locator('form#input-form').evaluate(form => [...new FormData(form).entries()])
  expect(await formData()).toEqual([['alias', '外部修改'], ['passcode', 'initial']])
  await page.getByRole('button', { name: '切换输入框禁用' }).click()
  await expect(alias).toBeDisabled()
  await expect(page.getByRole('button', { name: '显示密码' })).toBeDisabled()
  expect(await formData()).toEqual([])

  const rejected = page.getByLabel('受控别名')
  await rejected.fill('新名称')
  await expect(page.locator('#input-rejected')).toHaveText('新名称')
  await expect(rejected).toHaveValue('审核中')
})

test('IME text is published once when the composition is committed', async ({ page }) => {
  const alias = page.getByLabel('账户别名', { exact: true })
  await alias.focus()
  await alias.evaluate((el: HTMLInputElement) => {
    el.dispatchEvent(new CompositionEvent('compositionstart', { bubbles: true }))
    el.value = 'pin'
    el.dispatchEvent(new InputEvent('input', { data: 'pin', isComposing: true, bubbles: true }))
  })
  await expect(alias).toHaveValue('pin')
  await expect(page.locator('#input-model')).toBeEmpty()
  await expect(page.locator('#input-changes')).toHaveText('[]')
  await alias.evaluate((el: HTMLInputElement) => {
    el.value = '拼'
    el.dispatchEvent(new CompositionEvent('compositionend', { data: '拼', bubbles: true }))
    el.dispatchEvent(new InputEvent('input', { data: '拼', bubbles: true }))
  })
  await expect(page.locator('#input-model')).toHaveText('拼')
  await expect(page.locator('#input-updates')).toHaveText('["拼"]')
  await expect(page.locator('#input-changes')).toHaveText('["拼"]')
})

test('password visibility is keyboard accessible and preserves the uncontrolled value', async ({ page }) => {
  const password = page.getByLabel('访问口令')
  await expect(password).toHaveJSProperty('type', 'password')
  await expect(password).toHaveValue('initial')
  await password.fill('edited')
  const show = page.getByRole('button', { name: '显示密码' })
  await show.press('Enter')
  await expect(password).toHaveJSProperty('type', 'text')
  await page.getByRole('button', { name: '隐藏密码' }).press('Space')
  await expect(password).toHaveJSProperty('type', 'password')
  await show.click()
  const switchType = page.getByRole('button', { name: '切换口令类型' })
  await switchType.click()
  await expect(password).toHaveJSProperty('type', 'text')
  await expect(page.getByRole('button', { name: /^(显示|隐藏)密码$/ })).toHaveCount(0)
  await switchType.click()
  await expect(password).toHaveJSProperty('type', 'password')
  await expect(password).toHaveValue('edited')
  await expect(page.locator('#input-password-changes')).toHaveText('1')
  await page.getByRole('button', { name: '传入其他输入类型' }).click()
  await expect(password).toHaveJSProperty('type', 'text')
})

test('nested input settings update size, focus color, surface and radius', async ({ page }) => {
  const input = page.getByLabel('继承配置的输入框')
  const box = page.locator('.ym-input').filter({ has: input })
  const local = page.locator('.ym-input').filter({ has: page.getByLabel('指定尺寸的输入框') })
  await expect(box).toHaveCSS('height', '40px')
  await expect(box).toHaveCSS('border-radius', '11px')
  await input.focus()
  await expect(box).toHaveCSS('border-top-color', 'rgb(33, 101, 74)')
  await page.getByLabel('输入框浅色焦点色').fill('#734556')
  await input.focus()
  await expect(box).toHaveCSS('border-top-color', 'rgb(115, 69, 86)')
  await page.getByRole('button', { name: '切换输入框模式' }).click()
  await input.focus()
  await expect(box).toHaveCSS('border-top-color', 'rgb(154, 188, 222)')
  await expect(box).toHaveCSS('background-color', 'rgb(42, 53, 68)')
  await page.getByRole('button', { name: '切换输入框大小和圆角' }).click()
  await expect(box).toHaveCSS('height', '20px')
  await expect(box).toHaveCSS('border-radius', '0px')
  await expect(local).toHaveCSS('height', '24px')
})
