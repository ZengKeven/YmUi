import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.goto('/tests/fixture/')
})

test('a labeled radio supports keyboard activation and emits once when selected', async ({ page }) => {
  const field = page.getByRole('radio', { name: '开启单选提醒' })
  const events = page.locator('#radio-events')
  await expect(field).not.toBeChecked()
  await expect(page.getByRole('radio', { name: '初始开启的单选项' })).toBeChecked()
  await field.press('Space')
  await expect(field).toBeChecked()
  await expect(events).toHaveText('true update/true true/change')
  await page.getByText('开启单选提醒', { exact: true }).click()
  await expect(field).toBeChecked()
  await expect(events).toHaveText('true update/true true/change')
})

test('group selections retain typed values, skip disabled options and submit one native field', async ({ page }) => {
  const group = page.getByRole('radiogroup', { name: '结算方式' })
  const textZero = group.getByRole('radio', { name: '字符串零' })
  const numberZero = group.getByRole('radio', { name: '数字零' })
  const bool = group.getByRole('radio', { name: '布尔假' })
  const submitted = () => page.locator('form#radio-method-form').evaluate(form => [...new FormData(form).entries()])
  await expect(group.getByText('由插槽替换')).toHaveCount(0)
  await expect(textZero).toBeChecked()
  await expect(group.getByRole('radio', { name: '缺少单选值' })).toBeDisabled()
  await textZero.press('ArrowRight')
  await expect(numberZero).toBeFocused()
  await expect(numberZero).toBeChecked()
  await expect(textZero).not.toBeChecked()
  await expect(numberZero).toHaveAttribute('name', 'method')
  expect(await submitted()).toEqual([['method', '0']])
  await group.getByText('布尔假', { exact: true }).click()
  await expect(bool).toBeChecked()
  expect(await submitted()).toEqual([['method', 'false']])
  await group.getByRole('radio', { name: '空字符串' }).check()
  expect(await submitted()).toEqual([['method', '']])
  await expect(page.locator('#radio-values')).toHaveText('[0,false,""]')
  await expect(page.locator('#radio-changes')).toHaveText('0/method/change false/method/change ""/method/change')
  await page.getByRole('button', { name: '重设结算方式' }).click()
  await expect(textZero).toBeChecked()
  await page.getByRole('button', { name: '切换结算方式禁用' }).click()
  await expect(textZero).toBeDisabled()
  await expect(numberZero).toBeDisabled()
  expect(await submitted()).toEqual([])
})

test('rejected updates restore the previous radio and unnamed groups stay independent', async ({ page }) => {
  const locked = page.getByRole('radiogroup', { name: '待确认方式' })
  const previous = locked.getByRole('radio', { name: 'false' })
  const candidate = locked.getByRole('radio', { name: '备用' })
  const independent = page.getByRole('radiogroup', { name: '另一组' })
  const second = independent.getByRole('radio', { name: '乙' })
  const name = await previous.getAttribute('name')
  expect(name).toBeTruthy()
  await expect(candidate).toHaveAttribute('name', name!)
  await expect(second).not.toHaveAttribute('name', name!)
  await expect(independent).toHaveCSS('flex-direction', 'column')
  await expect(independent.getByRole('radio', { checked: true })).toHaveCount(0)
  await second.check()
  await expect(second).toHaveCSS('background-color', 'rgb(10, 191, 91)')
  await candidate.click()
  await expect(page.locator('#radio-rejected')).toHaveText('["b"]')
  await expect(previous).toBeChecked()
  await expect(candidate).not.toBeChecked()
  await expect(second).toBeChecked()
})

test('radio size, palette and focus radius follow nested providers and local overrides', async ({ page }) => {
  const inherited = page.getByRole('radio', { name: '继承单选尺寸' })
  const grouped = page.getByRole('radio', { name: '继承组尺寸' })
  const smaller = page.getByRole('radio', { name: '显式单项尺寸' })
  const label = page.locator('label.ym-radio').filter({ has: grouped })
  for (const item of [inherited, grouped]) {
    await expect(item).toHaveCSS('width', '18px')
    await expect(item).toHaveCSS('background-color', 'rgb(36, 104, 84)')
  }
  await grouped.press('Space')
  await expect(label).toHaveCSS('outline-style', 'solid')
  await expect(label).toHaveCSS('border-radius', '9px')
  await page.getByLabel('单选框浅色主题色').fill('#6e375f')
  await expect(grouped).toHaveCSS('background-color', 'rgb(110, 55, 95)')
  await page.getByRole('button', { name: '切换单选框配色模式' }).click()
  await expect(grouped).toHaveCSS('background-color', 'rgb(170, 204, 238)')
  await page.getByRole('button', { name: '切换单选框尺寸和圆角' }).click()
  await grouped.press('Space')
  await expect(label).toHaveCSS('border-radius', '0px')
  await expect(grouped).toHaveCSS('border-radius', '50%')
  await expect(inherited).toHaveCSS('width', '14px')
  await expect(grouped).toHaveCSS('width', '16px')
  await expect(smaller).toHaveCSS('width', '13px')
})

test('radio group themes follow the palette and selected options can override their group', async ({ page }) => {
  const group = page.getByRole('radiogroup', { name: '单选框主题展示' })
  const grouped = group.getByRole('radio', { name: '继承组尺寸' })
  const local = group.getByRole('radio', { name: '显式单项尺寸' })
  const theme = page.getByRole('combobox', { name: '单选框分组主题' })
  for (const [value, color] of [
    ['primary', 'rgb(36, 104, 84)'], ['warning', 'rgb(145, 80, 0)'], ['success', 'rgb(10, 191, 91)'],
  ]) {
    await theme.selectOption(value)
    await expect(grouped).toHaveCSS('background-color', color)
    await expect(grouped).toHaveCSS('border-top-color', color)
  }
  await theme.selectOption('danger')
  await page.getByRole('button', { name: '切换单选框配色模式' }).click()
  await expect(grouped).toHaveCSS('background-color', 'rgb(255, 102, 119)')
  await grouped.press('Space')
  await expect(group.locator('label:focus-within')).toHaveCSS('outline-color', 'rgb(255, 102, 119)')
  await local.check()
  await expect(local).toHaveCSS('background-color', 'rgb(204, 221, 238)')
  const dot = await local.evaluate(el => getComputedStyle(el, '::before').backgroundColor)
  expect(dot).toBe('rgb(32, 48, 64)')
  await expect(grouped).toHaveCSS('background-color', 'rgb(32, 48, 64)')
  await grouped.hover()
  await expect(grouped).toHaveCSS('border-top-color', 'rgb(255, 102, 119)')
})
