import { expect, test, type Locator } from '@playwright/test'

const fixture = '/tests/fixture/chat-list.html'
const viewportSelector = '.ym-chat-list__viewport'
const distanceToBottom = (view: Locator) => view.evaluate(el => el.scrollHeight - el.clientHeight - el.scrollTop)

test('initial position and following respond to message growth, manual reading and returning to the bottom', async ({ page }) => {
  await page.goto(fixture)
  const view = page.locator(viewportSelector)
  const back = page.getByRole('button', { name: '回到底部' })
  await expect.poll(() => view.evaluate(el => el.scrollTop)).toBeGreaterThan(200)
  await expect.poll(() => distanceToBottom(view)).toBeLessThanOrEqual(1)
  const beforeGrowth = await view.evaluate(el => el.scrollHeight)
  await page.getByRole('button', { name: '追加片段' }).click()
  await expect.poll(() => view.evaluate(el => el.scrollHeight)).toBeGreaterThan(beforeGrowth + 100)
  await expect.poll(() => distanceToBottom(view)).toBeLessThanOrEqual(1)
  await view.evaluate(el => { el.scrollTop = 60 })
  await expect(back).toBeVisible()
  await expect(page.locator('#last-scroll')).toHaveText('scroll')
  await page.getByRole('button', { name: '追加消息' }).click()
  await expect(view.getByText('新消息 25')).toHaveCount(1)
  await page.getByRole('button', { name: '追加片段' }).click()
  await expect.poll(() => distanceToBottom(view)).toBeGreaterThan(200)
  await expect.poll(() => view.evaluate(el => el.scrollTop)).toBe(60)
  await back.click()
  await expect.poll(() => distanceToBottom(view)).toBeLessThanOrEqual(1)
  await expect(back).toBeHidden()
  await page.getByRole('button', { name: '追加片段' }).click()
  await expect.poll(() => distanceToBottom(view)).toBeLessThanOrEqual(1)
})

test('initial top, disabled follow and disabled scroll button allow deliberate scrolling via the public instance', async ({ page }) => {
  await page.goto(fixture + '?top&manual')
  const view = page.locator(viewportSelector)
  await expect.poll(() => distanceToBottom(view)).toBeGreaterThan(200)
  await expect.poll(() => view.evaluate(el => el.scrollTop)).toBe(0)
  await page.getByLabel('显示回底按钮').uncheck()
  await expect(page.getByRole('button', { name: '回到底部' })).toBeHidden()
  await page.getByRole('button', { name: '实例回底' }).click()
  await expect.poll(() => distanceToBottom(view)).toBeLessThanOrEqual(1)
  const top = await view.evaluate(el => el.scrollTop)
  await page.getByRole('button', { name: '追加片段' }).click()
  await expect.poll(() => distanceToBottom(view)).toBeGreaterThan(100)
  expect(await view.evaluate(el => el.scrollTop)).toBe(top)
  await page.getByRole('button', { name: '追加并回底' }).click()
  await expect.poll(() => distanceToBottom(view)).toBeLessThanOrEqual(1)
})

test('role placement, reversed data and scoped slots use stable message identity and source indices', async ({ page }) => {
  await page.goto(fixture)
  const view = page.locator(viewportSelector)
  const first = view.locator('.ym-chat-message').first()
  await expect(first).toHaveAttribute('data-message-id', '1')
  await expect(first).toHaveAttribute('data-placement', 'right')
  await expect(view.locator('[data-message-id="2"]')).toHaveAttribute('data-placement', 'left')
  await expect(view.getByText('插槽历史')).toHaveCount(0)
  await page.getByLabel('单列布局').check()
  await expect(first).toHaveAttribute('data-placement', 'left')
  await page.getByLabel('倒序数据').check()
  await page.getByLabel('自定义正文').check()
  await expect(first).toHaveAttribute('data-message-id', '1')
  await expect(first).toContainText('1 位于 23')
  await expect(view.locator('.ym-chat-message').last()).toContainText('24 位于 0')
  await page.getByRole('button', { name: '移除数据' }).click()
  await expect(view.getByText('插槽历史')).toBeVisible()
  await expect(page.getByRole('textbox', { name: '消息内容' })).toBeVisible()
})

test('clearing requires confirmation and lets the owner accept or reject the empty array', async ({ page }) => {
  await page.goto(fixture)
  const rows = page.locator(viewportSelector + ' .ym-chat-message')
  const open = page.getByRole('button', { name: '清空历史', exact: true })
  const dialog = page.getByRole('dialog', { name: '清空历史消息？' })
  await page.getByLabel('显示清空').uncheck()
  await expect(open).toBeHidden()
  await page.getByLabel('显示清空').check()
  await open.click()
  await dialog.getByRole('button', { name: '取消' }).click()
  await expect(dialog).toBeHidden()
  await expect(page.locator('#events')).toBeEmpty()
  await expect(rows).toHaveCount(24)
  await page.getByLabel('接受清空').uncheck()
  await open.click()
  await dialog.getByRole('button', { name: '清空', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(rows).toHaveCount(24)
  const firstEvents = (await page.locator('#events').innerText()).split(',').sort()
  expect(firstEvents).toEqual(['clear:click', 'update:0'])
  await page.getByLabel('接受清空').check()
  await open.click()
  await dialog.getByRole('button', { name: '清空', exact: true }).click()
  await expect(rows).toHaveCount(1)
  await expect(rows).toHaveText('插槽历史')
})

test('messages, the footer and the clear dialog inherit provider colors, radius and size', async ({ page }) => {
  await page.goto(fixture)
  const bubble = page.locator('.ym-chat-message__bubble').first()
  const sender = page.locator('.ym-chat-sender')
  await expect(bubble).toHaveCSS('font-size', '16px')
  await expect(sender).toHaveCSS('border-radius', '9px')
  await expect(sender).toHaveCSS('background-color', 'rgb(242, 237, 223)')
  await page.getByLabel('浅色背景').fill('#e6f5ea')
  await expect(sender).toHaveCSS('background-color', 'rgb(230, 245, 234)')
  await page.getByLabel('紧凑尺寸').check()
  await expect(bubble).toHaveCSS('font-size', '11px')
  await page.getByLabel('局部小号').check()
  await page.getByLabel('紧凑尺寸').uncheck()
  await expect(bubble).toHaveCSS('font-size', '12px')
  await page.getByLabel('深色模式').check()
  await page.getByLabel('直角', { exact: true }).check()
  await expect(sender).toHaveCSS('border-radius', '0px')
  await expect(sender).toHaveCSS('background-color', 'rgb(49, 57, 69)')
  await page.getByRole('button', { name: '清空历史', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '清空历史消息？' })
  await expect(dialog).toHaveCSS('background-color', 'rgb(49, 57, 69)')
  await expect(dialog).toHaveCSS('font-size', '12px')
  await expect(dialog).toHaveCSS('border-radius', '0px')
  // 模态框打开时模拟来自业务页面的全局配置更新。
  await page.getByLabel('直角', { exact: true }).evaluate(input => (input as HTMLInputElement).click())
  await expect(dialog).toHaveCSS('border-radius', '9px')
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(page.locator('#events')).toBeEmpty()
})
