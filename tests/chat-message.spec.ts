import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.route('**/chat-avatar.svg', route => route.fulfill({ status: 404, body: '' }))
  await page.goto('/tests/fixture/chat-message.html')
})

test('plain text keeps line breaks, segment order and visible angle brackets; placement moves the bubble', async ({ page }) => {
  const row = page.locator('#plain .ym-chat-message')
  const bubble = row.locator('.ym-chat-message__bubble')
  await expect(row).toHaveAttribute('data-role', 'assistant')
  await expect(row).toHaveAttribute('data-status', 'complete')
  await expect(row).toHaveAttribute('data-variant', 'text')
  await expect(row).toHaveAttribute('data-placement', 'left')
  await expect(row.getByText('赵宁', { exact: true })).toBeVisible()
  await expect(row.getByText('今天 16:38', { exact: true })).toBeVisible()
  await expect(row.locator('img')).toBeVisible()
  expect(await bubble.innerText()).toMatch(/第一行\n第二行\s*<em>已收货<\/em>/)
  await expect(bubble.locator('em')).toHaveCount(0)
  const left = (await bubble.boundingBox())!.x
  await page.getByLabel('靠右显示').check()
  await expect(row).toHaveAttribute('data-placement', 'right')
  await expect.poll(async () => (await bubble.boundingBox())!.x).toBeGreaterThan(left)
})

test('the message record supplies metadata and a fallback avatar while explicit fields override individually', async ({ page }) => {
  const row = page.locator('#record .ym-chat-message')
  await expect(row).toHaveAttribute('data-message-id', 'msg-21')
  await expect(row).toHaveAttribute('data-role', 'user')
  for (const text of ['收货员', '周三 12:20', '请确认到货时间']) {
    await expect(row.getByText(text, { exact: true })).toBeVisible()
  }
  const avatar = row.getByRole('img', { name: '收货头像' })
  await expect(avatar).toHaveAttribute('src', /^data:image\/svg\+xml/)
  await page.getByLabel('覆盖消息字段').check()
  await expect(row).toHaveAttribute('data-role', 'system')
  await expect(row.getByText('收货员', { exact: true })).toHaveCount(0)
  await expect(row.getByText('新的到货日期', { exact: true })).toBeVisible()
  await expect(row.getByText('周三 12:20', { exact: true })).toBeVisible()
  await expect(avatar).toBeVisible()
  await page.getByLabel('覆盖消息字段').uncheck()
  await expect(row.getByText('请确认到货时间', { exact: true })).toBeVisible()
})

test('pending, streaming, stopped, failed and completed replies keep the available text and announce state', async ({ page }) => {
  const state = page.getByLabel('消息状态')
  const text = page.getByLabel('状态正文')
  const row = page.locator('#state .ym-chat-message')
  const loading = row.getByRole('status')
  const partial = row.getByText('已收到采购单', { exact: true })
  await expect(loading).toBeVisible()
  await text.fill('已收到采购单')
  await expect(partial).toBeVisible()
  await expect(loading).toBeVisible()
  await state.selectOption('streaming')
  await expect(loading).toHaveCount(0)
  await expect(partial).toBeVisible()
  await text.fill('')
  await expect(loading).toBeVisible()
  await text.fill('已收到采购单')
  await state.selectOption('stop')
  await expect(loading).toHaveCount(0)
  await expect(partial).toBeVisible()
  await state.selectOption('error')
  await expect(row.getByRole('alert')).toContainText('消息出错')
  await expect(partial).toBeVisible()
  await text.fill('')
  await expect(row.getByRole('alert')).toBeVisible()
  await state.selectOption('complete')
  await expect(row.getByRole('alert')).toHaveCount(0)
  await expect(loading).toHaveCount(0)
})

test('a streaming record reacts to in-place text and avatar changes and keeps its reply readable', async ({ page }) => {
  const row = page.locator('#streamed .ym-chat-message')
  const bubble = row.locator('.ym-chat-message__bubble')
  const image = row.locator('img[alt="排期助手头像"]')
  await expect(row).toHaveAttribute('data-message-id', 'msg-22')
  await expect(image).toBeVisible()
  await expect(bubble).toHaveText('正在核对')
  await page.getByRole('button', { name: '追加文字' }).click()
  await expect(bubble).toHaveText('正在核对入库记录')
  await page.getByRole('button', { name: '切到失效头像' }).click()
  await expect(image).toHaveCount(0)
  await expect(row.getByRole('img', { name: '排期助手头像' })).toBeVisible()
  await expect(bubble).toHaveText('正在核对入库记录')
  await page.getByRole('button', { name: '恢复头像' }).click()
  await expect(image).toBeVisible()
  await expect(row.locator('.ym-chat-message__avatar svg')).toHaveCount(0)
  await expect(bubble).toHaveText('正在核对入库记录')
})

test('header and content slots take precedence and custom actions remain accessible', async ({ page }) => {
  const row = page.locator('#slots')
  for (const text of ['头像插槽', '昵称插槽', '时间插槽', '默认正文插槽']) {
    await expect(row.getByText(text, { exact: true })).toBeVisible()
  }
  await expect(row.locator('img')).toHaveCount(0)
  await expect(row).not.toContainText('属性')
  await page.getByLabel('整体标题').check()
  await expect(row.getByText('自定义标题', { exact: true })).toBeVisible()
  await expect(row.getByText('昵称插槽', { exact: true })).toHaveCount(0)
  await expect(row.getByText('时间插槽', { exact: true })).toHaveCount(0)
  await page.getByLabel('具名正文', { exact: true }).check()
  await expect(row.getByText('具名正文插槽', { exact: true })).toBeVisible()
  await expect(row.getByText('默认正文插槽', { exact: true })).toHaveCount(0)
  await expect(row.getByRole('button', { name: '复制消息' })).toBeVisible()
})

test('bubble radius, colors and font sizes respond to nested providers and a local size', async ({ page }) => {
  const bubble = page.locator('#inherited .ym-chat-message__bubble')
  const local = page.locator('#local .ym-chat-message__bubble')
  await expect(bubble).toHaveCSS('font-size', '16px')
  await expect(local).toHaveCSS('font-size', '12px')
  await expect(bubble).toHaveCSS('border-radius', '9px')
  await expect(bubble).toHaveCSS('border-top-style', 'solid')
  await expect(bubble).toHaveCSS('color', 'rgb(64, 52, 41)')
  await page.getByLabel('正文颜色').fill('#445566')
  await expect(bubble).toHaveCSS('color', 'rgb(68, 85, 102)')
  await page.getByLabel('深色模式').check()
  await expect(local).toHaveCSS('color', 'rgb(245, 240, 218)')
  await page.getByLabel('紧凑尺寸').check()
  await expect(bubble).toHaveCSS('font-size', '11px')
  await expect(local).toHaveCSS('font-size', '12px')
  await page.getByLabel('直角气泡').check()
  await expect(bubble).toHaveCSS('border-radius', '0px')
})
