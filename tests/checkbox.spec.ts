import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.goto('/tests/fixture/')
})

test('a checkbox supports label and keyboard activation, native submission and mixed state', async ({ page }) => {
  const cases = page.locator('#checkbox-cases')
  const box = cases.getByRole('checkbox', { name: '接收通知' })
  const events = cases.locator('#checkbox-events')
  await expect(box).toBeChecked({ indeterminate: true })
  await expect(cases.getByText('默认文案')).toHaveCount(0)
  await expect(cases.getByRole('checkbox', { name: '锁定设置' })).toBeDisabled()
  await cases.getByText('接收通知', { exact: true }).click()
  await expect(events).toHaveText('true/true/true/change')
  await expect(box).toBeChecked({ indeterminate: true })
  await cases.getByRole('button', { name: '解除半选' }).click()
  await expect(box).toBeChecked()
  const entries = await cases.locator('form').evaluate(form => Array.from(new FormData(form).entries()))
  expect(entries).toEqual([['notice', 'yes']])
  await box.press('Space')
  await expect(box).not.toBeChecked()
  await expect(events).toHaveText('false/true,false/true/change,false/change')
  const local = cases.getByRole('checkbox', { name: '保留副本' })
  await expect(local).toBeChecked()
  await local.uncheck()
  await cases.getByRole('button', { name: '恢复复选框初始值' }).click()
  await expect(local).toBeChecked()
  await expect(box).not.toBeChecked()

  const rejected = cases.getByRole('checkbox', { name: '由父级确认' })
  await rejected.click()
  await expect(cases.locator('#checkbox-rejected')).toHaveText('true')
  await expect(rejected).not.toBeChecked()
})

test('group models preserve value types, emit once per action and follow external changes', async ({ page }) => {
  const cases = page.locator('#checkbox-cases')
  const group = cases.getByRole('group', { name: '通知类型' })
  const zero = group.getByRole('checkbox', { name: '零值' })
  const original = group.getByRole('checkbox', { name: '原始渠道' })
  const boolean = group.getByRole('checkbox', { name: '布尔值' })
  await expect(group.getByText('由插槽替换')).toHaveCount(0)
  await expect(group.getByRole('checkbox', { name: '缺少标识' })).toBeDisabled()
  await expect(original).toBeChecked()
  await expect(zero).toHaveAttribute('name', 'channels')
  await expect(zero).toHaveValue('0')
  await expect(boolean).toHaveValue('false')
  await zero.check()
  await original.uncheck()
  await expect(cases.locator('#checkbox-group-model')).toHaveText('[0]')
  const changes = cases.locator('#checkbox-group-changes')
  const log = '["original",0] check 0 change; [0] uncheck "original" change'
  await expect(changes).toHaveText(log)
  await expect(cases.locator('#checkbox-group-updates')).toHaveText('[["original",0],[0]]')
  await expect(cases.locator('#checkbox-item-events')).toHaveText('true/true')
  await cases.getByRole('button', { name: '替换分组选择' }).click()
  await expect(boolean).toBeChecked()
  await expect(zero).not.toBeChecked()
  await cases.getByRole('button', { name: '切换整组禁用' }).click()
  await expect(zero).toBeDisabled()
  await expect(boolean).toBeDisabled()
  await expect(changes).toHaveText(log)
})

test('option groups render primitive and labeled options and track an uncontrolled selection', async ({ page }) => {
  const delivery = page.getByRole('group', { name: '配送方式' })
  await expect(delivery.getByRole('checkbox')).toHaveCount(5)
  await expect(delivery.getByRole('checkbox', { name: '自提' })).toBeChecked()
  await expect(delivery.getByRole('checkbox', { name: '暂停配送' })).toBeDisabled()
  await delivery.getByRole('checkbox', { name: '0' }).check()
  await delivery.getByRole('checkbox', { name: 'false' }).check()
  await delivery.getByRole('checkbox', { name: '快递' }).check()
  await delivery.getByRole('checkbox', { name: '自提' }).uncheck()
  await expect(delivery.getByRole('checkbox', { checked: true })).toHaveCount(3)
})

test('checkboxes inherit live size, palette, mode and radius through a nested provider', async ({ page }) => {
  const cases = page.locator('#checkbox-cases')
  const single = cases.getByRole('checkbox', { name: '继承单项' })
  const grouped = cases.getByRole('checkbox', { name: '继承分组' })
  const local = cases.getByRole('checkbox', { name: '局部复选框' })
  for (const box of [single, grouped]) {
    await expect(box).toHaveCSS('height', '18px')
    await expect(box).toHaveCSS('background-color', 'rgb(35, 101, 71)')
    await expect(box).toHaveCSS('border-radius', '9px')
  }
  await cases.getByLabel('复选框浅色主色').fill('#773355')
  await expect(grouped).toHaveCSS('background-color', 'rgb(119, 51, 85)')
  await cases.getByRole('button', { name: '调整复选框模式' }).click()
  await expect(single).toHaveCSS('background-color', 'rgb(153, 187, 221)')
  await expect(grouped).toHaveCSS('background-color', 'rgb(153, 187, 221)')
  await cases.getByRole('button', { name: '调整复选框尺寸圆角' }).click()
  await expect(single).toHaveCSS('height', '14px')
  await expect(grouped).toHaveCSS('height', '14px')
  await expect(grouped).toHaveCSS('border-radius', '0px')
  await cases.getByRole('button', { name: '调整分组局部尺寸' }).click()
  await expect(grouped).toHaveCSS('height', '16px')
  await expect(local).toHaveCSS('height', '13px')
})
