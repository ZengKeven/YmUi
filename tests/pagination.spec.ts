import { expect, test } from '@playwright/test'

test('defaults show numbered pages, total and page sizes and allow keyboard navigation', async ({ page }) => {
  await page.goto('/tests/fixture/')
  const nav = page.locator('#pagination-default').getByRole('navigation', { name: '分页' })
  const sizes = nav.getByRole('combobox', { name: '每页条数' })
  const current = nav.locator('[aria-current="page"]')
  await expect(nav.getByText('共 61 条')).toBeVisible()
  await expect(sizes).toHaveValue('10')
  await expect(sizes.getByRole('option', { includeHidden: true })).toHaveText(['5 条/页', '10 条/页', '20 条/页', '50 条/页'])
  await expect(nav.getByRole('button', { name: /^第 \d+ 页$/ })).toHaveCount(7)
  await expect(nav.locator('input')).toHaveCount(0)
  await expect(current).toHaveAccessibleName('第 1 页')
  await expect(nav.getByRole('button', { name: '首页' })).toBeDisabled()
  await expect(nav.getByRole('button', { name: '上一页' })).toBeDisabled()
  await nav.getByRole('button', { name: '第 4 页' }).press('Enter')
  await expect(current).toHaveAccessibleName('第 4 页')
  await nav.getByRole('button', { name: '下一页' }).click()
  await expect(current).toHaveAccessibleName('第 5 页')
  await nav.getByRole('button', { name: '上一页' }).click()
  await expect(current).toHaveAccessibleName('第 4 页')
})

test('first and last buttons navigate across omitted pages and disabled controls preserve selection', async ({ page }) => {
  await page.goto('/tests/fixture/')
  const cases = page.locator('#pagination-cases')
  const nav = cases.getByRole('navigation', { name: '分页' })
  const first = nav.getByRole('button', { name: '首页' })
  const last = nav.getByRole('button', { name: '尾页' })
  const changes = cases.locator('#pagination-changes')
  await expect(nav.getByRole('button', { name: '第 24 页' })).toBeVisible()
  await expect(nav.getByRole('button', { name: '第 12 页' })).toHaveCount(0)
  await expect(nav.getByText(/^(…|\.\.\.)$/).first()).toBeVisible()
  await last.click()
  await expect(nav.locator('[aria-current="page"]')).toHaveAccessibleName('第 24 页')
  await expect(last).toBeDisabled()
  await expect(nav.getByRole('button', { name: '下一页' })).toBeDisabled()
  await first.click()
  await expect(first).toBeDisabled()
  await nav.getByRole('button', { name: '第 2 页' }).click()
  await expect(changes).toHaveText('1→24/10,24→1/10,1→2/10')
  await cases.getByLabel('禁用分页').check()
  await expect(nav.locator('button:enabled')).toHaveCount(0)
  await expect(nav.getByRole('combobox')).toBeDisabled()
  await expect(cases.locator('#pagination-model')).toHaveText('2/10')
})

test('page size retains or clamps the page and shrinking totals update the bound model', async ({ page }) => {
  await page.goto('/tests/fixture/')
  const cases = page.locator('#pagination-cases')
  const nav = cases.getByRole('navigation', { name: '分页' })
  const sizes = nav.getByRole('combobox', { name: '每页条数' })
  const model = cases.locator('#pagination-model')
  const changes = cases.locator('#pagination-changes')
  await expect(sizes.getByRole('option', { includeHidden: true })).toHaveText(['10 条/页', '20 条/页', '50 条/页'])
  await nav.getByRole('button', { name: '第 2 页' }).click()
  await sizes.selectOption('20')
  await expect(model).toHaveText('2/20')
  await nav.getByRole('button', { name: '尾页' }).click()
  await expect(model).toHaveText('12/20')
  await sizes.selectOption('50')
  await expect(model).toHaveText('5/50')
  const userChanges = '1→2/10,2→2/20,2→12/20,12→5/50'
  await expect(changes).toHaveText(userChanges)
  await cases.getByLabel('分页数据条数').fill('51')
  await expect(nav.getByText('共 51 条')).toBeVisible()
  await expect(model).toHaveText('2/50')
  await expect(nav.locator('[aria-current="page"]')).toHaveAccessibleName('第 2 页')
  await cases.getByLabel('分页数据条数').fill('0')
  await expect(nav.getByText('共 0 条')).toBeVisible()
  await expect(model).toHaveText('1/50')
  await expect(nav.getByRole('button', { name: /^第 \d+ 页$/ })).toHaveCount(1)
  for (const name of ['首页', '上一页', '下一页', '尾页']) {
    await expect(nav.getByRole('button', { name })).toBeDisabled()
  }
  await expect(changes).toHaveText(userChanges)
})

test('buttons and page sizes inherit nested provider settings and respect a local size', async ({ page }) => {
  await page.goto('/tests/fixture/')
  const cases = page.locator('#pagination-cases')
  const nav = cases.getByRole('navigation', { name: '分页' })
  const current = nav.locator('[aria-current="page"]')
  const sizes = nav.getByRole('combobox')
  await expect(current).toHaveCSS('height', '40px')
  await expect(sizes).toHaveCSS('height', '40px')
  await expect(current).toHaveCSS('border-radius', '13px')
  await expect(sizes).toHaveCSS('border-radius', '13px')
  await expect(current).toHaveCSS('background-color', 'rgb(35, 101, 71)')
  await cases.getByLabel('分页浅色主色').fill('#773355')
  await expect(current).toHaveCSS('background-color', 'rgb(119, 51, 85)')
  await cases.getByLabel('分页深色模式').check()
  await expect(current).toHaveCSS('background-color', 'rgb(153, 187, 221)')
  await cases.getByLabel('分页紧凑配置').check()
  await expect(current).toHaveCSS('height', '24px')
  await expect(sizes).toHaveCSS('height', '24px')
  await expect(current).toHaveCSS('border-radius', '0px')
  await expect(sizes).toHaveCSS('border-radius', '0px')
  await cases.getByLabel('分页局部尺寸').check()
  await expect(current).toHaveCSS('height', '20px')
  await expect(sizes).toHaveCSS('height', '20px')
})
