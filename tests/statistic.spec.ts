import { expect, test, type Locator, type Page } from '@playwright/test'

const fixture = '/tests/fixture/statistic.html'
const valueOf = (component: Locator) => component.locator('.ym-statistic__value')

async function openAnimationFixture(page: Page) {
  await page.clock.install({ time: new Date('2026-01-01T12:00:00Z') })
  await page.goto(fixture)
  await expect(valueOf(page.locator('#animated'))).toHaveText('25')
  await page.clock.pauseAt(new Date('2026-01-01T12:01:00Z'))
}

test('numbers preserve their sign and precision, with configurable grouping and custom formatting', async ({ page }) => {
  await page.goto(fixture)
  await expect(valueOf(page.locator('#default'))).toHaveText('0')
  const value = valueOf(page.locator('#formatted'))
  await expect(value).toHaveText('-1,234,567.895')
  await page.getByRole('combobox', { name: '精度' }).selectOption('2')
  await expect(value).toHaveText('-1,234,567.90')
  await page.getByRole('combobox', { name: '分组符' }).selectOption('_')
  await expect(value).toHaveText('-1_234_567.90')
  await page.getByRole('combobox', { name: '分组符' }).selectOption('')
  await expect(value).toHaveText('-1234567.90')
  await page.getByRole('spinbutton', { name: '金额' }).fill('1234.5')
  await expect(value).toHaveText('1234.50')
  await page.getByRole('checkbox', { name: '自定义格式' }).check()
  await expect(value).toHaveText('金额 1234.5')
})

test('named slots override their text props and the trend shares the chosen affix position', async ({ page }) => {
  await page.goto(fixture)
  const slots = page.locator('#slots')
  for (const text of ['当月库存', '约', '箱', '可用', '已盘点']) {
    await expect(slots.getByText(text, { exact: true })).toBeVisible()
  }
  await expect(slots).not.toContainText('原始')
  const fields = page.locator('#fields')
  await expect(fields).toContainText('昨日订单')
  await expect(fields).toContainText('已确认')
  const value = valueOf(fields)
  const trend = fields.locator('.ym-icon')
  await expect(trend).toHaveAttribute('data-name', 'trend-up')
  expect((await trend.boundingBox())!.x).toBeLessThan((await value.boundingBox())!.x)
  await page.getByRole('textbox', { name: '前缀' }).fill('共')
  await expect(trend).toHaveCount(0)
  await page.getByRole('combobox', { name: '位置' }).selectOption('right')
  await page.getByRole('combobox', { name: '趋势' }).selectOption('decrease')
  await expect(trend).toHaveAttribute('data-name', 'trend-down')
  expect((await trend.boundingBox())!.x).toBeGreaterThan((await value.boundingBox())!.x)
  await expect(slots.locator('.ym-icon')).toHaveCount(0)

  await page.getByRole('checkbox', { name: '显示加载' }).check()
  await expect(fields.locator('.ym-loading')).toBeVisible()
  await expect(value).toBeHidden()
  await expect(fields).toContainText('昨日订单')
  await page.getByRole('checkbox', { name: '显示加载' }).uncheck()
  await expect(value).toHaveText('120')
})

test('start() replays a manual animation from its start value and removing animation cancels outstanding frames', async ({ page }) => {
  await openAnimationFixture(page)
  const value = valueOf(page.locator('#animated'))
  const replay = page.getByRole('button', { name: '手动重播' })
  await page.clock.runFor(1100)
  await expect(value).toHaveText('25')
  await replay.click()
  await page.clock.runFor(200)
  const middle = Number(await value.innerText())
  expect(middle).toBeGreaterThan(25)
  expect(middle).toBeLessThan(125)
  await page.clock.runFor(1000)
  await expect(value).toHaveText('125')
  await replay.click()
  await expect(value).toHaveText('25')
  await page.clock.runFor(100)
  await page.getByRole('checkbox', { name: '配置动画' }).uncheck()
  await expect(value).toHaveText('125')
  await page.getByRole('spinbutton', { name: '目标值' }).fill('-7')
  await page.clock.runFor(1500)
  await expect(value).toHaveText('-7')
})

test('automatic playback can count down and retarget in flight without jumping back or finishing at the old target', async ({ page }) => {
  await openAnimationFixture(page)
  await page.getByRole('checkbox', { name: '挂载自动动画' }).check()
  const down = valueOf(page.locator('#onmount'))
  await expect(down).toHaveText('100.75')
  await page.clock.runFor(200)
  const middleDown = Number(await down.innerText())
  expect(middleDown).toBeLessThan(100)
  expect(middleDown).toBeGreaterThan(-150)
  await page.clock.runFor(1000)
  await expect(down).toHaveText('-150')

  const value = valueOf(page.locator('#animated'))
  await page.getByRole('checkbox', { name: '自动播放' }).check()
  await page.clock.runFor(160)
  const beforeChange = Number(await value.innerText())
  expect(beforeChange).toBeGreaterThan(25)
  expect(beforeChange).toBeLessThan(125)
  await page.getByRole('spinbutton', { name: '目标值' }).fill('-100')
  await expect(value).toHaveText(String(beforeChange))
  await page.clock.runFor(240)
  const redirected = Number(await value.innerText())
  expect(redirected).toBeLessThan(beforeChange)
  expect(redirected).toBeGreaterThan(-100)
  await page.clock.runFor(1200)
  await expect(value).toHaveText('-100')
})

test('zero duration and reduced motion settle on the target immediately, including preference changes during playback', async ({ page }) => {
  await openAnimationFixture(page)
  const value = valueOf(page.locator('#animated'))
  const replay = page.getByRole('button', { name: '手动重播' })
  const duration = page.getByRole('spinbutton', { name: '时长' })
  await duration.fill('0')
  await replay.click()
  await expect(value).toHaveText('125')
  await duration.fill('1000')
  await replay.click()
  await page.clock.runFor(160)
  expect(Number(await value.innerText())).toBeLessThan(125)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(value).toHaveText('125')
  await replay.click()
  await expect(value).toHaveText('125')
})

test('nested providers update size, palette, mode and loading radius with local size and color overrides', async ({ page }) => {
  await page.goto(fixture)
  const inherited = valueOf(page.locator('#inherited'))
  const plain = valueOf(page.locator('#default-color'))
  const local = valueOf(page.locator('#local'))
  const localFont = await local.evaluate(el => getComputedStyle(el).fontSize)
  let lastSize = 0
  for (const size of ['extra-small', 'small', 'medium', 'large']) {
    await page.getByRole('combobox', { name: '全局尺寸' }).selectOption(size)
    const currentSize = await inherited.evaluate(el => parseFloat(getComputedStyle(el).fontSize))
    expect(currentSize).toBeGreaterThan(lastSize)
    lastSize = currentSize
    await expect(local).toHaveCSS('font-size', localFont)
  }
  await expect(inherited).toHaveCSS('color', 'rgb(69, 103, 137)')
  await expect(plain).toHaveCSS('color', 'rgb(36, 53, 70)')
  await page.getByLabel('主题主色').fill('#683369')
  await expect(inherited).toHaveCSS('color', 'rgb(104, 51, 105)')
  await page.getByRole('checkbox', { name: '深色模式' }).check()
  await expect(inherited).toHaveCSS('color', 'rgb(170, 204, 221)')
  await expect(plain).toHaveCSS('color', 'rgb(227, 231, 234)')
  await expect(local).toHaveCSS('color', 'rgb(36, 104, 36)')
  await page.getByRole('checkbox', { name: '显示加载' }).check()
  const loading = page.locator('#inherited .ym-statistic__loading')
  await expect(loading).toHaveCSS('border-top-left-radius', '5px')
  await page.getByRole('checkbox', { name: '使用直角' }).check()
  await expect(loading).toHaveCSS('border-top-left-radius', '0px')
})
