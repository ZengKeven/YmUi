import { expect, test } from '@playwright/test'

test('space inherits the provider size and accepts local presets and zero', async ({ page }) => {
  await page.goto('/tests/fixture/')
  const space = page.locator('#space-layout')
  const size = page.getByLabel('组件间距')
  await expect(space).toHaveCSS('display', 'inline-flex')
  await expect(space).toHaveCSS('gap', '16px')
  await expect(space).toHaveCSS('flex-direction', 'row')
  await expect(space).toHaveCSS('flex-wrap', 'nowrap')
  await page.getByLabel('全局间距尺寸').selectOption('large')
  await expect(space).toHaveCSS('gap', '24px')
  await size.selectOption({ label: '极小' })
  await expect(space).toHaveCSS('gap', '4px')
  await size.selectOption({ label: '无间距' })
  await expect(space).toHaveCSS('gap', '0px')
  await size.selectOption({ label: '继承' })
  await expect(space).toHaveCSS('gap', '24px')
})

test('space wraps horizontal items with separate row and column gaps and aligns their edges', async ({ page }) => {
  await page.goto('/tests/fixture/')
  const space = page.locator('#space-layout')
  await page.getByLabel('组件间距').selectOption({ label: '分轴' })
  await page.getByLabel('间距换行').check()
  await expect(space).toHaveCSS('flex-wrap', 'wrap')
  const items = space.locator('.space-case-item')
  const [a, b, c] = await items.evaluateAll(nodes => nodes.map(el => el.getBoundingClientRect().toJSON()))
  expect(b.left - a.right).toBe(24)
  expect(b.bottom).toBe(a.bottom)
  expect(c.left).toBe(a.left)
  expect(c.top - b.bottom).toBe(8)

  await page.getByLabel('纵向间距').check()
  await expect(space).toHaveCSS('flex-direction', 'column')
  await expect(space).toHaveCSS('flex-wrap', 'nowrap')
  const [first, second] = await items.evaluateAll(nodes => nodes.map(el => el.getBoundingClientRect().toJSON()))
  expect(second.top - first.bottom).toBe(8)
})

test('space separates text, conditional and keyed children while preserving their input state', async ({ page }) => {
  await page.goto('/tests/fixture/')
  const space = page.locator('#space-dynamic')
  await expect(space).toHaveCSS('gap', '16px')
  await expect(space).toHaveText(/^\s*首项\s*·\s*可选\s*·\s*甲\s*·\s*乙\s*$/)
  await space.getByLabel('甲').fill('保留输入')
  await page.getByLabel('可选间距项').uncheck()
  await page.getByRole('button', { name: '反转间距项' }).click()
  await expect(space).toHaveText(/^\s*首项\s*·\s*乙\s*·\s*甲\s*$/)
  await expect(space.getByLabel('甲')).toHaveValue('保留输入')

  const slot = page.getByLabel('自定义分隔符')
  await slot.check()
  const buttons = space.getByRole('button')
  await expect(buttons).toHaveText(['分隔 0', '分隔 0'])
  await buttons.last().click()
  await expect(buttons).toHaveText(['分隔 1', '分隔 1'])
  await expect(space).not.toContainText('·')
  await slot.uncheck()
  await expect(space).toHaveText(/^\s*首项\s*·\s*乙\s*·\s*甲\s*$/)
  await page.getByRole('button', { name: '清空间距项' }).click()
  await expect(space).toHaveText('首项')
})
