import { expect, test } from '@playwright/test'

test('standalone loading shows inline by default and preserves wrapped content across delayed updates', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-01-01T12:00:00Z') })
  await page.goto('/tests/fixture/')
  const inline = page.locator('#inline-loading').getByRole('status')
  await expect(inline).toHaveAccessibleName('加载中')
  await expect(inline.locator('svg.ym-icon[data-name="loading"]')).toBeVisible()

  await page.clock.pauseAt(new Date('2026-01-01T12:01:00Z'))
  const toggle = page.getByLabel('panel loading')
  const panel = page.locator('#panel-loading')
  const status = panel.getByRole('status')
  const content = panel.getByLabel('panel content')
  await content.fill('unsaved edits')
  await toggle.check()
  await expect(panel).toHaveAttribute('aria-busy', 'true')
  await page.clock.runFor(150)
  await expect(status).toHaveCount(0)
  await toggle.uncheck()
  await page.clock.runFor(300)
  await expect(status).toHaveCount(0)

  await toggle.check()
  await page.clock.runFor(300)
  await expect(status).toHaveText('Updating')
  await expect(status).toHaveCSS('position', 'absolute')
  await toggle.uncheck()
  await expect(panel).toHaveAttribute('aria-busy', 'false')
  await expect(status).toHaveCount(0)
  await expect(content).toHaveValue('unsaved edits')
})

test('inline and covered loading follow the provider size and radius as they change', async ({ page }) => {
  await page.goto('/tests/fixture/')
  const inline = page.locator('#inline-loading svg')
  const fixed = page.locator('#fixed-loading svg')
  const mask = page.locator('#panel-loading').getByRole('status')
  await page.getByLabel('panel loading').check()
  await expect(inline).toHaveCSS('width', '24px')
  await expect(fixed).toHaveCSS('width', '19px')
  await expect(mask).toHaveCSS('border-radius', '12px')
  await page.getByLabel('compact loading settings').check()
  await expect(inline).toHaveCSS('width', '14px')
  await expect(fixed).toHaveCSS('width', '19px')
  await expect(mask).toHaveCSS('border-radius', '0px')
})

test('attached loading follows its source provider and releases the fullscreen scroll lock', async ({ page }) => {
  await page.goto('/tests/fixture/')
  const busy = page.getByLabel('busy', { exact: true })
  const status = page.locator('#target').getByRole('status')
  await busy.check()
  await expect(status).toHaveText('attached')
  await expect(status).toHaveCSS('color', 'rgb(136, 187, 238)')
  await expect(status).toHaveCSS('z-index', '41')
  const spinner = status.locator('svg')
  await expect(spinner).toHaveCSS('width', '24px')
  await expect(status).toHaveCSS('border-radius', '12px')
  const compact = page.getByLabel('compact loading settings')
  await compact.check()
  await expect(spinner).toHaveCSS('width', '14px')
  await expect(status).toHaveCSS('border-radius', '0px')
  await compact.uncheck()
  await expect(status).toHaveCSS('border-radius', '12px')
  await page.locator('#switch-mode').click()
  await expect(status).toHaveCSS('color', 'rgb(34, 85, 136)')
  await page.getByLabel('fullscreen').check()
  await expect(status).toHaveCSS('position', 'fixed')
  await expect(status).toHaveCSS('border-radius', '0px')
  await expect(spinner).toHaveCSS('width', '24px')
  await expect(page.locator('body')).toHaveCSS('overflow', 'hidden')
  // Simulate the asynchronous operation completing underneath the overlay.
  await busy.evaluate(input => (input as HTMLInputElement).click())
  await expect(status).toHaveCount(0)
  await expect(page.locator('body')).not.toHaveCSS('overflow', 'hidden')
})
