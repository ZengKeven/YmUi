import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.goto('/tests/fixture/dropdown.html')
})

test('hover opens the default trigger, retains the menu over its panel and runs zero-valued commands once', async ({ page }) => {
  const trigger = page.getByRole('button', { name: '更多操作' })
  const menu = page.getByRole('menu')
  const refresh = menu.getByRole('menuitem', { name: '刷新当前页' })
  await expect(trigger).toHaveAttribute('aria-haspopup', 'menu')
  await expect(menu).toBeHidden()
  await trigger.hover()
  await expect(trigger).toHaveAttribute('aria-expanded', 'true')
  await expect(menu.getByRole('menuitem')).toHaveCount(4)
  await expect(refresh.locator('svg')).toBeVisible()
  await expect(menu.getByRole('separator')).toHaveCount(1)
  await refresh.hover()
  await expect(refresh).toBeVisible()
  await page.getByRole('button', { name: '外部按钮' }).hover()
  await expect(menu).toBeHidden()
  await trigger.hover()
  await refresh.click()
  await expect(menu).toBeHidden()
  await expect(page.locator('#events')).toHaveText('0/click/true')
})

test('keyboard commands skip disabled items, support Home and End and restore the attached trigger', async ({ page }) => {
  const trigger = page.getByRole('button', { name: '页签操作' })
  const menu = page.locator('#commands').getByRole('menu')
  const items = menu.getByRole('menuitem')
  await trigger.press('ArrowDown')
  await expect(items.nth(0)).toBeFocused()
  await expect(items.nth(0).locator('strong')).toHaveText('1. 刷新当前页')
  await expect(items.nth(1)).toBeDisabled()
  await page.keyboard.press('ArrowDown')
  await expect(items.nth(2)).toBeFocused()
  await page.keyboard.press('End')
  await expect(items.last()).toBeFocused()
  await page.keyboard.press('Home')
  await expect(items.first()).toBeFocused()
  await page.keyboard.press('Space')
  await expect(menu).toBeHidden()
  await expect(trigger).toBeFocused()
  await trigger.press('ArrowUp')
  await expect(items.last()).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.locator('#events')).toHaveText('0/click/true,all/click/true')
  await trigger.press('ArrowDown')
  await page.keyboard.press('Escape')
  await expect(menu).toBeHidden()
  await expect(trigger).toBeFocused()
  await trigger.press('ArrowDown')
  await page.keyboard.press('Tab')
  await expect(menu).toBeHidden()
  await expect(page.getByRole('button', { name: '账号后一个按钮' })).toBeFocused()
})

test('click menus respect disabled commands, keep-open configuration and outside dismissal', async ({ page }) => {
  const trigger = page.getByRole('button', { name: '页签操作' })
  const menu = page.getByRole('menu')
  await page.getByLabel('选择后保留菜单').check()
  await trigger.click()
  await menu.getByRole('menuitem', { name: /关闭其他页签/ }).click({ force: true })
  await expect(page.locator('#events')).toBeEmpty()
  await menu.getByRole('menuitem', { name: /关闭右侧页签/ }).click()
  await expect(menu).toBeVisible()
  await expect(page.locator('#events')).toHaveText('right/click/true')
  await page.getByRole('button', { name: '外部按钮' }).click()
  await expect(menu).toBeHidden()
  await page.getByLabel('禁用操作').check()
  await trigger.click({ force: true })
  await expect(menu).toBeHidden()
})

test('right-click requests are controlled and focus triggers honor initial visibility', async ({ page }) => {
  const trigger = page.getByRole('button', { name: '账户操作', exact: true })
  const menu = page.getByRole('menu')
  await trigger.click({ button: 'right' })
  await expect(menu).toBeHidden()
  await expect(page.locator('#updates')).toHaveText('true')
  await expect(page.locator('#changes')).toHaveText('true')
  await page.getByLabel('接受打开请求').check()
  await trigger.click({ button: 'right' })
  await menu.getByRole('menuitem', { name: '退出登录' }).click()
  await expect(menu).toBeHidden()
  await expect(page.locator('#events')).toHaveText('logout/click/true')
  await expect(page.locator('#updates')).toHaveText('true,true,false')
  await expect(page.locator('#changes')).toHaveText('true,true,false')
  for (const key of ['Enter', 'Space']) {
    await trigger.press(key)
    await expect(menu.getByRole('menuitem', { name: '修改密码' })).toBeFocused()
    await page.keyboard.press('Escape')
    await expect(trigger).toBeFocused()
  }
  await page.getByRole('button', { name: '外部切换' }).click()
  await expect(menu).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(menu).toBeHidden()
  await page.getByLabel('初始打开用例').check()
  await expect(menu).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(menu).toBeHidden()
  await page.getByRole('button', { name: '聚焦账户' }).focus()
  await expect(menu).toBeVisible()
})

test('dropdown inherits disabled forms and honors an explicit enabled override for the trigger and commands', async ({ page }) => {
  const inherited = page.getByRole('button', { name: '继承表单禁用' })
  const override = page.getByRole('button', { name: '允许账户操作' })
  await expect(inherited).toBeDisabled()
  await inherited.click({ force: true })
  await expect(page.getByRole('menu')).toBeHidden()
  await expect(inherited).toHaveAttribute('aria-expanded', 'false')
  await expect(override).toBeEnabled()
  await override.press('Enter')
  const command = page.getByRole('menuitem', { name: '修改密码' })
  await expect(command).toBeFocused()
  await command.press('Enter')
  await expect(page.locator('#events')).toHaveText('password/click/true')
  await expect(override).toBeFocused()
})

test('an attached menu inherits the live source theme, nested radius and locally overridden size', async ({ page }) => {
  await page.getByLabel('展示主题用例').check()
  const panel = page.locator('#commands .ym-popup__panel:popover-open')
  const item = panel.getByRole('menuitem', { name: '修改密码' })
  await expect(item).toBeVisible()
  await expect(panel).toHaveCSS('border-radius', '7px')
  await expect(panel).toHaveCSS('background-color', 'rgb(232, 240, 247)')
  await expect(item).toHaveCSS('color', 'rgb(51, 68, 85)')
  await page.getByLabel('浅色表面').fill('#d7ebe4')
  await expect(panel).toHaveCSS('background-color', 'rgb(215, 235, 228)')
  await page.getByLabel('深色模式').check()
  await expect(panel).toHaveCSS('background-color', 'rgb(36, 52, 72)')
  await expect(item).toHaveCSS('color', 'rgb(228, 241, 242)')
  await page.getByLabel('内层直角').check()
  await expect(panel).toHaveCSS('border-radius', '0px')
  for (const [size, font] of [['extra-small', '11px'], ['small', '12px'], ['medium', '14px'], ['large', '16px']]) {
    await page.getByLabel('全局尺寸').selectOption(size)
    await expect(item).toHaveCSS('font-size', font)
  }
  await page.getByLabel('局部小号').check()
  await expect(item).toHaveCSS('font-size', '12px')
})
