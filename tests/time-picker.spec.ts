import { expect, test, type Locator, type Page } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.goto('/tests/fixture/time-picker.html')
})

function option(panel: Locator, column: string, value: string) {
  return panel.getByRole('listbox', { name: column, exact: true }).getByRole('option', { name: value, exact: true })
}

function formValue(page: Page, name: string) {
  return page.locator('#schedule').evaluate((form, key) => new FormData(form as HTMLFormElement).get(key), name)
}

test('single times commit all three columns once and unconfirmed changes leave the form untouched', async ({ page }) => {
  const field = page.getByRole('combobox', { name: '提醒时间' })
  const panel = page.getByRole('dialog', { name: '选择时间', exact: true })
  const confirm = panel.getByRole('button', { name: '确定' })
  await expect(field).toHaveValue('')
  await field.click()
  await expect(field).toHaveAttribute('aria-expanded', 'true')
  await expect(panel.getByRole('listbox')).toHaveCount(3)
  await expect(panel.getByRole('listbox', { name: '小时' }).getByRole('option')).toHaveCount(24)
  await expect(panel.getByRole('listbox', { name: '分钟' }).getByRole('option')).toHaveCount(60)
  await expect(option(panel, '秒钟', '00')).toHaveAttribute('aria-selected', 'true')
  await option(panel, '小时', '23').click()
  await option(panel, '分钟', '45').click()
  await option(panel, '秒钟', '59').click()
  expect(await formValue(page, 'reminder')).toBe('')
  await expect(page.locator('#changes')).toHaveText('[]')
  await confirm.click()
  await expect(panel).toBeHidden()
  await expect(field).toHaveValue('23:45:59')
  expect(await formValue(page, 'reminder')).toBe('23:45:59')
  await field.click()
  await confirm.click()
  await expect(page.locator('#updates')).toHaveText('["23:45:59"]')
  await expect(page.locator('#changes')).toHaveText('["23:45:59"]')
  await field.click()
  await option(panel, '小时', '04').click()
  await page.getByRole('button', { name: '其他操作' }).click()
  await expect(panel).toBeHidden()
  await expect(field).toHaveValue('23:45:59')
  await page.getByRole('button', { name: '设置提醒' }).click()
  await expect(field).toHaveValue('23:01:02')
  await field.click()
  await expect(option(panel, '分钟', '01')).toHaveAttribute('aria-selected', 'true')
})

test('range panels edit both endpoints and commit ordered minute-precision times including equal endpoints', async ({ page }) => {
  const fields = page.getByRole('group', { name: '工作时段' })
  const start = fields.getByRole('combobox', { name: '开始时间' })
  const end = fields.getByRole('combobox', { name: '结束时间' })
  const panel = page.getByRole('dialog', { name: '选择时间范围' })
  const left = panel.getByRole('group', { name: '开始时间' })
  const right = panel.getByRole('group', { name: '结束时间' })
  const confirm = panel.getByRole('button', { name: '确定' })
  await expect(start).toHaveValue('09:00')
  await expect(end).toHaveValue('17:30')
  await end.click()
  await expect(panel.getByRole('listbox')).toHaveCount(4)
  await expect(panel.getByRole('listbox', { name: '秒钟' })).toHaveCount(0)
  await option(left, '小时', '19').click()
  await option(right, '小时', '08').click()
  expect(await formValue(page, 'shift')).toBe('09:00 至 17:30')
  await expect(page.locator('#range-changes')).toHaveText('[]')
  await confirm.click()
  await expect(panel).toBeHidden()
  await expect(start).toHaveValue('08:30')
  await expect(end).toHaveValue('19:00')
  expect(await formValue(page, 'shift')).toBe('08:30 至 19:00')
  await start.click()
  await option(right, '小时', '08').click()
  await option(right, '分钟', '30').click()
  await confirm.click()
  await expect(end).toHaveValue('08:30')
  await end.click()
  await confirm.click()
  const events = '[["08:30","19:00"],["08:30","08:30"]]'
  await expect(page.locator('#range-updates')).toHaveText(events)
  await expect(page.locator('#range-changes')).toHaveText(events)
  await page.getByRole('button', { name: '重置工作时段' }).click()
  await expect(start).toHaveValue('')
  await expect(end).toHaveValue('')
  await end.click()
  await option(right, '小时', '13').click()
  await expect(option(left, '小时', '13')).toHaveAttribute('aria-selected', 'true')
  await expect(start).toHaveValue('13:00')
  await confirm.click()
  await expect(start).toHaveValue('13:00')
  await expect(end).toHaveValue('13:00')
})

test('keyboard navigation edits the active endpoint and Escape discards its draft', async ({ page }) => {
  const fields = page.getByRole('group', { name: '工作时段' })
  const end = fields.getByRole('combobox', { name: '结束时间' })
  const panel = page.getByRole('dialog', { name: '选择时间范围' })
  const right = panel.getByRole('group', { name: '结束时间' })
  await end.press('ArrowDown')
  await page.keyboard.press('End')
  await expect(option(right, '小时', '23')).toHaveAttribute('aria-selected', 'true')
  await page.keyboard.press('ArrowRight')
  await page.keyboard.press('Home')
  await page.keyboard.press('ArrowDown')
  await expect(option(right, '分钟', '01')).toHaveAttribute('aria-selected', 'true')
  await page.keyboard.press('Escape')
  await expect(panel).toBeHidden()
  await expect(end).toBeFocused()
  await expect(end).toHaveValue('17:30')
  await expect(page.locator('#range-updates')).toHaveText('[]')
  await end.press('Enter')
  await expect(option(right, '分钟', '30')).toHaveAttribute('aria-selected', 'true')
  await page.keyboard.press('ArrowUp')
  await page.keyboard.press('ArrowRight')
  await page.keyboard.press('Tab')
  const confirm = panel.getByRole('button', { name: '确定' })
  await expect(confirm).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(end).toHaveValue('16:30')
})

test('an uncontrolled range resets to its form default and controlled and disabled fields respect ownership', async ({ page }) => {
  const fields = page.getByRole('group', { name: '值班时段' })
  const start = fields.getByRole('combobox', { name: '开始时间' })
  const range = page.getByRole('dialog', { name: '选择时间范围' })
  await start.click()
  await option(range.getByRole('group', { name: '开始时间' }), '分钟', '55').click()
  await range.getByRole('button', { name: '确定' }).click()
  expect(await formValue(page, 'duty')).toBe('08:55:00 至 09:30:00')
  await start.click()
  await page.locator('#schedule').evaluate(form => (form as HTMLFormElement).reset())
  await expect(range).toBeHidden()
  await expect(start).toHaveValue('08:15:00')
  expect(await formValue(page, 'duty')).toBe('08:15:00 至 09:30:00')

  const fixed = page.getByRole('combobox', { name: '固定时间' })
  const single = page.getByRole('dialog', { name: '选择时间', exact: true })
  await fixed.click()
  await option(single, '秒钟', '12').click()
  await single.getByRole('button', { name: '确定' }).click()
  await expect(fixed).toHaveValue('12:00:00')
  const disabled = page.getByRole('combobox', { name: '禁用时间' })
  await expect(disabled).toBeDisabled()
  await expect(disabled).toHaveAttribute('placeholder', '暂不可选')
  await expect(page.locator('.ym-input').filter({ has: disabled })).toHaveCSS('border-top-color', 'rgba(0, 0, 0, 0)')
  const controlled = page.getByRole('group', { name: '工作时段' })
  await controlled.getByRole('combobox', { name: '开始时间' }).click()
  await option(range.getByRole('group', { name: '结束时间' }), '小时', '18').click()
  // 直接更新外部状态，避免点击控件先触发浮层的外部关闭。
  await page.getByLabel('禁用工作时段').evaluate(input => (input as HTMLInputElement).click())
  await expect(range).toBeHidden()
  await expect(controlled.getByRole('combobox', { name: '结束时间' })).toBeDisabled()
  expect(await formValue(page, 'shift')).toBeNull()
  await page.getByLabel('禁用工作时段').uncheck()
  await expect(controlled.getByRole('combobox', { name: '结束时间' })).toHaveValue('17:30')
})

test('nested configuration and local size apply to the trigger and to an externally mounted panel', async ({ page }) => {
  const field = page.getByRole('combobox', { name: '继承配置' })
  const local = page.getByRole('combobox', { name: '覆盖尺寸' })
  const source = page.locator('.ym-input').filter({ has: field })
  const override = page.locator('.ym-input').filter({ has: local })
  const panel = page.locator('#time-overlays .ym-time-picker__panel')
  const selected = option(panel, '小时', '08')
  await expect(source).toHaveCSS('height', '40px')
  await expect(override).toHaveCSS('height', '20px')
  await field.click()
  await expect(panel).toHaveCSS('border-radius', '10px')
  await expect(panel).toHaveCSS('background-color', 'rgb(244, 241, 223)')
  await expect(selected).toHaveCSS('background-color', 'rgb(33, 97, 67)')
  const largeRow = (await selected.boundingBox())!.height
  await page.getByLabel('强调色').evaluate((input: HTMLInputElement) => {
    input.value = '#8b3642'
    input.dispatchEvent(new Event('input', { bubbles: true }))
  })
  await expect(selected).toHaveCSS('background-color', 'rgb(139, 54, 66)')
  await page.getByLabel('深色', { exact: true }).evaluate(input => (input as HTMLInputElement).click())
  await expect(panel).toHaveCSS('background-color', 'rgb(35, 33, 54)')
  await expect(selected).toHaveCSS('background-color', 'rgb(209, 201, 250)')
  await page.getByLabel('紧凑直角').evaluate(input => (input as HTMLInputElement).click())
  await expect(source).toHaveCSS('height', '24px')
  await expect(source).toHaveCSS('border-radius', '0px')
  await expect(panel).toHaveCSS('border-radius', '0px')
  await expect.poll(async () => (await selected.boundingBox())?.height).toBeLessThan(largeRow)
  await expect(override).toHaveCSS('height', '20px')
})
