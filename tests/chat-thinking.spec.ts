import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.goto('/tests/fixture/chat-thinking.html')
})

test('keyboard disclosure preserves streaming text and the chosen state when thinking finishes', async ({ page }) => {
  const thinking = page.locator('#basic .ym-chat-thinking')
  const toggle = thinking.getByRole('button')
  await expect(toggle).toHaveAccessibleName('思考中')
  await expect(toggle).toHaveAttribute('aria-expanded', 'true')
  const panelId = await toggle.getAttribute('aria-controls')
  expect(panelId).toBeTruthy()
  const panel = thinking.locator(`[id="${panelId}"]`)
  await expect(panel).toHaveText('正在读取单据。')
  await toggle.press('Enter')
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await expect(panel).toBeHidden()
  const updated = '已读取单据。\n<em>数量 12</em>'
  await page.getByLabel('过程文字').fill(updated)
  await page.getByLabel('完成思考').check()
  await expect(toggle).toHaveAccessibleName('思考完成')
  await expect(panel).toBeHidden()
  await toggle.press('Space')
  await expect(toggle).toBeFocused()
  await expect(toggle).toHaveAttribute('aria-expanded', 'true')
  await expect(panel).toBeVisible()
  expect(await panel.textContent()).toBe(updated)
  await expect(panel.locator('em')).toHaveCount(0)
  await expect(page.locator('#changes')).toHaveText('[true,false]')
})

test('a controlled panel waits for acceptance and retains the custom title', async ({ page }) => {
  const thinking = page.locator('#controlled')
  const toggle = thinking.getByRole('button', { name: '核对进度' })
  const text = thinking.getByText('已核对仓库编号。')
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await toggle.click()
  await expect(page.locator('#requests')).toHaveText('[false]')
  await expect(text).toBeHidden()
  await page.getByRole('button', { name: '应用折叠请求' }).click()
  await expect(toggle).toHaveAttribute('aria-expanded', 'true')
  await expect(text).toBeVisible()
  await toggle.click()
  await expect(page.locator('#requests')).toHaveText('[false,true]')
  await expect(text).toBeVisible()
  await page.getByRole('button', { name: '应用折叠请求' }).click()
  await expect(text).toBeHidden()
})

test('content slots follow precedence and initial collapse only affects its own panel', async ({ page }) => {
  const section = page.locator('#slots')
  const buttons = section.getByRole('button')
  await expect(buttons.nth(0)).toHaveAttribute('aria-expanded', 'false')
  await expect(buttons.nth(1)).toHaveAttribute('aria-expanded', 'true')
  await expect(section.getByText('默认正文')).toBeVisible()
  await buttons.first().click()
  await expect(section.locator('strong')).toHaveText('具名插槽')
  await expect(section.getByText('默认插槽')).toHaveCount(0)
  await expect(section.getByText('属性正文')).toHaveCount(0)
  expect(await buttons.nth(0).getAttribute('aria-controls')).not.toBe(await buttons.nth(1).getAttribute('aria-controls'))
})

test('message blocks follow the message status until explicitly complete, and copy only the answer', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  const message = page.locator('#message article')
  const panel = message.locator('.ym-chat-thinking')
  const toggle = panel.getByRole('button')
  const copy = message.getByRole('button', { name: '复制' })
  await expect(toggle).toHaveAccessibleName('思考中')
  await expect(message.getByText('加载中', { exact: true })).toHaveCount(0)
  await expect(copy).toBeDisabled()
  const status = page.getByLabel('消息状态')
  await status.selectOption('complete')
  await expect(toggle).toHaveAccessibleName('思考完成')
  await status.selectOption('streaming')
  await expect(toggle).toHaveAccessibleName('思考中')
  await expect(message.getByText('加载中', { exact: true })).toHaveCount(0)
  await toggle.click()
  await page.getByRole('button', { name: '追加最终回复' }).click()
  await expect(message).toHaveAttribute('data-status', 'streaming')
  await expect(toggle).toHaveAccessibleName('思考完成')
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await expect(message.getByRole('heading', { name: '收货清单' })).toBeVisible()
  await toggle.click()
  await expect(panel.getByText('已核对送货单。')).toBeVisible()
  await expect(message.locator('.ym-chat-message__bubble')).toHaveText(/已核对送货单。\s*已就绪\s*收货清单/)
  await copy.click()
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('已就绪\n## 收货清单')
})

test('switching the displayed message starts its own disclosure state', async ({ page }) => {
  const message = page.locator('#message article')
  const toggle = message.locator('.ym-chat-thinking').getByRole('button')
  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await page.getByLabel('显示下一条消息').check()
  await expect(message).toHaveAttribute('data-message-id', 'next')
  await expect(toggle).toHaveAccessibleName('思考完成')
  await expect(toggle).toHaveAttribute('aria-expanded', 'true')
  await expect(message.getByText('已读取下一张单据。')).toBeVisible()
})

test('thinking panels inherit nested size, theme, mode and radius with a local size override', async ({ page }) => {
  const inherited = page.locator('#inherited .ym-chat-thinking')
  const local = page.locator('#local .ym-chat-thinking')
  const text = inherited.getByText('配置随面板更新')
  await expect(inherited).toHaveCSS('font-size', '16px')
  await expect(local).toHaveCSS('font-size', '12px')
  await expect(inherited).toHaveCSS('border-radius', '9px')
  await expect(text).toHaveCSS('color', 'rgb(64, 52, 41)')
  await page.getByLabel('正文颜色').fill('#445566')
  await expect(text).toHaveCSS('color', 'rgb(68, 85, 102)')
  await page.getByLabel('深色模式').check()
  await expect(text).toHaveCSS('color', 'rgb(245, 240, 218)')
  await page.getByLabel('紧凑尺寸').check()
  await expect(inherited).toHaveCSS('font-size', '11px')
  await expect(local).toHaveCSS('font-size', '12px')
  await page.getByLabel('直角面板').check()
  await expect(local).toHaveCSS('border-radius', '0px')
})
