import { expect, test } from '@playwright/test'

test('steps start on the first item and keyboard selection advances an indexed workflow', async ({ page }) => {
  await page.goto('/tests/fixture/')
  const list = page.locator('#steps-default').getByRole('list')
  const items = list.getByRole('listitem')
  await expect(items).toHaveCount(3)
  await expect(items.nth(0)).toHaveAttribute('aria-current', 'step')
  await expect(items.nth(0).locator('.ym-steps__marker')).toHaveText('1')
  await expect(items.nth(2).locator('.ym-steps__marker')).toHaveText('3')
  await list.getByRole('button', { name: '审核' }).press('Enter')
  await expect(items.nth(0)).toHaveAttribute('data-status', 'finish')
  await expect(items.nth(0).locator('svg')).toBeVisible()
  await expect(items.nth(1)).toHaveAttribute('aria-current', 'step')
  await expect(items.nth(1)).toHaveAttribute('data-status', 'process')
  await expect(items.nth(2)).toHaveAttribute('data-status', 'default')
  await expect(page.locator('#steps-complete li[data-status="finish"]')).toHaveCount(3)
  await expect(page.locator('#steps-complete [aria-current="step"]')).toHaveCount(0)
})

test('named and zero values update once and manual status overrides automatic progress', async ({ page }) => {
  await page.goto('/tests/fixture/')
  const cases = page.locator('#steps-cases')
  const list = cases.getByRole('list')
  const model = cases.locator('#steps-model')
  const changes = cases.locator('#steps-changes')
  const current = list.locator('[aria-current="step"]')
  const first = list.getByRole('listitem').filter({ hasText: '提交申请' })
  const last = list.getByRole('listitem').filter({ hasText: '对账' })
  await expect(current).toContainText('主管审批')
  await expect(list.getByText('需双人核对')).toBeVisible()
  await expect(first.locator('svg[data-name="edit"]')).toBeVisible()
  await expect(list.getByText('填写单据')).toBeVisible()
  await expect(last).toHaveAttribute('data-status', 'error')
  await list.getByRole('button', { name: '发货' }).click()
  await expect(model).toHaveText('ship')
  await expect(current).toContainText('发货')
  await list.getByRole('button', { name: '发货' }).dispatchEvent('click')
  await list.getByRole('button', { name: '主管审批' }).press('Space')
  await expect(current).toContainText('主管审批')
  await expect(model).toHaveText('0')
  await expect(cases.locator('#steps-updates')).toHaveText('ship,0')
  await expect(changes).toHaveText('0→ship/true,ship→0/true')
  await cases.getByLabel('步骤只读').check()
  await expect(list.getByRole('button')).toHaveCount(0)
  await list.getByText('发货').click()
  await expect(model).toHaveText('0')
  await cases.getByRole('button', { name: '完成流程' }).click()
  await expect(list.locator('li[data-status="finish"]')).toHaveCount(3)
  await expect(last).toHaveAttribute('data-status', 'error')
  await cases.getByRole('button', { name: '未匹配步骤' }).click()
  await expect(current).toHaveCount(0)
  await expect(list.locator('li[data-status="default"]')).toHaveCount(3)
  await expect(changes).toHaveText('0→ship/true,ship→0/true')
})

test('reversing the display preserves active value, numbering and workflow order', async ({ page }) => {
  await page.goto('/tests/fixture/')
  const cases = page.locator('#steps-cases')
  const list = cases.getByRole('list')
  await cases.getByLabel('步骤倒序').check()
  await expect(list.locator('.ym-steps__title')).toHaveText(['对账', '发货', '主管审批', '提交申请'])
  await expect(list.locator('[aria-current="step"] .ym-steps__marker')).toHaveText('2')
  await expect(list.getByRole('listitem').last()).toHaveAttribute('data-status', 'finish')
  await cases.getByLabel('步骤纵向').check()
  const buttons = list.getByRole('button')
  const top = await buttons.first().boundingBox()
  const next = await buttons.nth(1).boundingBox()
  expect(next!.y).toBeGreaterThan(top!.y + top!.height)
  await buttons.nth(1).click()
  await expect(cases.locator('#steps-model')).toHaveText('ship')
})

test('scoped slots receive the step, index and status and allow independent extra actions', async ({ page }) => {
  await page.goto('/tests/fixture/')
  const cases = page.locator('#steps-slots')
  const list = cases.getByRole('list')
  const first = list.getByRole('listitem').first()
  await expect(first.getByRole('button', { name: '步骤 1 · 提交申请' })).toBeVisible()
  await expect(first.getByText('标记 1')).toBeVisible()
  await expect(first.getByText('提交申请 / process')).toBeVisible()
  await expect(first.locator('svg[data-name="edit"]')).toHaveCount(0)
  await expect(list.getByText('填写单据')).toHaveCount(0)
  await expect(list.getByText('需双人核对')).toHaveCount(0)
  await list.getByRole('button', { name: '核对记录' }).click()
  await expect(cases.locator('output')).toHaveText('1')
  await expect(first).toHaveAttribute('aria-current', 'step')
  await list.getByRole('button', { name: '步骤 3 · 发货' }).click()
  await expect(first.getByText('提交申请 / finish')).toBeVisible()
})

test('step markers react to inherited size, mode, palette and radius and respect a local size', async ({ page }) => {
  await page.goto('/tests/fixture/')
  const cases = page.locator('#steps-cases')
  const marker = cases.locator('[aria-current="step"] .ym-steps__marker')
  await expect(marker).toHaveCSS('height', '40px')
  await expect(marker).toHaveCSS('border-radius', '13px')
  await expect(marker).toHaveCSS('background-color', 'rgb(35, 101, 71)')
  await expect(cases.locator('[data-status="finish"] .ym-steps__marker')).toHaveCSS('background-color', 'rgb(34, 85, 136)')
  await expect(cases.locator('[data-status="error"] .ym-steps__marker')).toHaveCSS('background-color', 'rgb(136, 51, 34)')
  await cases.getByLabel('步骤浅色主色').fill('#773355')
  await expect(marker).toHaveCSS('background-color', 'rgb(119, 51, 85)')
  await cases.getByLabel('步骤深色模式').check()
  await expect(marker).toHaveCSS('background-color', 'rgb(153, 187, 221)')
  await cases.getByLabel('步骤紧凑配置').check()
  await expect(marker).toHaveCSS('height', '24px')
  await expect(marker).toHaveCSS('border-radius', '0px')
  await cases.getByLabel('步骤局部尺寸').check()
  await expect(marker).toHaveCSS('height', '20px')
})
