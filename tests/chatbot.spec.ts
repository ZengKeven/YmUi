import { expect, test, type Page } from '@playwright/test'

const fixture = '/tests/fixture/chatbot.html'
const note = { name: '签收单.txt', mimeType: 'text/plain', buffer: Buffer.from('已签收') }
const conversation = (page: Page) => page.locator('.ym-chatbot')
const sender = (page: Page) => conversation(page).locator('.ym-chat-sender')
const replies = (page: Page) => conversation(page).locator('[data-role=assistant]')

async function submit(page: Page, text: string) {
  await sender(page).getByRole('textbox').fill(text)
  await sender(page).getByRole('button', { name: '发送消息' }).click()
}

test('text and file turns stream independently with the correct request history', async ({ page }) => {
  await page.goto(fixture)
  const rows = conversation(page).getByRole('article')
  const input = sender(page).locator('input[type=file]')
  const send = sender(page).getByRole('button', { name: '发送消息' })
  await expect(send).toBeDisabled()
  await input.setInputFiles(note)
  await submit(page, '核对送货单')
  await expect(rows).toHaveCount(2)
  await expect(rows.first()).toContainText('核对送货单')
  await expect(rows.first().getByText(note.name, { exact: true })).toBeVisible()
  await expect(rows.first().getByRole('button', { name: /移除/ })).toHaveCount(0)
  await expect(sender(page).getByRole('textbox')).toHaveValue('')
  await expect(sender(page).getByText(note.name, { exact: true })).toHaveCount(0)
  const userId = await rows.first().getAttribute('data-message-id')
  const first = page.locator('#run-1')
  const payload = await first.locator('.request').innerText()
  expect(JSON.parse(payload)).toEqual({
    prompt: '核对送货单', trigger: 'send', files: [[note.name, true]], history: [['user', userId]],
  })
  const reply = replies(page).first()
  const replyId = await reply.getAttribute('data-message-id')
  await expect(reply).toHaveAttribute('data-status', 'pending')
  await first.getByRole('button', { name: '首段' }).click()
  await expect(reply).toHaveAttribute('data-status', 'streaming')
  await expect(reply.locator('.ym-chat-markdown')).toHaveText('首段1')
  await first.getByRole('button', { name: '末段' }).click()
  await first.getByRole('button', { name: '结束请求' }).click()
  await expect(reply).toHaveAttribute('data-status', 'complete')
  await expect(reply.locator('.ym-chat-markdown')).toHaveText('首段1，末段1')
  expect(JSON.parse(await page.locator('#changes').innerText())).toEqual(expect.arrayContaining([
    ['complete', 'pending'], ['complete', 'streaming'], ['complete', 'complete'],
  ]))

  await input.setInputFiles(note)
  await send.click()
  await expect(rows).toHaveCount(4)
  const secondUserId = await rows.nth(2).getAttribute('data-message-id')
  expect(JSON.parse(await page.locator('#run-2 .request').innerText())).toEqual({
    prompt: '', trigger: 'send', files: [[note.name, true]],
    history: [['user', userId], ['assistant', replyId], ['user', secondUserId]],
  })
  await expect(first.locator('.request')).toHaveText(payload)
  await expect(reply.getByRole('button', { name: '重新生成' })).toHaveCount(0)
})

test('stop preserves partial content and an old failure cannot finish or change a regenerated reply', async ({ page }) => {
  await page.goto(fixture)
  await sender(page).locator('input[type=file]').setInputFiles(note)
  await submit(page, '收货流程')
  const reply = replies(page)
  const id = await reply.getAttribute('data-message-id')
  const first = page.locator('#run-1')
  await first.getByRole('button', { name: '首段' }).click()
  await sender(page).getByRole('textbox').fill('下一条草稿')
  await sender(page).getByRole('textbox').press('Enter')
  await page.getByRole('button', { name: '实例发送' }).click()
  await page.getByRole('button', { name: '实例重试' }).click()
  await expect(page.locator('#run-2')).toHaveCount(0)
  await sender(page).getByRole('button', { name: '停止生成' }).click()
  await expect(reply).toHaveAttribute('data-status', 'stop')
  await expect(reply).toContainText('首段1')
  await expect(conversation(page)).toContainText('已停止生成')
  await expect(page.locator('#aborted')).toHaveText('1')

  await reply.getByRole('button', { name: '重新生成' }).click()
  await expect(reply).toHaveAttribute('data-status', 'pending')
  await expect(reply).not.toContainText('首段1')
  const second = page.locator('#run-2')
  expect(JSON.parse(await second.locator('.request').innerText())).toMatchObject({
    prompt: '收货流程', trigger: 'regenerate', files: [[note.name, true]],
    history: [['user', await conversation(page).locator('[data-role=user]').getAttribute('data-message-id')]],
  })
  await second.getByRole('button', { name: '首段' }).click()
  await first.getByRole('button', { name: '末段' }).click()
  await first.getByRole('button', { name: '请求出错' }).click()
  await expect(reply).toHaveAttribute('data-status', 'streaming')
  await expect(reply.locator('.ym-chat-markdown')).toHaveText('首段2')
  await second.getByRole('button', { name: '结束请求' }).click()
  await second.getByRole('button', { name: '末段' }).click()
  await expect(reply).toHaveAttribute('data-status', 'complete')
  await expect(reply).toHaveAttribute('data-message-id', id!)
  await expect(reply.locator('.ym-chat-markdown')).toHaveText('首段2')
  await expect(conversation(page).getByRole('article')).toHaveCount(2)
  await expect(sender(page).getByRole('textbox')).toHaveValue('下一条草稿')
})

test('clear confirmation aborts the request and preserves the next draft, while cancel leaves the stream running', async ({ page }) => {
  await page.goto(fixture)
  await submit(page, '准备清空')
  await sender(page).getByRole('textbox').fill('另一张清单')
  await sender(page).locator('input[type=file]').setInputFiles(note)
  const clear = conversation(page).getByRole('button', { name: '清空历史' })
  const dialog = page.getByRole('dialog', { name: '清空历史消息？' })
  await clear.click()
  await dialog.getByRole('button', { name: '取消' }).click()
  await expect(page.locator('#aborted')).toBeEmpty()
  await expect(replies(page)).toHaveAttribute('data-status', 'pending')
  await page.locator('#run-1').getByRole('button', { name: '首段' }).click()
  await expect(replies(page)).toContainText('首段1')
  await clear.click()
  await dialog.getByRole('button', { name: '清空', exact: true }).click()
  await expect(page.locator('#aborted')).toHaveText('1')
  await expect(conversation(page).getByRole('article')).toHaveCount(0)
  await expect(sender(page).getByRole('textbox')).toHaveValue('另一张清单')
  await expect(sender(page).getByText(note.name, { exact: true })).toBeVisible()
  await sender(page).getByRole('button', { name: '发送消息' }).click()
  await page.locator('#run-1').getByRole('button', { name: '末段' }).click()
  await page.locator('#run-1').getByRole('button', { name: '结束请求' }).click()
  await expect(conversation(page).getByRole('article')).toHaveCount(2)
  await expect(replies(page)).toHaveAttribute('data-status', 'pending')
  await expect(replies(page)).not.toContainText('末段1')
  await expect(sender(page).getByRole('button', { name: '停止生成' })).toBeVisible()
})

test('the last seeded turn can be retried after an error without duplicating either message', async ({ page }) => {
  await page.goto(fixture + '?history')
  const rows = conversation(page).getByRole('article')
  await expect(rows).toHaveCount(3)
  await expect(rows.first().getByRole('button', { name: '重新生成' })).toHaveCount(0)
  const reply = conversation(page).locator('[data-message-id=past-reply]')
  await reply.getByRole('button', { name: '重新生成' }).click()
  expect(JSON.parse(await page.locator('#run-1 .request').innerText())).toEqual({
    prompt: '上次的清单', trigger: 'regenerate', files: [['原始清单.txt', false]],
    history: [['assistant', 'greeting'], ['user', 'past-user']],
  })
  await page.locator('#run-1').getByRole('button', { name: '首段' }).click()
  await page.locator('#run-1').getByRole('button', { name: '请求出错' }).click()
  await expect(reply).toHaveAttribute('data-status', 'error')
  await expect(reply.getByRole('alert')).toContainText('消息出错')
  await expect(reply).toContainText('首段1')
  await page.getByRole('button', { name: '实例重试' }).click()
  await page.locator('#run-2').getByRole('button', { name: '末段' }).click()
  await page.locator('#run-2').getByRole('button', { name: '结束请求' }).click()
  await expect(reply).toHaveAttribute('data-status', 'complete')
  await expect(reply).toContainText('末段2')
  await expect(reply).not.toContainText('首段1')
  await expect(rows).toHaveCount(3)
})

test('imperative calls and unmount cancel active work even before its first chunk', async ({ page }) => {
  await page.goto(fixture)
  const invoke = page.getByRole('button', { name: '实例发送' })
  await invoke.click()
  await expect(page.locator('#completed-sends')).toHaveText('0')
  await page.getByRole('button', { name: '实例停止' }).click()
  await expect(replies(page)).toHaveAttribute('data-status', 'stop')
  await expect(page.locator('#completed-sends')).toHaveText('1')
  await page.getByRole('button', { name: '实例重试' }).click()
  await page.getByRole('button', { name: '实例清空' }).click()
  await expect(conversation(page).getByRole('article')).toHaveCount(0)
  await invoke.click()
  await page.getByLabel('挂载会话').uncheck()
  await expect(page.locator('#aborted')).toHaveText('1,2,3')
  const changes = await page.locator('#changes').innerText()
  await page.locator('#run-3').getByRole('button', { name: '首段' }).click()
  await page.locator('#run-3').getByRole('button', { name: '结束请求' }).click()
  await expect(page.locator('#changes')).toHaveText(changes)
  await page.getByLabel('挂载会话').check()
  await expect(conversation(page).getByRole('article')).toHaveCount(0)
})

test('synchronous replies and synchronous errors settle and unlock the sender', async ({ page }) => {
  await page.goto(fixture)
  await submit(page, '同步异常')
  await expect(replies(page)).toHaveAttribute('data-status', 'error')
  await submit(page, '同步完成')
  const latest = replies(page).last()
  await expect(latest).toHaveAttribute('data-status', 'complete')
  await expect(latest.locator('strong')).toHaveText('即时回复')
  await expect(sender(page).getByRole('button', { name: '停止生成' })).toHaveCount(0)
})

test('list, sender and confirmation follow nested provider changes and the local size override', async ({ page }) => {
  await page.goto(fixture + '?history')
  const input = sender(page)
  const bubble = conversation(page).locator('.ym-chat-message__bubble').first()
  await expect(input).toHaveCSS('font-size', '16px')
  await expect(input).toHaveCSS('border-radius', '9px')
  await expect(input).toHaveCSS('background-color', 'rgb(242, 237, 223)')
  await page.getByLabel('浅色背景').fill('#ebfaec')
  await expect(input).toHaveCSS('background-color', 'rgb(235, 250, 236)')
  await page.getByLabel('紧凑尺寸').check()
  await expect(bubble).toHaveCSS('font-size', '11px')
  await page.getByLabel('局部小号').check()
  await page.getByLabel('紧凑尺寸').uncheck()
  await expect(input).toHaveCSS('font-size', '12px')
  await page.getByLabel('深色模式').check()
  await page.getByLabel('直角', { exact: true }).check()
  await expect(input).toHaveCSS('background-color', 'rgb(49, 57, 69)')
  await expect(input).toHaveCSS('border-radius', '0px')
  await conversation(page).getByRole('button', { name: '清空历史' }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toHaveCSS('background-color', 'rgb(49, 57, 69)')
  await expect(dialog).toHaveCSS('font-size', '12px')
  await expect(dialog).toHaveCSS('border-radius', '0px')
  await page.getByLabel('直角', { exact: true }).evaluate(input => (input as HTMLInputElement).click())
  await expect(dialog).toHaveCSS('border-radius', '9px')
})
