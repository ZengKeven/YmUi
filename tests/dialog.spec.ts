test('only the active child handles dialog keys and focus returns to its opener', async ({ page }) => {
  await page.goto(fixture)
  await page.getByRole('button', { name: '编辑收货单' }).click()
  const parent = page.getByRole('dialog', { name: '编辑收货单' })
  const opener = parent.getByRole('button', { name: '核对地址' })
  const child = page.getByRole('dialog', { name: '核对地址' })
  await opener.press('Enter')
  await expect(child).toContainText('确认当前地址？')
  await expect(page.locator('dialog[open]')).toHaveCount(2)
  await page.keyboard.press('Enter')
  await expect(child).toBeHidden()
  await expect(opener).toBeFocused()
  await opener.click()
  const move = child.getByRole('button', { name: '切换父框挂载点' })
  await move.click()
  await expect(page.locator('#external dialog[open]')).toContainText('编辑收货单')
  await move.click()
  await expect(child.locator('output')).toHaveText('2')
  await page.keyboard.press('Escape')
  await expect(child).toBeHidden()
  await expect(parent).toBeVisible()
  await expect(opener).toBeFocused()
  await expect(page.locator('#events')).toHaveText('child-confirm,child-esc')
})

test('a browser without atomic DOM moves relocates the parent once its child closes', async ({ page }) => {
  await page.addInitScript(() => Object.defineProperty(Element.prototype, 'moveBefore', { value: undefined, configurable: true }))
  await page.route('**/fixture-dialog-request/esc', route => route.fulfill({ json: { allow: true } }))
  await page.goto(fixture)
  const launcher = page.getByRole('button', { name: '编辑收货单' })
  await launcher.click()
  const opener = page.getByRole('button', { name: '核对地址' })
  await opener.click()
  await page.getByRole('button', { name: '切换父框挂载点' }).click()
  await expect(page.locator('#external dialog:modal')).toHaveCount(0)
  await page.keyboard.press('Escape')
  await expect(page.locator('#external dialog:modal')).toContainText('编辑收货单')
  await expect(opener).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(launcher).toBeFocused()
})

test('form confirmation and cancellation await the handler once and preserve input on failure', async ({ page }) => {
  const requests: Route[] = []
  await page.route('**/fixture-dialog-request/*', route => { requests.push(route) })
  await page.goto(fixture)
  await page.getByRole('button', { name: '编辑收货单' }).click()
  const dialog = page.getByRole('dialog', { name: '编辑收货单' })
  const recipient = dialog.getByRole('textbox', { name: '收货人' })
  const notes = dialog.getByRole('textbox', { name: '备注' })
  const events = page.locator('#events')
  await recipient.fill('新收货人')
  await recipient.dispatchEvent('keydown', { key: 'Enter', isComposing: true })
  await notes.fill('第一行')
  await notes.press('End')
  await notes.press('Enter')
  await expect(notes).toHaveValue('第一行\n')
  const category = dialog.getByRole('combobox', { name: '类别' })
  await category.press('ArrowDown')
  await category.press('Enter')
  await expect(category).toHaveValue('纸张')
  await expect(events).toBeEmpty()

  await recipient.press('Enter')
  await expect.poll(() => requests.length).toBe(1)
  expect(requests[0].request().url()).toContain('/confirm')
  await recipient.press('Enter')
  await page.keyboard.press('Escape')
  await expect(events).toHaveText('start-confirm')
  await requests[0].fulfill({ status: 503, body: '稍后重试' })
  await expect(events).toHaveText('start-confirm,error-confirm')
  await expect(dialog).toBeVisible()
  await expect(recipient).toHaveValue('新收货人')

  await dialog.getByRole('button', { name: '放弃' }).click()
  await expect.poll(() => requests.length).toBe(2)
  expect(requests[1].request().url()).toContain('/cancel')
  await expect(dialog).toBeVisible()
  await requests[1].fulfill({ json: { allow: false } })
  await expect(dialog.getByRole('button', { name: '保存' })).toBeEnabled()
  await recipient.press('Enter')
  await expect.poll(() => requests.length).toBe(3)
  await requests[2].fulfill({ json: { allow: true } })
  await expect(dialog).toBeHidden()
  await expect(events).toHaveText('start-confirm,error-confirm,start-cancel,start-confirm,confirm')
})

test('a previous save cannot close a reopened dialog and Escape runs the async cancel callback', async ({ page }) => {
  const requests: Route[] = []
  await page.route('**/fixture-dialog-request/*', route => { requests.push(route) })
  await page.goto(fixture)
  const open = page.getByRole('button', { name: '编辑收货单' })
  await open.click()
  const dialog = page.getByRole('dialog', { name: '编辑收货单' })
  await dialog.getByRole('button', { name: '保存' }).click()
  await expect.poll(() => requests.length).toBe(1)
  await dialog.getByRole('button', { name: '业务收起表单' }).click()
  await expect(dialog).toBeHidden()
  await open.click()
  await requests[0].fulfill({ json: { allow: true } })
  await expect(dialog).toBeVisible()
  await page.keyboard.press('Escape')
  await expect.poll(() => requests.length).toBe(2)
  expect(requests[1].request().url()).toContain('/esc')
  await expect(dialog).toBeVisible()
  await requests[1].fulfill({ json: { allow: true } })
  await expect(dialog).toBeHidden()
  await expect(page.locator('#events')).toHaveText('start-confirm,start-esc,esc')
  await expect(open).toBeFocused()
})

test('the attachment accepts selectors, elements and getters and keeps the live source theme', async ({ page }) => {
  for (const attach of ['node', 'getter', 'selector']) {
    await page.goto(fixture + '?attach=' + attach)
    await page.getByRole('button', { name: '打开主题框' }).click()
    await expect(page.locator('#external').getByRole('dialog', { name: '主题设置' })).toBeVisible()
  }
  const panel = page.locator('#external dialog[open]')
  const box = (await panel.boundingBox())!
  expect(box.width).toBeCloseTo(420, 0)
  expect(box.y).toBeCloseTo(60, 0)
  await expect(panel).toHaveCSS('border-radius', '9px')
  await expect(panel).toHaveCSS('background-color', 'rgb(225, 232, 239)')
  await expect(panel).toHaveCSS('color', 'rgb(18, 52, 86)')
  await panel.getByLabel('浅色背景').fill('#e5f4cf')
  await expect(panel).toHaveCSS('background-color', 'rgb(229, 244, 207)')
  await panel.getByLabel('深色').check()
  await panel.getByLabel('直角').check()
  await expect(panel).toHaveCSS('background-color', 'rgb(34, 51, 68)')
  await expect(panel).toHaveCSS('color', 'rgb(217, 231, 240)')
  await expect(panel).toHaveCSS('border-radius', '0px')
  for (const [size, font] of [['extra-small', '11px'], ['small', '12px'], ['medium', '14px'], ['large', '16px']]) {
    await panel.getByLabel('全局尺寸').selectOption(size)
    await expect(panel).toHaveCSS('font-size', font)
  }
  await panel.getByLabel('组件使用中号').check()
  await expect(panel).toHaveCSS('font-size', '14px')
})
