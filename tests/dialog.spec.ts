import { expect, test, type Route } from '@playwright/test'

const fixture = '/tests/fixture/dialog.html'

test('a confirmation dialog is centered, handles Enter, Escape and the optional backdrop', async ({ page }) => {
  await page.goto(fixture)
  const open = page.getByRole('button', { name: '打开确认框' })
  const dialog = page.getByRole('dialog', { name: '确认收货' })
  const events = page.locator('#events')
  await open.click()
  await expect(dialog).toContainText('是否将货品入库？')
  const box = (await dialog.boundingBox())!
  const viewport = page.viewportSize()!
  expect(box.x + box.width / 2).toBeCloseTo(viewport.width / 2, 0)
  expect(box.y + box.height / 2).toBeCloseTo(viewport.height / 2, 0)
  await page.mouse.click(4, 4)
  await expect(dialog).toBeVisible()
  await page.keyboard.press('Enter')
  await expect(dialog).toBeHidden()
  await expect(events).toHaveText('confirm')
  await expect(open).toBeFocused()

  await open.click()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(events).toHaveText('confirm,esc')
  await page.getByLabel('允许关闭').uncheck()
  await open.click()
  await expect(dialog.getByRole('button', { name: '取消' })).toBeVisible()
  await page.keyboard.press('Enter')
  await expect(dialog).toBeHidden()
  await expect(events).toHaveText('confirm,esc,confirm')
  await page.getByLabel('允许确认').uncheck()
  await page.getByLabel('点击遮罩关闭').check()
  await open.click()
  await expect(dialog.getByRole('button', { name: '关闭对话框' })).toHaveCount(0)
  await expect(dialog.getByRole('button', { name: '确定' })).toHaveCount(0)
  await page.keyboard.press('Escape')
  await expect(dialog).toBeVisible()
  await page.mouse.click(4, 4)
  await expect(dialog).toBeHidden()
  await expect(events).toHaveText('confirm,esc,confirm,overlay')
})

