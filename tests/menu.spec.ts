import { expect, test } from '@playwright/test'

test('expanded navigation mixes links, leaf buttons and inline groups', async ({ page }) => {
  await page.goto('/tests/fixture/')
  const menu = page.locator('#menu-cases nav')
  const group = menu.getByRole('button', { name: '仓储作业' })
  const child = menu.getByRole('button', { name: '入库登记' })
  await expect(menu.getByRole('button', { name: '营运总览' })).toHaveAttribute('aria-current', 'page')
  await expect(group.locator('svg[data-name="warehouse"]')).toBeVisible()
  await expect(child).toBeHidden()
  await group.click()
  await expect(group).toHaveAttribute('aria-expanded', 'true')
  await expect(group).toHaveAttribute('aria-controls', (await menu.locator('.ym-menu__inline').getAttribute('id'))!)
  await expect(page.locator('#menu-expanded')).toHaveText('warehouse')
  await expect(page.locator('#menu-changes')).toBeEmpty()
  await expect(child.locator('svg[data-name="inventory"]')).toBeVisible()
  await child.click()
  await expect(page.locator('#menu-selection')).toHaveText('0')
  await expect(child).toHaveAttribute('aria-current', 'page')
  await menu.getByRole('link', { name: '出库记录' }).click()
  await expect(page).toHaveURL(/#outbound-records$/)
  await group.click()
  await expect(child).toBeHidden()
  await expect(page.locator('#menu-expanded')).toBeEmpty()
  await menu.getByRole('link', { name: '营运报表' }).click()
  await expect(page).toHaveURL(/#menu-reports$/)
  await expect(page.locator('#menu-changes')).toHaveText('0,outbound,reports')
})

test('a collapsed group opens beyond the layout sidebar and allows pointer selection', async ({ page }) => {
  await page.goto('/tests/fixture/')
  const cases = page.locator('#menu-cases')
  const menu = cases.locator('nav')
  await cases.getByRole('button', { name: '收起侧栏' }).click()
  const overview = menu.getByRole('button', { name: '营运总览' })
  const group = menu.getByRole('button', { name: '仓储作业' })
  const popup = menu.locator('.ym-menu__popup:popover-open')
  await expect(overview.locator('svg[data-name="dashboard"]')).toBeVisible()
  await expect(overview.getByText('营运总览', { exact: true })).toBeHidden()
  await overview.hover()
  await expect(popup).toHaveText('营运总览')
  await group.hover()
  await expect(popup.getByText('仓储作业', { exact: true })).toBeVisible()
  await expect(group).toHaveAttribute('aria-controls', (await popup.getAttribute('id'))!)
  const link = popup.getByRole('link', { name: '出库记录' })
  const sidebar = (await cases.locator('aside').boundingBox())!
  const item = (await link.boundingBox())!
  expect(item.x + item.width / 2).toBeGreaterThan(sidebar.x + sidebar.width)
  await link.hover()
  await link.click()
  await expect(page).toHaveURL(/#outbound-records$/)
  await expect(page.locator('#menu-changes')).toHaveText('outbound')
})

test('keyboard focus opens the flyout and Escape returns to the group', async ({ page }) => {
  await page.goto('/tests/fixture/')
  const cases = page.locator('#menu-cases')
  await cases.getByRole('button', { name: '收起侧栏' }).click()
  const group = cases.getByRole('button', { name: '仓储作业' })
  const child = cases.getByRole('button', { name: '入库登记' })
  await group.focus()
  await expect(group).toHaveAttribute('aria-expanded', 'true')
  await group.press('Tab')
  await expect(child).toBeFocused()
  await child.press('Escape')
  await expect(child).toBeHidden()
  await expect(group).toBeFocused()
  await expect(group).toHaveAttribute('aria-expanded', 'false')
  await group.press('Enter')
  await group.press('Tab')
  await expect(child).toBeFocused()
  await child.press('Enter')
  await expect(page.locator('#menu-selection')).toHaveText('0')
  await expect(child).toBeHidden()
  await expect(group).toBeFocused()
})

test('menu rows and flyouts inherit nested provider settings and respect local size', async ({ page }) => {
  await page.goto('/tests/fixture/')
  const cases = page.locator('#menu-cases')
  const current = cases.getByRole('button', { name: '营运总览' })
  const group = cases.getByRole('button', { name: '仓储作业' })
  const popup = cases.locator('.ym-menu__popup:popover-open')
  await expect(current).toHaveCSS('height', '40px')
  await expect(current).toHaveCSS('border-radius', '13px')
  await expect(current).toHaveCSS('background-color', 'rgb(35, 101, 71)')
  await cases.getByLabel('菜单浅色主色').fill('#773355')
  await expect(current).toHaveCSS('background-color', 'rgb(119, 51, 85)')
  await cases.getByRole('button', { name: '收起侧栏' }).click()
  await group.hover()
  await expect(popup).toHaveCSS('background-color', 'rgb(245, 246, 247)')
  await expect(popup).toHaveCSS('border-radius', '13px')
  await cases.getByLabel('菜单深色模式').check()
  await cases.getByLabel('菜单紧凑配置').check()
  await expect(current).toHaveCSS('height', '24px')
  await expect(current).toHaveCSS('background-color', 'rgb(153, 187, 221)')
  await group.hover()
  await expect(popup).toHaveCSS('background-color', 'rgb(32, 36, 46)')
  await expect(popup).toHaveCSS('border-radius', '0px')
  const child = popup.getByRole('button', { name: '入库登记' })
  await expect(child).toHaveCSS('height', '24px')
  await cases.getByLabel('菜单局部尺寸').check()
  await expect(current).toHaveCSS('height', '20px')
  await group.hover()
  await expect(child).toHaveCSS('height', '20px')
})
