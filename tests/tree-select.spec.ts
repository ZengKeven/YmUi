import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.goto('/tests/fixture/')
})

test('each level can be disabled without blocking expansion or selecting its descendants', async ({ page }) => {
  const field = page.getByRole('combobox', { name: '区域多选' })
  const tree = page.getByRole('tree')
  const east = tree.getByRole('treeitem', { name: '华东大区', exact: true })
  const shanghai = tree.getByRole('treeitem', { name: '上海配送中心', exact: true })
  await field.click()
  await expect(tree).toHaveAttribute('aria-multiselectable', 'true')
  await expect(east).toBeDisabled()
  await expect(shanghai).toBeHidden()
  await tree.getByRole('button', { name: '展开 华东大区' }).click()
  await expect(shanghai).toBeDisabled()
  await tree.getByRole('button', { name: '展开 上海配送中心' }).click()
  const paused = tree.getByRole('treeitem', { name: '停用仓' })
  await expect(paused).toBeDisabled()
  await paused.click({ force: true })
  const hongqiao = tree.getByRole('treeitem', { name: '虹桥仓' })
  await expect(hongqiao).toHaveAttribute('aria-level', '3')
  const checkbox = hongqiao.getByRole('checkbox', { name: '虹桥仓' })
  await checkbox.click()
  await expect(checkbox).toBeChecked()
  await expect(page.locator('#tree-changes')).toHaveText('[[0]]')
  await tree.getByRole('treeitem', { name: '浦东仓' }).click()
  await expect(page.locator('#tree-many')).toHaveText('[0,"0"]')
  await expect(page.locator('#tree-changes')).toHaveText('[[0],[0,"0"]]')
  await expect(east).toHaveAttribute('aria-selected', 'false')
  await expect(shanghai).toHaveAttribute('aria-selected', 'false')
  await page.locator('.ym-tree-select__control').filter({ has: field }).getByRole('button', { name: '移除 虹桥仓' }).click()
  await expect(page.locator('#tree-many')).toHaveText('["0"]')
  await expect(tree).toBeVisible()
  await shanghai.getByText('上海配送中心', { exact: true }).click({ force: true })
  await east.getByText('华东大区', { exact: true }).click({ force: true })
  await expect(page.locator('#tree-changes')).toHaveText('[[0],[0,"0"],["0"]]')

  await page.getByRole('button', { name: '仅禁选第二级' }).click()
  await field.click()
  await expect(east).toBeEnabled()
  await east.getByText('华东大区', { exact: true }).click()
  await expect(page.locator('#tree-many')).toHaveText('["0","east"]')
  await page.getByRole('button', { name: '允许各层级选择' }).click()
  await field.click()
  const south = tree.getByRole('treeitem', { name: '华南大区', exact: true })
  await expect(south).toBeDisabled()
  await tree.getByRole('button', { name: '展开 华南大区' }).click()
  await tree.getByRole('treeitem', { name: '广州仓' }).click()
  await expect(page.locator('#tree-many')).toHaveText('["0","east","guangzhou"]')
})

test('filtering reveals matches with their ancestors and restores the prior expansion', async ({ page }) => {
  const field = page.getByRole('combobox', { name: '区域多选' })
  const tree = page.getByRole('tree')
  await field.click()
  await tree.getByRole('button', { name: '展开 华东大区' }).click()
  await field.fill('虹桥')
  await expect(page.locator('#tree-searches')).toHaveText('["虹桥"]')
  await expect(tree.getByRole('treeitem')).toHaveCount(3)
  await expect(tree.getByRole('treeitem', { name: '华东大区', exact: true })).toBeDisabled()
  await tree.getByRole('treeitem', { name: '虹桥仓' }).click()
  await expect(page.locator('#tree-many')).toHaveText('[0]')
  await field.fill('找不到的区域')
  await expect(tree.getByRole('treeitem')).toHaveCount(0)
  await field.fill('')
  await expect(tree.getByRole('treeitem', { name: '华东大区', exact: true })).toHaveAttribute('aria-expanded', 'true')
  await expect(tree.getByRole('treeitem', { name: '上海配送中心', exact: true })).toHaveAttribute('aria-expanded', 'false')
  await expect(tree.getByRole('treeitem', { name: '虹桥仓' })).toBeHidden()
  await expect(page.locator('.ym-tree-select__control').filter({ has: field }).getByRole('button', { name: '移除 虹桥仓' })).toBeVisible()
})

test('keyboard navigation expands and traverses the tree and single selection follows its owner', async ({ page }) => {
  const field = page.getByRole('combobox', { name: '键盘选仓' })
  const tree = page.getByRole('tree')
  await field.press('ArrowDown')
  await expect(field).toHaveAttribute('aria-haspopup', 'tree')
  const root = tree.getByRole('treeitem', { name: '华东大区', exact: true })
  await field.press('ArrowRight')
  await expect(root).toHaveAttribute('aria-expanded', 'true')
  await field.press('ArrowDown')
  await field.press('ArrowRight')
  const branch = tree.getByRole('treeitem', { name: '上海配送中心', exact: true })
  await expect(branch).toHaveAttribute('aria-expanded', 'true')
  await field.press('ArrowLeft')
  await expect(branch).toHaveAttribute('aria-expanded', 'false')
  await field.press('ArrowRight')
  await field.press('ArrowDown')
  const id = await tree.getByRole('treeitem', { name: '虹桥仓' }).getAttribute('id')
  await expect(field).toHaveAttribute('aria-activedescendant', id!)
  await field.press('Enter')
  await expect(field).toHaveValue('虹桥仓')
  await expect(tree).toBeHidden()
  const locked = page.getByRole('combobox', { name: '锁定区域' })
  await locked.click()
  await tree.getByRole('button', { name: '展开 华东大区' }).click()
  await tree.getByText('上海配送中心', { exact: true }).click()
  await expect(locked).toHaveValue('华东大区')
  await locked.press('ArrowDown')
  await locked.press('Escape')
  await expect(locked).toHaveAttribute('aria-expanded', 'false')
  await expect(page.getByRole('combobox', { name: '已禁用的区域' })).toBeDisabled()
})

test('an associated form submits selected keys while filtering and restores its defaults on reset', async ({ page }) => {
  const field = page.getByRole('combobox', { name: '表单区域' })
  const values = () => page.locator('form#tree-form').evaluate(form => new FormData(form).getAll('region'))
  await field.click()
  await field.fill('虹桥')
  await expect.poll(values).toEqual(['east'])
  await page.getByRole('treeitem', { name: '虹桥仓' }).getByRole('checkbox').click()
  await expect.poll(values).toEqual(['east', '0'])
  await page.getByRole('button', { name: '重置区域表单' }).click()
  await expect.poll(values).toEqual(['east'])
  await expect(field).toHaveAttribute('aria-expanded', 'false')
})

test('tree select and open panel inherit nested size, mode, palette and radius at runtime', async ({ page }) => {
  const field = page.getByRole('combobox', { name: '继承配置的区域' })
  const control = page.locator('.ym-tree-select__control').filter({ has: field })
  const panel = page.locator('.ym-tree-select__panel:popover-open')
  await expect(control).toHaveCSS('height', '40px')
  await expect(control).toHaveCSS('border-radius', '12px')
  await field.click()
  await expect(panel).toHaveCSS('border-radius', '12px')
  await expect(panel).toHaveCSS('background-color', 'rgb(245, 240, 224)')
  await page.getByLabel('树面板浅色背景').fill('#decafe')
  await expect(control).toHaveCSS('background-color', 'rgb(222, 202, 254)')
  await page.getByLabel('树选择器深色模式').check()
  await page.getByLabel('树选择器紧凑配置').check()
  await expect(control).toHaveCSS('height', '24px')
  await expect(control).toHaveCSS('border-radius', '0px')
  await field.click()
  await expect(panel).toHaveCSS('border-radius', '0px')
  await expect(panel).toHaveCSS('background-color', 'rgb(41, 64, 89)')
  await expect(panel).toHaveCSS('color', 'rgb(204, 221, 238)')
  const local = page.getByRole('combobox', { name: '固定尺寸的区域' })
  await expect(page.locator('.ym-tree-select__control').filter({ has: local })).toHaveCSS('height', '20px')
})
