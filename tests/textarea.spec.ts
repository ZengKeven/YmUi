import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.goto('/tests/fixture/')
})

test('multiline input forwards native events and participates in an external form', async ({ page }) => {
  const notes = page.getByRole('textbox', { name: '订单备注', exact: true })
  const draft = page.getByRole('textbox', { name: '草稿', exact: true })
  const entries = () => page.locator('form#textarea-form').evaluate(form => [...new FormData(form).entries()])
  await expect(notes).toHaveValue('')
  await expect(notes).toHaveJSProperty('rows', 3)
  await expect(notes).toHaveJSProperty('required', true)
  await expect(notes).toHaveCSS('text-align', 'right')
  await page.getByRole('button', { name: '聚焦订单备注' }).click()
  await expect(notes).toBeFocused()
  await notes.press('A')
  await notes.press('Enter')
  await notes.press('B')
  await page.getByRole('button', { name: '移开备注焦点' }).click()
  await expect(notes).not.toBeFocused()
  await expect(page.locator('#textarea-events')).toHaveText('focus keydown keydown keydown blur')
  expect(await entries()).toEqual([['notes', 'A\nB'], ['draft', '初稿']])
  await page.getByRole('button', { name: '填入外部备注' }).click()
  await draft.fill('未保存的修改')
  await page.getByRole('button', { name: '重置多行文本' }).click()
  await expect(draft).toHaveValue('初稿')
  await expect(notes).toHaveValue('外部修改')
  await page.getByRole('button', { name: '切换备注只读' }).click()
  await expect(notes).not.toBeEditable()
  await page.getByRole('button', { name: '切换备注禁用' }).click()
  await expect(notes).toBeDisabled()
  expect(await entries()).toEqual([['draft', '初稿']])
})

test('composition commits once, a parent can reject edits and autofocus selects the existing value', async ({ page }) => {
  const notes = page.getByRole('textbox', { name: '订单备注', exact: true })
  await notes.focus()
  await notes.evaluate((field: HTMLTextAreaElement) => {
    field.dispatchEvent(new CompositionEvent('compositionstart', { bubbles: true }))
    field.value = 'pin'
    field.dispatchEvent(new InputEvent('input', { bubbles: true, isComposing: true, data: 'pin' }))
  })
  await expect(page.locator('#textarea-updates')).toHaveText('[]')
  await notes.evaluate((field: HTMLTextAreaElement) => {
    field.value = '拼'
    field.dispatchEvent(new CompositionEvent('compositionend', { bubbles: true, data: '拼' }))
    field.dispatchEvent(new InputEvent('input', { bubbles: true, data: '拼' }))
  })
  await expect(page.locator('#textarea-updates')).toHaveText('["拼"]')
  await expect(page.locator('#textarea-changes')).toHaveText('["拼"]')
  const rejected = page.getByLabel('已归档备注')
  await rejected.fill('新的备注')
  await expect(page.locator('#textarea-rejected')).toHaveText('新的备注')
  await expect(rejected).toHaveValue('已归档')
  await page.getByRole('button', { name: '编辑备注模板' }).click()
  const template = page.getByLabel('备注模板', { exact: true })
  await expect(template).toBeFocused()
  await page.keyboard.type('new')
  await expect(template).toHaveValue('new')
})

test('limits count UTF-16 or weighted characters and report overflow and recovery', async ({ page }) => {
  const box = page.locator('#textarea-limit')
  const field = box.getByRole('textbox', { name: '限长备注' })
  await expect(box.getByText('请填写配送要求')).toBeVisible()
  await expect(box.getByText('默认提示')).toHaveCount(0)
  await field.fill('🍊12')
  await field.press('X')
  await expect(field).toHaveValue('🍊12')
  await expect(box.getByText(/4\s*\/\s*4/)).toBeVisible()
  await page.getByRole('button', { name: '启用加权计数' }).click()
  await field.fill('a你🍊x')
  await expect(field).toHaveValue('a你🍊')
  await expect(box.getByText(/5\s*\/\s*5/)).toBeVisible()
  await page.getByRole('button', { name: '允许备注超长' }).click()
  await field.fill('a你🍊x')
  await expect(field).toHaveValue('a你🍊x')
  await expect(box.getByText(/6\s*\/\s*5/)).toBeVisible()
  await expect(field).toHaveCSS('border-top-color', 'rgb(229, 69, 69)')
  await field.fill('你')
  await expect(page.locator('#textarea-validations')).toHaveText('exceed-maximum ok')
})

test('autosize follows wrapped lines, stops at maxRows, and shrinks when text is removed', async ({ page }) => {
  const field = page.getByLabel('自适应备注')
  const height = () => field.evaluate(el => el.clientHeight)
  const minimum = await height()
  await field.fill('第一行\n第二行\n第三行\n第四行')
  await expect.poll(height).toBeGreaterThan(minimum)
  const maximum = await height()
  await field.fill('窄列自动换行。'.repeat(40))
  await expect.poll(height).toBe(maximum)
  await expect.poll(() => field.evaluate(el => el.scrollHeight - el.clientHeight)).toBeGreaterThan(0)
  await field.fill('短句')
  await expect.poll(height).toBe(minimum)
  await page.getByRole('button', { name: '解除行数上限' }).click()
  await field.fill('第一行\n第二行\n第三行\n第四行\n第五行\n第六行')
  await expect.poll(height).toBeGreaterThan(maximum)
})

test('nested providers update size, mode, palette and radius while local size wins', async ({ page }) => {
  const field = page.getByLabel('继承主题的备注')
  const local = page.getByLabel('局部尺寸的备注')
  await expect(field).toHaveCSS('font-size', '16px')
  await expect(local).toHaveCSS('font-size', '12px')
  await expect(field).toHaveCSS('border-radius', '9px')
  await field.focus()
  await expect(field).toHaveCSS('border-top-color', 'rgb(38, 83, 39)')
  await page.getByLabel('备注浅色主色').fill('#573388')
  await field.focus()
  await expect(field).toHaveCSS('border-top-color', 'rgb(87, 51, 136)')
  await page.getByRole('button', { name: '切换备注深浅模式' }).click()
  await field.focus()
  await expect(field).toHaveCSS('background-color', 'rgb(32, 40, 48)')
  await expect(field).toHaveCSS('border-top-color', 'rgb(136, 187, 221)')
  await expect(local).toHaveCSS('border-top-color', 'rgb(128, 171, 130)')
  await page.getByRole('button', { name: '切换备注尺寸圆角' }).click()
  await expect(field).toHaveCSS('font-size', '11px')
  await expect(local).toHaveCSS('font-size', '12px')
  await expect(local).toHaveCSS('border-radius', '0px')
})
