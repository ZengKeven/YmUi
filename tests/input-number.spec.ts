import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.goto('/tests/fixture/')
})

test('autofocus selects formatted negative values and editable zero for replacement', async ({ page }) => {
  await expect(page.getByRole('textbox', { name: '记账金额' })).not.toBeFocused()
  const field = page.getByRole('textbox', { name: '自动聚焦金额' })
  for (const [button, original] of [['打开负数编辑框', '-12.50'], ['打开零值编辑框', '0']]) {
    await page.getByRole('button', { name: button }).click()
    await expect(field).toBeFocused()
    await expect(field).toHaveValue(original)
    await expect(field).toHaveJSProperty('selectionStart', 0)
    await expect(field).toHaveJSProperty('selectionEnd', original.length)
    await page.keyboard.type('3.25')
    await page.keyboard.press('Tab')
    await expect(field).toHaveValue('3.25')
  }
})

test('a disabled number input with autofocus leaves focus on the opener', async ({ page }) => {
  await page.getByRole('button', { name: '切换金额禁用' }).click()
  const opener = page.getByRole('button', { name: '打开负数编辑框' })
  await opener.click()
  await expect(page.getByRole('textbox', { name: '自动聚焦金额' })).toBeDisabled()
  await expect(opener).toBeFocused()
})

test('zero displays as a dash, submits as zero, and can be edited without step controls', async ({ page }) => {
  const field = page.getByRole('textbox', { name: '记账金额' })
  const form = page.locator('form#amount-form')
  await expect(field).toHaveValue('-')
  await expect(field).toHaveCSS('text-align', 'right')
  await expect(field).toHaveAttribute('inputmode', 'decimal')
  await expect(field).toHaveAttribute('placeholder', '输入金额')
  await expect(page.locator('.ym-input').filter({ has: field }).getByRole('button')).toHaveCount(0)
  await expect(page.locator('#amount-model')).toHaveText('0')
  expect(await form.evaluate(el => new FormData(el).getAll('amount'))).toEqual(['0'])

  await page.getByRole('button', { name: '聚焦记账金额' }).click()
  await expect(field).toBeFocused()
  await field.press('ArrowUp')
  await field.dispatchEvent('wheel', { deltaY: -100 })
  await page.getByRole('button', { name: '移开金额焦点' }).click()
  await expect(field).not.toBeFocused()
  await expect(field).toHaveValue('-')
  await expect(page.locator('#amount-updates')).toHaveText('[]')
  await page.getByRole('button', { name: '切换金额只读' }).click()
  await expect(field).not.toBeEditable()
  expect(await form.evaluate(el => new FormData(el).getAll('amount'))).toEqual(['0'])
  await page.getByRole('button', { name: '切换金额禁用' }).click()
  await expect(field).toBeDisabled()
  expect(await form.evaluate(el => new FormData(el).getAll('amount'))).toEqual([])
})

test('edits keep partial decimals and emit numbers only when confirmed', async ({ page }) => {
  const field = page.getByRole('textbox', { name: '记账金额' })
  await field.fill('-')
  await expect(field).toHaveValue('-')
  await field.pressSequentially('1.')
  await expect(field).toHaveValue('-1.')
  await field.pressSequentially('005')
  await expect(page.locator('#amount-model')).toHaveText('0')
  await expect(page.locator('#amount-updates')).toHaveText('[]')
  await expect(page.locator('#amount-changes')).toHaveText('[]')
  await field.press('Enter')
  await expect(page.locator('#amount-model')).toHaveText('-1.01')
  await field.blur()
  await expect(field).toHaveValue('-1.01')
  await expect(page.locator('#amount-updates')).toHaveText('[-1.01]')
  await expect(page.locator('#amount-changes')).toHaveText('[-1.01]')

  await field.fill('99')
  await field.blur()
  await expect(field).toHaveValue('5.00')
  await field.fill('-99')
  await field.blur()
  await expect(field).toHaveValue('-5.00')
  await field.fill('-')
  await field.blur()
  await expect(field).toHaveValue('-5.00')
  await field.fill('')
  await field.blur()
  await expect(field).toHaveValue('')
  await expect(page.locator('#amount-model')).toHaveText('null')
  await expect(page.locator('#amount-updates')).toHaveText('[-1.01,5,-5,null]')
  await expect(page.locator('#amount-changes')).toHaveText('[-1.01,5,-5,null]')
})

test('uncontrolled values accept edits and controlled values follow their owner', async ({ page }) => {
  const uncontrolled = page.getByRole('textbox', { name: '自管数值' })
  await expect(uncontrolled).toHaveValue('12.5')
  await uncontrolled.fill('0')
  await uncontrolled.blur()
  await expect(uncontrolled).toHaveValue('-')
  await uncontrolled.fill('3.125')
  await uncontrolled.blur()
  await expect(uncontrolled).toHaveValue('3.125')
  await page.getByRole('button', { name: '重置自管数值' }).click()
  await expect(uncontrolled).toHaveValue('12.5')

  const controlled = page.getByRole('textbox', { name: '锁定数值' })
  await controlled.fill('9')
  await controlled.blur()
  await expect(controlled).toHaveValue('4')
})

test('typing over zero and submitting with Enter sends the confirmed numeric value', async ({ page }) => {
  const form = page.locator('form#amount-form')
  await form.evaluate(el => el.addEventListener('submit', () => {
    el.dataset.submitted = String(new FormData(el).get('amount'))
  }))
  const field = page.getByRole('textbox', { name: '记账金额' })
  await field.click()
  await field.pressSequentially('-2.155')
  await field.press('Enter')
  await expect(form).toHaveAttribute('data-submitted', '-2.16')
  await expect(field).toHaveValue('-2.16')
})

test('nested providers update negative text color, surface, size and radius', async ({ page }) => {
  const field = page.getByRole('textbox', { name: '继承配置的数值' })
  const box = page.locator('.ym-input').filter({ has: field })
  const local = page.locator('.ym-input').filter({ has: page.getByRole('textbox', { name: '局部尺寸的数值' }) })
  await expect(box).toHaveCSS('height', '40px')
  await expect(box).toHaveCSS('border-radius', '9px')
  await expect(field).toHaveCSS('color', 'rgb(186, 40, 71)')
  await page.getByRole('button', { name: '切换数值正负' }).click()
  await expect(field).toHaveValue('2')
  await expect(field).toHaveCSS('color', 'rgb(32, 67, 101)')
  await page.getByRole('button', { name: '切换数值正负' }).click()
  await page.getByLabel('数值负数颜色').fill('#d02a3f')
  await expect(field).toHaveCSS('color', 'rgb(208, 42, 63)')
  await page.getByRole('button', { name: '切换数值模式' }).click()
  await expect(field).toHaveCSS('color', 'rgb(248, 157, 156)')
  await expect(box).toHaveCSS('background-color', 'rgb(39, 51, 64)')
  await page.getByRole('button', { name: '切换数值尺寸和圆角' }).click()
  await expect(box).toHaveCSS('height', '20px')
  await expect(box).toHaveCSS('border-radius', '0px')
  await expect(local).toHaveCSS('height', '24px')
})
